void
SetCICPMetadata(FIBITMAP *dib, unsigned primaries, unsigned transfer, unsigned matrix, BOOL full_range) {
	if (!dib || ((primaries == CICP_UNSPECIFIED) && (transfer == CICP_UNSPECIFIED) && (matrix == CICP_UNSPECIFIED))) {
		return;
	}
	// code points are 8-bit; ISOBMFF stores them in 16 bits
	BYTE value[4] = {
		(BYTE)((primaries < 256) ? primaries : CICP_UNSPECIFIED),
		(BYTE)((transfer < 256) ? transfer : CICP_UNSPECIFIED),
		(BYTE)((matrix < 256) ? matrix : CICP_UNSPECIFIED),
		(BYTE)(full_range ? 1 : 0)
	};
	FITAG *tag = FreeImage_CreateTag();
	if (tag) {
		FreeImage_SetTagKey(tag, CICP_KEY);
		FreeImage_SetTagDescription(tag, "Color primaries, transfer characteristics, matrix coefficients, full range flag (ITU-T H.273)");
		FreeImage_SetTagType(tag, FIDT_BYTE);
		FreeImage_SetTagCount(tag, 4);
		FreeImage_SetTagLength(tag, 4);
		FreeImage_SetTagValue(tag, value);
		FreeImage_SetMetadata(FIMD_CUSTOM, dib, CICP_KEY, tag);
		FreeImage_DeleteTag(tag);
	}
}

// samples of fewer bits than the image type holds, unscaled: J2K_UNSCALED and JP2_UNSCALED loads
static bool
IsUnscaled(FIBITMAP *dib) {
	FITAG *tag = NULL;
	if (!FreeImage_GetMetadata(FIMD_CUSTOM, dib, "UnscaledBits", &tag) || !tag) {
		return false;
	}
	const BYTE *bits = (const BYTE *)FreeImage_GetTagValue(tag);
	if ((FreeImage_GetTagType(tag) != FIDT_BYTE) || (FreeImage_GetTagCount(tag) != 1) || !bits) {
		return false;
	}
	switch (FreeImage_GetImageType(dib)) {
		case FIT_BITMAP:
			return (*bits > 0) && (*bits < 8);
		case FIT_UINT16:
		case FIT_RGB16:
		case FIT_RGBA16:
			return (*bits > 0) && (*bits < 16);
		default:
			return false;
	}
}

bool
GetCICPMetadata(FIBITMAP *dib, BYTE cicp[4]) {
	FITAG *tag = NULL;
	if (!FreeImage_GetMetadata(FIMD_CUSTOM, dib, CICP_KEY, &tag) || !tag) {
		return false;
	}
	const void *value = FreeImage_GetTagValue(tag);
	if ((FreeImage_GetTagType(tag) != FIDT_BYTE) || (FreeImage_GetTagCount(tag) != 4) || !value) {
		return false;
	}
	memcpy(cicp, value, 4);
	return true;
}

static Transfer
TransferOfCode(BYTE transfer) {
	switch (transfer) {
		case 1:		// BT.709
		case 4:		// BT.470 System M, gamma 2.2
		case 5:		// BT.470 System B and G, gamma 2.8
		case 6:		// BT.601
		case 7:		// SMPTE 240M
		case 11:	// IEC 61966-2-4, xvYCC
		case 12:	// BT.1361
		case 13:	// IEC 61966-2-1, sRGB
		case 14:	// BT.2020, 10 bits
		case 15:	// BT.2020, 12 bits
		case 17:	// SMPTE ST 428-1, DCI XYZ
			return TRANSFER_DISPLAY;
		case 8:
			return TRANSFER_LINEAR;
		case 9:		// logarithmic, 100:1
		case 10:	// logarithmic, 316:1
			return TRANSFER_STEEP;
		case 16:
			return TRANSFER_PQ;
		case 18:	// ARIB STD-B67
			return TRANSFER_HLG;
		default:	// 2 unspecified, 0 and 3 reserved
			return TRANSFER_UNKNOWN;
	}
}

