#include "FreeImage.h"
#include "Utilities.h"

#define CMS_NO_REGISTER_KEYWORD 1
#include "../LibLCMS2/include/lcms2.h"

// the most pixels inspected; a larger image is sampled on a regular grid
#define SAMPLE_BUDGET (1 << 20)

// 16-bit samples that all stay below this carry at most 12 bits: JPEG 2000 and scientific
// files store 9- to 12-bit data unscaled, which looks black when shown as it is
#define LOW_RANGE_LIMIT 4096

// the ITU-T H.273 code point for "unspecified"
#define CICP_UNSPECIFIED 2

#define CICP_KEY "CICP"

namespace {

// how the samples encode light
enum Transfer {
	TRANSFER_UNKNOWN = 0,	// not described
	TRANSFER_DISPLAY,		// a display curve: sRGB, BT.709, gamma 1.8 to 2.8, L*
	TRANSFER_HLG,			// Hybrid Log-Gamma, made to be shown as it is on SDR screens too
	TRANSFER_LINEAR,		// proportional to light
	TRANSFER_STEEP,			// logarithmic, or steeper than any display curve
	TRANSFER_PQ				// SMPTE ST 2084, absolute luminance up to 10000 cd/m2
};

// the file's format, looked up only when the verdict depends on it
class SourceFormat {
public:
	SourceFormat(const char *name, const wchar_t *wide_name) : m_name(name), m_wide_name(wide_name), m_fif(FIF_UNKNOWN), m_known(false) {
	}
	FREE_IMAGE_FORMAT Get() {
		if (!m_known) {
			m_known = true;
			if (m_name && *m_name) {
				m_fif = FreeImage_GetFileType(m_name, 0);
				if (m_fif == FIF_UNKNOWN) {
					m_fif = FreeImage_GetFIFFromFilename(m_name);
				}
			} else if (m_wide_name && *m_wide_name) {
				m_fif = FreeImage_GetFileTypeU(m_wide_name, 0);
				if (m_fif == FIF_UNKNOWN) {
					m_fif = FreeImage_GetFIFFromFilenameU(m_wide_name);
				}
			}
		}
		return m_fif;
	}

private:
	const char *m_name;
	const wchar_t *m_wide_name;
	FREE_IMAGE_FORMAT m_fif;
	bool m_known;
};

struct Samples16 {
	WORD brightest;		// the largest color sample
	bool widened;		// every sample is an 8-bit value widened to 16 bits
};

struct SamplesFloat {
	size_t finite;
	size_t negative;
	size_t bright;		// above white, 1.0
};

} // namespace

// ----------------------------------------------------------
//   The color description of the file: ITU-T H.273 code points
