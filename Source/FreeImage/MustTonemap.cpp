static unsigned
SampleStep(unsigned width, unsigned height) {
	const double pixels = (double)width * (double)height;
	return (pixels <= SAMPLE_BUDGET) ? 1 : (unsigned)ceil(sqrt(pixels / SAMPLE_BUDGET));
}

// colors only: the alpha of an RGBA16 image is left out
static void
Scan16(FIBITMAP *dib, unsigned step, Samples16 &samples) {
	const unsigned width = FreeImage_GetWidth(dib);
	const unsigned height = FreeImage_GetHeight(dib);
	const unsigned words = FreeImage_GetBPP(dib) / 16;
	const unsigned colors = (words == 4) ? 3 : words;
	WORD brightest = 0;
	bool widened = true;
	for (unsigned y = 0; y < height; y += step) {
		const WORD *row = (const WORD *)FreeImage_GetScanLine(dib, y);
		for (unsigned x = 0; x < width; x += step) {
			const WORD *pixel = row + (size_t)x * words;
			for (unsigned c = 0; c < colors; c++) {
				const WORD value = pixel[c];
				const unsigned low = value & 0xFF;
				if (value > brightest) {
					brightest = value;
				}
				// FreeImage widens by shifting, other tools by multiplying by 257
				if ((low != 0) && (low != (unsigned)(value >> 8))) {
					widened = false;
				}
			}
		}
	}
	samples.brightest = brightest;
	samples.widened = widened;
}

static void
ScanFloat(FIBITMAP *dib, SamplesFloat &samples) {
	const unsigned width = FreeImage_GetWidth(dib);
	const unsigned height = FreeImage_GetHeight(dib);
	const unsigned step = SampleStep(width, height);
	samples.finite = samples.negative = samples.bright = 0;
	for (unsigned y = 0; y < height; y += step) {
		const float *row = (const float *)FreeImage_GetScanLine(dib, y);
		for (unsigned x = 0; x < width; x += step) {
			const float value = row[x];
			if (!IsFiniteValue(value)) {
				continue;
			}
			samples.finite++;
			if (value < 0) {
				samples.negative++;
			} else if (value > 1) {
				samples.bright++;
			}
		}
	}
}

