static int
VerdictOf16(FIBITMAP *dib, SourceFormat &source) {
	// CMYK is converted, not tone mapped
	if (FreeImage_GetColorType(dib) == FIC_CMYK) {
		return FITM_NONE;
	}
	const Transfer transfer = TransferOf(dib);
	if (transfer == TRANSFER_PQ) {
		return FITM_PQ;
	}

	bool widened = false;
	if (FreeImage_HasPixels(dib)) {
		Samples16 samples;
		const unsigned step = SampleStep(FreeImage_GetWidth(dib), FreeImage_GetHeight(dib));
		Scan16(dib, step, samples);
		if ((step > 1) && (samples.brightest < LOW_RANGE_LIMIT)) {
			// the grid may have missed the few bright pixels
			Scan16(dib, 1, samples);
		}
		if (samples.brightest == 0) {
			return FITM_NONE;
		}
		if ((samples.brightest < LOW_RANGE_LIMIT) && !samples.widened) {
			return FITM_OPTIONAL;
		}
		widened = samples.widened;
	}

	switch (transfer) {
		case TRANSFER_LINEAR:
		case TRANSFER_STEEP:
			return FITM_OPTIONAL;
		case TRANSFER_DISPLAY:
		case TRANSFER_HLG:
			return FITM_NONE;
		default:
			break;
	}
	// LibRaw decodes camera RAW to linear samples; widened 8-bit ones are a preview
	if (!widened && (source.Get() == FIF_RAW)) {
		return FITM_OPTIONAL;
	}
	return FITM_NONE;
}

static int
VerdictOfFloat(FIBITMAP *dib, SourceFormat &source) {
	if (TransferOf(dib) == TRANSFER_PQ) {
		return FITM_PQ;
	}
	switch (source.Get()) {
		case FIF_HDR:
		case FIF_EXR:
		case FIF_PFM:
		case FIF_JXR:
		case FIF_PSD:
			// these store light
			return FITM_REQUIRED;
		default:
			break;
	}
	if (!FreeImage_HasPixels(dib)) {
		return FITM_OPTIONAL;
	}
	SamplesFloat samples;
	ScanFloat(dib, samples);
	if (samples.finite == 0) {
		return FITM_NONE;
	}
	// signed data, such as elevations: FreeImage_ConvertToStandardType() spreads it, the operators clip it
	if (samples.negative * 100 >= samples.finite) {
		return FITM_NONE;
	}
	// brighter than white in 1 sample of 10000: one hot pixel is not enough, a light in the scene is
	if (samples.bright * 10000 >= samples.finite) {
		return FITM_REQUIRED;
	}
	return FITM_OPTIONAL;
}

static int
MustTonemap(FIBITMAP *dib, SourceFormat &source) {
	if (!dib) {
		return FITM_ERROR;
	}
	if (IsUnscaled(dib)) {
		return FITM_UNSCALED;
	}
	switch (FreeImage_GetImageType(dib)) {
		case FIT_BITMAP:
			return FITM_NONE;
		case FIT_UINT16:
		case FIT_RGB16:
		case FIT_RGBA16:
			return VerdictOf16(dib, source);
		case FIT_FLOAT:
			return VerdictOfFloat(dib, source);
		case FIT_RGBF:
		case FIT_RGBAF:
			// light, which only the tone mapping operators turn into a standard bitmap
			return (TransferOf(dib) == TRANSFER_PQ) ? FITM_PQ : FITM_REQUIRED;
		case FIT_INT16:
		case FIT_UINT32:
		case FIT_INT32:
		case FIT_DOUBLE:
		case FIT_COMPLEX:
			// measurements: FreeImage_ConvertToStandardType() shows them, the operators refuse them
			return FITM_NONE;
		default:
			return FITM_ERROR;
	}
}

