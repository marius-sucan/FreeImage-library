static void
MuteLittleCMS(cmsContext, cmsUInt32Number, const char *) {
}

// the luminance that neutral black, mid grey and white get through the profile, measured as
// the exponent of the mid grey: 1 for linear light, about 2.2 for sRGB, 6.8 for PQ
static Transfer
TransferOfResponse(cmsContext context, cmsHPROFILE profile) {
	switch (cmsGetDeviceClass(profile)) {
		case cmsSigInputClass:
		case cmsSigDisplayClass:
		case cmsSigOutputClass:
		case cmsSigColorSpaceClass:
			break;
		default:
			return TRANSFER_UNKNOWN;
	}
	const cmsColorSpaceSignature space = cmsGetColorSpace(profile);
	if ((space != cmsSigRgbData) && (space != cmsSigGrayData)) {
		return TRANSFER_UNKNOWN;
	}
	const unsigned channels = (space == cmsSigRgbData) ? 3 : 1;

	cmsHPROFILE xyz = cmsCreateXYZProfileTHR(context);
	if (!xyz) {
		return TRANSFER_UNKNOWN;
	}
	cmsHTRANSFORM transform = cmsCreateTransformTHR(context, profile, (channels == 3) ? TYPE_RGB_DBL : TYPE_GRAY_DBL, xyz, TYPE_XYZ_DBL, INTENT_RELATIVE_COLORIMETRIC, cmsFLAGS_NOCACHE | cmsFLAGS_NOOPTIMIZE);
	cmsCloseProfile(xyz);
	if (!transform) {
		return TRANSFER_UNKNOWN;
	}
	static const double levels[3] = { 0, 0.5, 1 };
	double device[3 * 3];
	cmsCIEXYZ light[3];
	for (unsigned i = 0; i < 3; i++) {
		for (unsigned c = 0; c < channels; c++) {
			device[i * channels + c] = levels[i];
		}
	}
	cmsDoTransform(transform, device, light, 3);
	cmsDeleteTransform(transform);

	const double range = light[2].Y - light[0].Y;
	if (!(range > 1e-6)) {
		return TRANSFER_UNKNOWN;
	}
	const double mid = (light[1].Y - light[0].Y) / range;
	if (!(mid > 0) || !(mid < 1)) {
		return TRANSFER_UNKNOWN;
	}
	const double exponent = log(mid) / log(0.5);
	if (exponent < 0.8) {
		return TRANSFER_UNKNOWN;
	}
	if (exponent <= 1.2) {
		return TRANSFER_LINEAR;
	}
	return (exponent <= 3.2) ? TRANSFER_DISPLAY : TRANSFER_STEEP;
}

static Transfer
TransferOfProfile(const void *data, DWORD size) {
	Transfer transfer = TRANSFER_UNKNOWN;
	cmsContext context = cmsCreateContext(NULL, NULL);
	if (!context) {
		return transfer;
	}
	cmsSetLogErrorHandlerTHR(context, MuteLittleCMS);
	cmsHPROFILE profile = cmsOpenProfileFromMemTHR(context, data, size);
	if (profile) {
		const cmsVideoSignalType *cicp = (const cmsVideoSignalType *)cmsReadTag(profile, cmsSigcicpTag);
		if (cicp) {
			transfer = TransferOfCode(cicp->TransferCharacteristics);
		}
		if (transfer == TRANSFER_UNKNOWN) {
			transfer = TransferOfResponse(context, profile);
		}
		cmsCloseProfile(profile);
	}
	cmsDeleteContext(context);
	return transfer;
}

// the file's code points first, which PNG ranks above iCCP; then the ICC profile
static Transfer
TransferOf(FIBITMAP *dib) {
	BYTE cicp[4];
	if (GetCICPMetadata(dib, cicp)) {
		const Transfer transfer = TransferOfCode(cicp[1]);
		if (transfer != TRANSFER_UNKNOWN) {
			return transfer;
		}
	}
	const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	if (icc && icc->data && (icc->size >= 132) && ((icc->flags & FIICC_COLOR_IS_CMYK) == 0)) {
		return TransferOfProfile(icc->data, (DWORD)icc->size);
	}
	return TRANSFER_UNKNOWN;
}

