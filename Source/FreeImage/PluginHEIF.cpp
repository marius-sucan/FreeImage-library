static heif_compression_format
SampleEntryFormat(uint32_t type) {
	switch(type) {
		case FI_HEIF_FOURCC('h','v','c','1'):
		case FI_HEIF_FOURCC('h','e','v','1'):
			return heif_compression_HEVC;
		case FI_HEIF_FOURCC('a','v','c','1'):
		case FI_HEIF_FOURCC('a','v','c','3'):
			return heif_compression_AVC;
		case FI_HEIF_FOURCC('a','v','0','1'):
			return heif_compression_AV1;
		case FI_HEIF_FOURCC('v','v','c','1'):
		case FI_HEIF_FOURCC('v','v','i','1'):
			return heif_compression_VVC;
		case FI_HEIF_FOURCC('m','j','p','g'):
			return heif_compression_JPEG;
		case FI_HEIF_FOURCC('j','2','k','i'):
			return heif_compression_JPEG2000;
		case FI_HEIF_FOURCC('u','n','c','v'):
			return heif_compression_uncompressed;
	}
	return heif_compression_undefined;
}

/** first 'pict' track that is not a thumbnail, else 'vide'; 0 if none */
static uint32_t
ChooseTrack(const heif_context *hctx) {
	const int count = heif_context_number_of_sequence_tracks(hctx);
	if(count <= 0) {
		return 0;
	}
	// heif_context_get_track_ids() writes exactly 'count' IDs
	uint32_t *ids = (uint32_t*)calloc((size_t)count, sizeof(uint32_t));
	if(!ids) {
		return 0;
	}
	heif_context_get_track_ids(hctx, ids);
	uint32_t best = 0;
	int best_rank = 2;
	for(int i = 0; i < count; i++) {
		heif_track *track = heif_context_get_track(hctx, ids[i]);
		if(!track) {
			continue;
		}
		const uint32_t handler = heif_track_get_track_handler_type(track);
		const int rank = (handler == heif_track_type_image_sequence) ? 0 : ((handler == heif_track_type_video) ? 1 : 2);
		if((rank < best_rank) && (heif_track_get_number_of_track_reference_of_type(track, heif_track_reference_type_thumbnails) == 0)) {
			best = ids[i];
			best_rank = rank;
		}
		heif_track_release(track);
	}
	free(ids);
	return best;
}

static void
ReorderDurations(HEIFStream *s, const HEIFBox *stbl, HEIFSequence *seq) {
	HEIFBox box;
	size_t size = 0;
	if(!FindBox(s, stbl->payload, stbl->end, FI_HEIF_FOURCC('c','t','t','s'), &box)) {
		return;
	}
	BYTE *ctts = ReadPayload(s, &box, 8 + 8 * (size_t)FI_HEIF_MAX_FRAMES, &size);
	if(!ctts) {
		return;
	}
	const uint32_t n = (uint32_t)seq->frames;
	int64_t *composition = NULL;
	uint32_t *order = NULL;
	uint32_t *durations = NULL;
	const uint32_t entries = (size >= 8) ? GetBE32(ctts + 4) : 0;
	uint64_t total = 0;
	if((size >= 8) && (entries <= (size - 8) / 8)) {
		for(uint32_t i = 0; i < entries; i++) {
			total += GetBE32(ctts + 8 + 8 * (size_t)i);
		}
	}
	// offsets must cover the samples exactly
	if((total == n) && (n > 1)) {
		composition = (int64_t*)malloc(n * sizeof(int64_t));
		order = (uint32_t*)malloc(n * sizeof(uint32_t));
	}
	if(composition && order) {
		BOOL reordered = FALSE;
		int32_t first = 0;
		uint64_t decoding = 0;
		uint32_t k = 0;
		for(uint32_t i = 0; i < entries; i++) {
			const uint32_t count = GetBE32(ctts + 8 + 8 * (size_t)i);
			// v0 unsigned, v1 signed: they agree on sane offsets
			int32_t offset = (int32_t)GetBE32(ctts + 12 + 8 * (size_t)i);
			if(offset == INT32_MIN) {
				offset = 0;
			}
			for(uint32_t c = 0; c < count; c++, k++) {
				if(k == 0) {
					first = offset;
				} else if(offset != first) {
					reordered = TRUE;
				}
				composition[k] = (int64_t)decoding + offset;
				decoding += seq->durations[k];
				order[k] = k;
			}
		}
		if(reordered) {
			const int64_t *ct = composition;
			std::stable_sort(order, order + n, [ct](uint32_t a, uint32_t b) { return ct[a] < ct[b]; });
			durations = (uint32_t*)malloc(n * sizeof(uint32_t));
			if(durations) {
				for(uint32_t i = 0; i + 1 < n; i++) {
					const int64_t d = ct[order[i + 1]] - ct[order[i]];
					durations[i] = (d > (int64_t)UINT32_MAX) ? UINT32_MAX : (uint32_t)d;
				}
				durations[n - 1] = seq->durations[order[n - 1]];
				free(seq->durations);
				seq->durations = durations;
			}
		}
	}
	free(order);
	free(composition);
	free(ctts);
}

/** durations and the frame count, from 'stts' */
static BOOL
ReadDurations(HEIFStream *s, const HEIFBox *stbl, HEIFSequence *seq) {
	HEIFBox box;
	size_t size = 0;
	if(!FindBox(s, stbl->payload, stbl->end, FI_HEIF_FOURCC('s','t','t','s'), &box)) {
		return FALSE;
	}
	BYTE *stts = ReadPayload(s, &box, 8 + 8 * (size_t)FI_HEIF_MAX_FRAMES, &size);
	if(!stts) {
		return FALSE;
	}
	BOOL bResult = FALSE;
	const uint32_t entries = (size >= 8) ? GetBE32(stts + 4) : 0;
	if((size >= 8) && (entries <= (size - 8) / 8)) {
		uint64_t total = 0;
		for(uint32_t i = 0; i < entries; i++) {
			total += GetBE32(stts + 8 + 8 * (size_t)i);
		}
		if((total > 0) && (total <= FI_HEIF_MAX_FRAMES)) {
			seq->durations = (uint32_t*)malloc((size_t)total * sizeof(uint32_t));
			if(seq->durations) {
				uint32_t k = 0;
				for(uint32_t i = 0; i < entries; i++) {
					const uint32_t count = GetBE32(stts + 8 + 8 * (size_t)i);
					const uint32_t delta = GetBE32(stts + 12 + 8 * (size_t)i);
					for(uint32_t c = 0; c < count; c++) {
						seq->durations[k++] = delta;
					}
				}
				seq->frames = (int)total;
				bResult = TRUE;
			}
		}
	}
	free(stts);
	if(bResult) {
		ReorderDurations(s, stbl, seq);
	}
	return bResult;
}

/** 'hvcC' depth/chroma and 'colr' ICC: libheif skips these for tracks */
static void
ReadSampleEntry(HEIFStream *s, const HEIFBox *stbl, HEIFSequence *seq) {
	HEIFBox stsd, entry, child;
	if(!FindBox(s, stbl->payload, stbl->end, FI_HEIF_FOURCC('s','t','s','d'), &stsd)) {
		return;
	}
	// after the full box header and the entry count
	if(!ReadBox(s, stsd.payload + 8, stsd.end, &entry)) {
		return;
	}
	// VisualSampleEntry: 78 bytes of fields first (14496-12, 12.1.3)
	if(entry.end - entry.payload < 78) {
		return;
	}
	const BOOL hevc = (SampleEntryFormat(entry.type) == heif_compression_HEVC) ? TRUE : FALSE;
	uint64_t offset = entry.payload + 78;
	for(int n = 0; (n < FI_HEIF_MAX_BOXES) && ReadBox(s, offset, entry.end, &child); n++) {
		if(hevc && (child.type == FI_HEIF_FOURCC('h','v','c','C')) && (child.end - child.payload >= 18)) {
			// hvcC (14496-15 8.3.3.1): chroma = byte16 & 3, depth - 8 = byte17 & 7
			BYTE hvcc[18];
			if(ReadAt(s, child.payload, hvcc, sizeof(hvcc))) {
				seq->mono = ((hvcc[16] & 3) == 0) ? TRUE : FALSE;
				seq->bits = (hvcc[17] & 7) + 8;
			}
		} else if((child.type == FI_HEIF_FOURCC('c','o','l','r')) && !seq->icc && (child.end - child.payload > 4)) {
			BYTE type[4];
			if(ReadAt(s, child.payload, type, 4) &&
			   ((GetBE32(type) == FI_HEIF_FOURCC('p','r','o','f')) || (GetBE32(type) == FI_HEIF_FOURCC('r','I','C','C')))) {
				const uint64_t length = child.end - child.payload - 4;
				if(length <= (uint64_t)FI_HEIF_MAX_ICC) {
					seq->icc = (BYTE*)malloc((size_t)length);
					if(seq->icc && ReadAt(s, child.payload + 4, seq->icc, (size_t)length)) {
						seq->icc_size = (size_t)length;
					} else {
						free(seq->icc);
						seq->icc = NULL;
					}
				}
			}
		}
		offset = child.end;
	}
}

static BOOL
ReadTrackBoxes(HEIFStream *s, HEIFSequence *seq) {
	HEIFBox moov, trak, box, mdia, minf, stbl;
	if(!FindBox(s, 0, StreamEnd(s), FI_HEIF_FOURCC('m','o','o','v'), &moov)) {
		return FALSE;
	}
	uint64_t offset = moov.payload;
	for(int n = 0; (n < FI_HEIF_MAX_BOXES) && ReadBox(s, offset, moov.end, &trak); n++) {
		offset = trak.end;
		if(trak.type != FI_HEIF_FOURCC('t','r','a','k')) {
			continue;
		}
		// tkhd: track ID after two 32-bit (v0) or 64-bit (v1) times
		BYTE tkhd[24];
		if(!FindBox(s, trak.payload, trak.end, FI_HEIF_FOURCC('t','k','h','d'), &box) ||
		   (box.end - box.payload < sizeof(tkhd)) || !ReadAt(s, box.payload, tkhd, sizeof(tkhd))) {
			continue;
		}
		if(GetBE32(tkhd + ((tkhd[0] == 1) ? 20 : 12)) != seq->track_id) {
			continue;
		}
		if(!FindBox(s, trak.payload, trak.end, FI_HEIF_FOURCC('m','d','i','a'), &mdia) ||
		   !FindBox(s, mdia.payload, mdia.end, FI_HEIF_FOURCC('m','i','n','f'), &minf) ||
		   !FindBox(s, minf.payload, minf.end, FI_HEIF_FOURCC('s','t','b','l'), &stbl)) {
			return FALSE;
		}
		if(!ReadDurations(s, &stbl, seq)) {
			return FALSE;
		}
		ReadSampleEntry(s, &stbl, seq);
		return TRUE;
	}
	return FALSE;
}

static void
FreeSequence(HEIFSequence *seq) {
	if(seq->track) {
		heif_track_release(seq->track);
	}
	if(seq->image) {
		heif_image_release(seq->image);
	}
	free(seq->durations);
	free(seq->icc);
	memset(seq, 0, sizeof(HEIFSequence));
	seq->image_page = -1;
}

static BOOL
OpenSequence(HEIFContext *ctx, BOOL *decodable) {
	HEIFSequence *seq = &ctx->seq;
	*decodable = FALSE;
	if(!heif_context_has_sequence(ctx->ctx)) {
		return FALSE;
	}
	seq->track_id = ChooseTrack(ctx->ctx);
	if(seq->track_id == 0) {
		return FALSE;
	}
	heif_track *track = heif_context_get_track(ctx->ctx, seq->track_id);
	if(!track) {
		return FALSE;
	}
	uint16_t width = 0;
	uint16_t height = 0;
	const BOOL visual = (heif_track_get_image_resolution(track, &width, &height).code == heif_error_Ok) ? TRUE : FALSE;
	seq->width = width;
	seq->height = height;
	seq->has_alpha = heif_track_has_alpha_channel(track) ? TRUE : FALSE;
	seq->timescale = heif_track_get_timescale(track);
	// edit list repeats: 1 = none, UINT32_MAX = forever, 0 = play once
	const uint32_t repetitions = heif_track_get_number_of_repetitions(track);
	if((repetitions == heif_sequence_track_number_of_repetitions_infinite) || (repetitions > 0x7FFFFFFF)) {
		seq->loop = 0;
	} else if(repetitions == 0) {
		seq->loop = 1;
	} else {
		seq->loop = (LONG)repetitions;
	}
	const heif_compression_format format = SampleEntryFormat(heif_track_get_sample_entry_type_of_first_cluster(track));
	*decodable = ((format != heif_compression_undefined) && heif_have_decoder_for_format(format)) ? TRUE : FALSE;
	heif_track_release(track);

	if(!visual || (width == 0) || (height == 0)) {
		return FALSE;
	}
	return ReadTrackBoxes(&ctx->stream, seq);
}

