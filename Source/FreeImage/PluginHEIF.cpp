typedef struct tagHEIFStream {
	FreeImageIO *io;
	fi_handle handle;
	INT64 base;				//! stream offset of the first HEIF byte
	uint64_t position;		//! relative to 'base'
	BOOL size_known;
	uint64_t size;			//! bytes from 'base' to the end
	uint64_t budget;		//! read cap in bytes, 0 = none
	uint64_t spent;
	BOOL overspent;
} HEIFStream;

/** seek to base + offset */
static BOOL
HEIF_SeekTo(HEIFStream *s, uint64_t offset) {
	if(offset > (uint64_t)(INT64_MAX - s->base)) {
		return FALSE;
	}
	return (s->io->seek_proc(s->handle, s->base + (INT64)offset, SEEK_SET) == 0) ? TRUE : FALSE;
}

/** is there a byte at 'offset'? Leaves the position undefined */
static BOOL
HEIF_Probe(HEIFStream *s, uint64_t offset) {
	BYTE b;
	return (HEIF_SeekTo(s, offset) && (s->io->read_proc(&b, 1, 1, s->handle) == 1)) ? TRUE : FALSE;
}

/** the length of a stream that SEEK_END cannot tell: doubling probes, then bisection */
static void
HEIF_MeasureStream(HEIFStream *s) {
	uint64_t lo = 0;	// a byte exists at 'lo'
	uint64_t hi = 1;	// no byte exists at 'hi', once the doubling stops

	if(!HEIF_Probe(s, 0)) {
		s->size = 0;
		s->size_known = TRUE;
		return;
	}
	while(HEIF_Probe(s, hi)) {
		if(hi > ((uint64_t)INT64_MAX >> 1)) {
			return;
		}
		lo = hi;
		hi <<= 1;
	}
	while(hi - lo > 1) {
		const uint64_t mid = lo + (hi - lo) / 2;
		if(HEIF_Probe(s, mid)) {
			lo = mid;
		} else {
			hi = mid;
		}
	}
	s->size = hi;
	s->size_known = TRUE;
}

/** libheif callback: tracked position */
static int64_t
HEIF_GetPosition(void *userdata) {
	HEIFStream *s = (HEIFStream*)userdata;
	return (s->position <= (uint64_t)INT64_MAX) ? (int64_t)s->position : INT64_MAX;
}

/** libheif callback: read exactly 'size' bytes, 0 on success */
static int
HEIF_Read(void *data, size_t size, void *userdata) {
	HEIFStream *s = (HEIFStream*)userdata;
	if(s->budget) {
		if((s->spent > s->budget) || ((uint64_t)size > s->budget - s->spent)) {
			s->overspent = TRUE;
			return -1;
		}
		s->spent += size;
	}
	const size_t total = FreeImage_ReadBytes(s->io, s->handle, data, size);
	s->position += total;
	return (total == size) ? 0 : -1;
}

/** libheif callback: absolute seek, 0 on success */
static int
HEIF_Seek(int64_t position, void *userdata) {
	HEIFStream *s = (HEIFStream*)userdata;
	if(position < 0) {
		return -1;
	}
	if(!HEIF_SeekTo(s, (uint64_t)position)) {
		return -1;
	}
	s->position = (uint64_t)position;
	return 0;
}

/** libheif callback: must be exact, libheif bisects the length with it */
static heif_reader_grow_status
HEIF_WaitForFileSize(int64_t target_size, void *userdata) {
	HEIFStream *s = (HEIFStream*)userdata;
	if(target_size < 0) {
		return heif_reader_grow_status_size_beyond_eof;
	}
	if(!s->size_known) {
		// unknown length: optimistic, a read past the end fails anyway
		return heif_reader_grow_status_size_reached;
	}
	return ((uint64_t)target_size <= s->size) ? heif_reader_grow_status_size_reached : heif_reader_grow_status_size_beyond_eof;
}

static const heif_reader s_reader = {
	1,						// reader_api_version
	HEIF_GetPosition,
	HEIF_Read,
	HEIF_Seek,
	HEIF_WaitForFileSize,
	NULL,					// request_range
	NULL,					// preload_range_hint
	NULL,					// release_file_range
	NULL					// release_error_msg
};

