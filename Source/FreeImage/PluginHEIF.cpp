static LONG
FrameTimeMs(uint32_t ticks, uint32_t timescale) {
	if(timescale == 0) {
		return 0;
	}
	const uint64_t scale = timescale;
	const uint64_t ms = ((uint64_t)ticks / scale) * 1000 + (((uint64_t)ticks % scale) * 1000 + scale / 2) / scale;
	return (ms > 0x7FFFFFFF) ? (LONG)0x7FFFFFFF : (LONG)ms;
}

/** 'dib' must be the finished page: the canvas is its size */
static void
AttachAnimation(FIBITMAP *dib, const HEIFSequence *seq, int page) {
	const LONG frametime = FrameTimeMs(seq->durations[page], seq->timescale);
	const WORD left = 0;
	const WORD top = 0;
	const BYTE disposal = 1;
	const BYTE blend = 1;
	SetAnimTag(dib, "FrameTime", ANIMTAG_FRAMETIME, FIDT_LONG, 1, 4, &frametime);
	SetAnimTag(dib, "FrameLeft", ANIMTAG_FRAMELEFT, FIDT_SHORT, 1, 2, &left);
	SetAnimTag(dib, "FrameTop", ANIMTAG_FRAMETOP, FIDT_SHORT, 1, 2, &top);
	SetAnimTag(dib, "DisposalMethod", ANIMTAG_DISPOSALMETHOD, FIDT_BYTE, 1, 1, &disposal);
	SetAnimTag(dib, "BlendMethod", ANIMTAG_BLENDMETHOD, FIDT_BYTE, 1, 1, &blend);

	// canvas and loop on every frame, so deleting page 0 keeps them
	const unsigned width = FreeImage_GetWidth(dib);
	const unsigned height = FreeImage_GetHeight(dib);
	const WORD logicalwidth = (WORD)((width > 0xFFFF) ? 0xFFFF : width);
	const WORD logicalheight = (WORD)((height > 0xFFFF) ? 0xFFFF : height);
	SetAnimTag(dib, "LogicalWidth", ANIMTAG_LOGICALWIDTH, FIDT_SHORT, 1, 2, &logicalwidth);
	SetAnimTag(dib, "LogicalHeight", ANIMTAG_LOGICALHEIGHT, FIDT_SHORT, 1, 2, &logicalheight);
	SetAnimTag(dib, "Loop", ANIMTAG_LOOP, FIDT_LONG, 1, 4, &seq->loop);
}

static void
AttachFrameMetadata(FIBITMAP *dib, const HEIFSequence *seq, int page) {
	if(seq->icc && (seq->icc_size > 0)) {
		FreeImage_CreateICCProfile(dib, seq->icc, (long)seq->icc_size);
	}
	AttachAnimation(dib, seq, page);
}

static BOOL
DecodeThumbnail(const HEIFContext *ctx, FIBITMAP *dib, heif_image_handle *thumb_handle, heif_error *error) {
	BOOL bResult = FALSE;
	heif_decoding_options *options = CreateDecodingOptions(ctx, thumb_handle);
	if(!options) {
		return FALSE;
	}
	options->convert_hdr_to_8bit = 1;
	options->num_codec_threads = 1;
	heif_image *image = NULL;
	*error = heif_decode_image(thumb_handle, &image, heif_colorspace_RGB, heif_chroma_interleaved_RGB, options);
	if((error->code == heif_error_Ok) && image) {
		const int width = heif_image_get_width(image, heif_channel_interleaved);
		const int height = heif_image_get_height(image, heif_channel_interleaved);
		if((width > 0) && (height > 0)) {
			FIBITMAP *thumb = FreeImage_Allocate(width, height, 24, FI_RGBA_RED_MASK, FI_RGBA_GREEN_MASK, FI_RGBA_BLUE_MASK);
			if(thumb) {
				if(CopyInterleaved8(image, thumb, FALSE, FALSE)) {
					bResult = FreeImage_SetThumbnail(dib, thumb);
				}
				FreeImage_Unload(thumb);
			}
		}
	}
	if(image) {
		heif_image_release(image);
	}
	heif_decoding_options_free(options);
	return bResult;
}

/** first 'thmb' that decodes; a failure costs only the thumbnail */
static void
AttachThumbnail(const HEIFContext *ctx, FIBITMAP *dib, const heif_image_handle *handle) {
	heif_item_id ids[8];
	const int count = heif_image_handle_get_list_of_thumbnail_IDs(handle, ids, 8);
	if(count <= 0) {
		return;
	}
	heif_error error = heif_error_success;
	for(int i = 0; i < count; i++) {
		heif_image_handle *thumb_handle = NULL;
		error = heif_image_handle_get_thumbnail(handle, ids[i], &thumb_handle);
		if((error.code != heif_error_Ok) || !thumb_handle) {
			continue;
		}
		const BOOL ok = DecodeThumbnail(ctx, dib, thumb_handle, &error);
		heif_image_handle_release(thumb_handle);
		if(ok) {
			return;
		}
	}
	if(error.code != heif_error_Ok) {
		ReportError("Ignoring the thumbnail", error);
	}
}

