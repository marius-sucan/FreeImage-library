// for writers whose format cannot hold a page as it is
#ifndef FREEIMAGE_ANIMATION_CANVAS_H
#define FREEIMAGE_ANIMATION_CANVAS_H

// left and top inclusive, right and bottom exclusive, y counted down from the top
struct AnimRect {
	int left, top, right, bottom;

	AnimRect() : left(0), top(0), right(0), bottom(0) {
	}
	AnimRect(int l, int t, int r, int b) : left(l), top(t), right(r), bottom(b) {
	}
	BOOL IsEmpty() const {
		return ((right <= left) || (bottom <= top)) ? TRUE : FALSE;
	}
	BOOL Contains(const AnimRect& r) const {
		return (r.IsEmpty() || ((left <= r.left) && (top <= r.top) && (right >= r.right) && (bottom >= r.bottom))) ? TRUE : FALSE;
	}
	BOOL Equals(const AnimRect& r) const {
		return ((left == r.left) && (top == r.top) && (right == r.right) && (bottom == r.bottom)) ? TRUE : FALSE;
	}
	// the bounding box of both
	AnimRect Union(const AnimRect& r) const {
		if(IsEmpty()) {
			return r;
		}
		if(r.IsEmpty()) {
			return *this;
		}
		return AnimRect(MIN(left, r.left), MIN(top, r.top), MAX(right, r.right), MAX(bottom, r.bottom));
	}
	AnimRect Intersect(const AnimRect& r) const {
		AnimRect out(MAX(left, r.left), MAX(top, r.top), MIN(right, r.right), MIN(bottom, r.bottom));
		return out.IsEmpty() ? AnimRect() : out;
	}
};

// 8-bit RGBA, the background where nothing was drawn: transparent, or a colour of the format's
class AnimationCanvas {
	FIBITMAP *m_dib;
	UINT64 m_max_pixels;
	BYTE m_background[4];

	AnimationCanvas(const AnimationCanvas&);
	AnimationCanvas& operator=(const AnimationCanvas&);

	BYTE *Pixel(int x, int y) const {
		return FreeImage_GetScanLine(m_dib, FreeImage_GetHeight(m_dib) - 1 - (unsigned)y) + (size_t)x * 4;
	}

	void Fill(BYTE *p, int count) const {
		for(int i = 0; i < count; i++, p += 4) {
			memcpy(p, m_background, 4);
		}
	}

public:
	AnimationCanvas(UINT64 max_pixels) : m_dib(NULL), m_max_pixels(max_pixels) {
		memset(m_background, 0, 4);
	}
	// before the first Grow()
	void SetBackground(const RGBQUAD& colour) {
		m_background[FI_RGBA_RED] = colour.rgbRed;
		m_background[FI_RGBA_GREEN] = colour.rgbGreen;
		m_background[FI_RGBA_BLUE] = colour.rgbBlue;
		m_background[FI_RGBA_ALPHA] = colour.rgbReserved;
	}
	~AnimationCanvas() {
		if(m_dib) {
			FreeImage_Unload(m_dib);
		}
	}
	int Width() const {
		return m_dib ? (int)FreeImage_GetWidth(m_dib) : 0;
	}
	int Height() const {
		return m_dib ? (int)FreeImage_GetHeight(m_dib) : 0;
	}
	AnimRect Bounds() const {
		return AnimRect(0, 0, Width(), Height());
	}

	// at least width x height, what is drawn kept at the top left
	BOOL Grow(unsigned width, unsigned height) {
		width = MAX(width, (unsigned)Width());
		height = MAX(height, (unsigned)Height());
		if(m_dib && (width == (unsigned)Width()) && (height == (unsigned)Height())) {
			return TRUE;
		}
		if(!width || !height || ((UINT64)width * (UINT64)height > m_max_pixels)) {
			return FALSE;
		}
		FIBITMAP *grown = FreeImage_Allocate((int)width, (int)height, 32, FI_RGBA_RED_MASK, FI_RGBA_GREEN_MASK, FI_RGBA_BLUE_MASK);
		if(!grown) {
			return FALSE;
		}
		for(unsigned y = 0; y < height; y++) {
			BYTE *line = FreeImage_GetScanLine(grown, height - 1 - y);
			Fill(line, (int)width);
			if(m_dib && (y < (unsigned)Height())) {
				memcpy(line, Pixel(0, (int)y), (size_t)Width() * 4);
			}
		}
		if(m_dib) {
			FreeImage_Unload(m_dib);
		}
		m_dib = grown;
		return TRUE;
	}

	// a 32-bit page at (x, y), over what is there or in its place
	void Draw(FIBITMAP *frame, int x, int y, BOOL replace) {
		const int frame_height = (int)FreeImage_GetHeight(frame);
		const AnimRect r = AnimRect(x, y, x + (int)FreeImage_GetWidth(frame), y + frame_height).Intersect(Bounds());
		for(int row = r.top; row < r.bottom; row++) {
			const BYTE *s = FreeImage_GetScanLine(frame, (unsigned)(frame_height - 1 - (row - y))) + (size_t)(r.left - x) * 4;
			BYTE *d = Pixel(r.left, row);
			if(replace) {
				memcpy(d, s, (size_t)(r.right - r.left) * 4);
				continue;
			}
			for(int col = r.left; col < r.right; col++, s += 4, d += 4) {
				const unsigned sa = s[FI_RGBA_ALPHA];
				if(sa == 255) {
					memcpy(d, s, 4);
				} else if(sa) {
					// over, scaled by 255 and rounded
					const unsigned weight = d[FI_RGBA_ALPHA] * (255 - sa);
					const unsigned alpha = sa * 255 + weight;
					const unsigned half = alpha / 2;
					d[FI_RGBA_RED] = (BYTE)((s[FI_RGBA_RED] * sa * 255 + d[FI_RGBA_RED] * weight + half) / alpha);
					d[FI_RGBA_GREEN] = (BYTE)((s[FI_RGBA_GREEN] * sa * 255 + d[FI_RGBA_GREEN] * weight + half) / alpha);
					d[FI_RGBA_BLUE] = (BYTE)((s[FI_RGBA_BLUE] * sa * 255 + d[FI_RGBA_BLUE] * weight + half) / alpha);
					d[FI_RGBA_ALPHA] = (BYTE)((alpha + 127) / 255);
				}
			}
		}
	}

	// back to the background
	void Clear(const AnimRect& rect) {
		const AnimRect r = rect.Intersect(Bounds());
		for(int row = r.top; row < r.bottom; row++) {
			Fill(Pixel(r.left, row), r.right - r.left);
		}
	}

	// TRUE when only the background shows there
	BOOL IsClear(const AnimRect& rect) const {
		const AnimRect r = rect.Intersect(Bounds());
		for(int row = r.top; row < r.bottom; row++) {
			const BYTE *p = Pixel(r.left, row);
			for(int col = r.left; col < r.right; col++, p += 4) {
				if(m_background[FI_RGBA_ALPHA] ? (memcmp(p, m_background, 4) != 0) : (p[FI_RGBA_ALPHA] != 0)) {
					return FALSE;
				}
			}
		}
		return TRUE;
	}

	// a 32-bit copy of the rectangle, NULL when it is empty or memory runs out
	FIBITMAP *Copy(const AnimRect& rect) const {
		const AnimRect r = rect.Intersect(Bounds());
		return r.IsEmpty() ? NULL : FreeImage_Copy(m_dib, r.left, r.top, r.right, r.bottom);
	}

	// a Copy() back where it came from
	void Restore(FIBITMAP *copy, int x, int y) {
		if(copy) {
			Draw(copy, x, y, TRUE);
		}
	}
};

// a page as 8-bit RGBA, NULL for a type no conversion reaches
inline FIBITMAP *
AnimationFrame32(FIBITMAP *dib) {
	// FreeImage_ConvertTo32Bits() cannot take 16-bit grey: its high byte first
	FIBITMAP *grey = (FreeImage_GetImageType(dib) == FIT_UINT16) ? FreeImage_ConvertTo8Bits(dib) : NULL;
	FIBITMAP *source = grey ? grey : dib;
	FIBITMAP *frame = ((FreeImage_GetImageType(source) == FIT_BITMAP) && (FreeImage_GetBPP(source) == 32))
		? FreeImage_Clone(source) : FreeImage_ConvertTo32Bits(source);
	if(grey) {
		FreeImage_Unload(grey);
	}
	return frame;
}

#endif // FREEIMAGE_ANIMATION_CANVAS_H
