// SDR reference white, ITU-R BT.2408: 1.0 in the result
#define REFERENCE_WHITE 203.0

// the nominal peak of the HLG reference display, ITU-R BT.2100, and its system gamma
#define HLG_PEAK 1000.0
#define HLG_GAMMA 1.2

// images smaller than this are converted on one thread
#define LINEAR_PARALLEL_PIXELS 65536

namespace {

// the light of a signal, 1.0 being SDR reference white
typedef double (*Curve)(double signal);

enum Layout {
	IN_RGB8,		// 24-bit, after FreeImage_ConvertTo24Bits
	IN_RGBA8,		// 32-bit, after FreeImage_ConvertTo32Bits
	IN_GREY16,
	IN_RGB16,
	IN_RGBA16,
	IN_GREYF,
	IN_RGBF,
	IN_RGBAF
};

struct Plan {
	Curve curve;					// NULL: the profile's tone curves, or linear light already
	const cmsToneCurve *trc[3];		// the profile's tone curves, red, green and blue, or grey in all three
	bool hlg;						// the HLG display step, per pixel, after the curve
	double weights[3];				// the luminance the HLG step reads
	bool convert;					// the primaries matrix, after the HLG step
	double matrix[3][3];
	BYTE primaries;					// the code point of the result's primaries

	Plan() : curve(NULL), hlg(false), convert(false), primaries(2) {
		trc[0] = trc[1] = trc[2] = NULL;
		weights[0] = 0.2126; weights[1] = 0.7152; weights[2] = 0.0722;
	}
	double Apply(unsigned channel, double signal) const {
		if (trc[channel]) {
			return cmsEvalToneCurveFloat(trc[channel], (cmsFloat32Number)signal);
		}
		return curve ? curve(signal) : signal;
	}
};

struct Chromaticities {
	BYTE code;
	double red[2], green[2], blue[2], white[2];
};

} // namespace

