// ITU-T H.273 table 2; 10, the cinema's XYZ, has no primaries a matrix can be built from
static const Chromaticities *
ChromaticitiesOfCode(BYTE code) {
	static const Chromaticities table[] = {
		{ 1, { 0.640, 0.330 }, { 0.300, 0.600 }, { 0.150, 0.060 }, { 0.3127, 0.3290 } },	// BT.709, sRGB
		{ 4, { 0.670, 0.330 }, { 0.210, 0.710 }, { 0.140, 0.080 }, { 0.3100, 0.3160 } },	// BT.470 System M
		{ 5, { 0.640, 0.330 }, { 0.290, 0.600 }, { 0.150, 0.060 }, { 0.3127, 0.3290 } },	// BT.601 625 lines
		{ 6, { 0.630, 0.340 }, { 0.310, 0.595 }, { 0.155, 0.070 }, { 0.3127, 0.3290 } },	// BT.601 525 lines
		{ 7, { 0.630, 0.340 }, { 0.310, 0.595 }, { 0.155, 0.070 }, { 0.3127, 0.3290 } },	// SMPTE 240M
		{ 8, { 0.681, 0.319 }, { 0.243, 0.692 }, { 0.145, 0.049 }, { 0.3100, 0.3160 } },	// generic film
		{ 9, { 0.708, 0.292 }, { 0.170, 0.797 }, { 0.131, 0.046 }, { 0.3127, 0.3290 } },	// BT.2020, BT.2100
		{ 11, { 0.680, 0.320 }, { 0.265, 0.690 }, { 0.150, 0.060 }, { 0.3140, 0.3510 } },	// DCI-P3
		{ 12, { 0.680, 0.320 }, { 0.265, 0.690 }, { 0.150, 0.060 }, { 0.3127, 0.3290 } },	// Display P3
		{ 22, { 0.630, 0.340 }, { 0.295, 0.605 }, { 0.155, 0.077 }, { 0.3127, 0.3290 } }	// EBU Tech 3213-E
	};
	for (unsigned i = 0; i < sizeof(table) / sizeof(table[0]); i++) {
		if (table[i].code == code) {
			return &table[i];
		}
	}
	return NULL;
}

static cmsHPROFILE
LinearProfile(cmsContext context, const cmsCIExyY &white, const cmsCIExyYTRIPLE &primaries) {
	cmsToneCurve *linear = cmsBuildGamma(context, 1.0);
	if (!linear) {
		return NULL;
	}
	cmsToneCurve *curves[3] = { linear, linear, linear };
	cmsHPROFILE profile = cmsCreateRGBProfileTHR(context, &white, &primaries, curves);
	cmsFreeToneCurve(linear);
	return profile;
}

static cmsHPROFILE
LinearProfileOfCode(cmsContext context, const Chromaticities &c) {
	const cmsCIExyY white = { c.white[0], c.white[1], 1 };
	const cmsCIExyYTRIPLE primaries = { { c.red[0], c.red[1], 1 }, { c.green[0], c.green[1], 1 }, { c.blue[0], c.blue[1], 1 } };
	return LinearProfile(context, white, primaries);
}

// a matrix-shaper profile with linear tone curves: its colorants, against the PCS white
static cmsHPROFILE
LinearCopy(cmsContext context, cmsHPROFILE profile) {
	const cmsCIEXYZ *red = (const cmsCIEXYZ *)cmsReadTag(profile, cmsSigRedColorantTag);
	const cmsCIEXYZ *green = (const cmsCIEXYZ *)cmsReadTag(profile, cmsSigGreenColorantTag);
	const cmsCIEXYZ *blue = (const cmsCIEXYZ *)cmsReadTag(profile, cmsSigBlueColorantTag);
	if (!red || !green || !blue) {
		return NULL;
	}
	cmsCIExyY white;
	cmsCIExyYTRIPLE primaries;
	cmsXYZ2xyY(&white, cmsD50_XYZ());
	cmsXYZ2xyY(&primaries.Red, red);
	cmsXYZ2xyY(&primaries.Green, green);
	cmsXYZ2xyY(&primaries.Blue, blue);
	return LinearProfile(context, white, primaries);
}

// the colors of linear light in 'from' as BT.709's, white kept white: Little CMS gives the columns,
// the pixels go through the matrix, which leaves light above white unclipped
static bool
MatrixToBT709(cmsContext context, cmsHPROFILE from, double matrix[3][3]) {
	const Chromaticities *bt709 = ChromaticitiesOfCode(1);
	cmsHPROFILE to = LinearProfileOfCode(context, *bt709);
	if (!to) {
		return false;
	}
	cmsHTRANSFORM transform = cmsCreateTransformTHR(context, from, TYPE_RGB_DBL, to, TYPE_RGB_DBL, INTENT_RELATIVE_COLORIMETRIC, cmsFLAGS_NOCACHE | cmsFLAGS_NOOPTIMIZE);
	cmsCloseProfile(to);
	if (!transform) {
		return false;
	}
	const double basis[9] = { 1, 0, 0, 0, 1, 0, 0, 0, 1 };
	double columns[9];
	cmsDoTransform(transform, basis, columns, 3);
	cmsDeleteTransform(transform);
	for (unsigned row = 0; row < 3; row++) {
		for (unsigned column = 0; column < 3; column++) {
			matrix[row][column] = columns[column * 3 + row];
			if (!IsFiniteValue(matrix[row][column])) {
				return false;
			}
		}
	}
	return true;
}

