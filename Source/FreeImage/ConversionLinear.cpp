static void
ConvertRows(FIBITMAP *src, FIBITMAP *dst, Layout layout, const Plan &plan, const std::vector<float> lut[3]) {
	const int width = (int)FreeImage_GetWidth(src);
	const int height = (int)FreeImage_GetHeight(src);
	const unsigned out_step = (FreeImage_GetImageType(dst) == FIT_RGBAF) ? 4 : 3;
	const bool parallel = ((double)width * height > LINEAR_PARALLEL_PIXELS);
	const double hlg_scale = HLG_PEAK / REFERENCE_WHITE;

#pragma omp parallel for if(parallel)
	for (int y = 0; y < height; y++) {
		const BYTE *in = FreeImage_GetScanLine(src, y);
		float *out = (float *)FreeImage_GetScanLine(dst, y);
		for (int x = 0; x < width; x++) {
			double rgb[3];
			double alpha = 1;
			switch (layout) {
				case IN_RGB8:
				case IN_RGBA8: {
					const BYTE *p = in + x * ((layout == IN_RGBA8) ? 4 : 3);
					rgb[0] = lut[0][p[FI_RGBA_RED]];
					rgb[1] = lut[1][p[FI_RGBA_GREEN]];
					rgb[2] = lut[2][p[FI_RGBA_BLUE]];
					if (layout == IN_RGBA8) {
						alpha = p[FI_RGBA_ALPHA] / 255.0;
					}
					break;
				}
				case IN_GREY16:
					rgb[0] = rgb[1] = rgb[2] = lut[0][((const WORD *)in)[x]];
					break;
				case IN_RGB16:
				case IN_RGBA16: {
					const WORD *p = (const WORD *)in + x * ((layout == IN_RGBA16) ? 4 : 3);
					rgb[0] = lut[0][p[0]];
					rgb[1] = lut[1][p[1]];
					rgb[2] = lut[2][p[2]];
					if (layout == IN_RGBA16) {
						alpha = p[3] / 65535.0;
					}
					break;
				}
				case IN_GREYF:
					rgb[0] = rgb[1] = rgb[2] = plan.Apply(0, ((const float *)in)[x]);
					break;
				default: {
					const float *p = (const float *)in + x * ((layout == IN_RGBAF) ? 4 : 3);
					for (unsigned c = 0; c < 3; c++) {
						rgb[c] = plan.Apply(c, p[c]);
					}
					if (layout == IN_RGBAF) {
						alpha = p[3];
					}
					break;
				}
			}
			if (plan.hlg) {
				// the reference display: 0.75 becomes 203 cd/m2
				const double luminance = plan.weights[0] * rgb[0] + plan.weights[1] * rgb[1] + plan.weights[2] * rgb[2];
				const double gain = (luminance > 0) ? hlg_scale * pow(luminance, HLG_GAMMA - 1) : 0;
				for (unsigned c = 0; c < 3; c++) {
					rgb[c] *= gain;
				}
			}
			float *q = out + x * out_step;
			if (plan.convert) {
				for (unsigned c = 0; c < 3; c++) {
					q[c] = (float)(plan.matrix[c][0] * rgb[0] + plan.matrix[c][1] * rgb[1] + plan.matrix[c][2] * rgb[2]);
				}
			} else {
				q[0] = (float)rgb[0];
				q[1] = (float)rgb[1];
				q[2] = (float)rgb[2];
			}
			if (out_step == 4) {
				q[3] = (float)alpha;
			}
		}
	}
}

// the result's description: its primaries and linear transfer, and the profile it keeps, if any
static void
Describe(FIBITMAP *dst, FIBITMAP *dib, BYTE primaries, const std::vector<BYTE> &icc) {
	FreeImage_CloneMetadata(dst, dib);
	FreeImage_SetDotsPerMeterX(dst, FreeImage_GetDotsPerMeterX(dib));
	FreeImage_SetDotsPerMeterY(dst, FreeImage_GetDotsPerMeterY(dib));
	// the result is light: the source's precision no longer applies
	FreeImage_SetMetadata(FIMD_CUSTOM, dst, "SignificantBits", NULL);
	FreeImage_SetMetadata(FIMD_CUSTOM, dst, "UnscaledBits", NULL);
	SetCICPMetadata(dst, primaries, 8, 0, TRUE);
	FreeImage_DestroyICCProfile(dst);
	if (!icc.empty()) {
		FreeImage_CreateICCProfile(dst, (void *)&icc[0], (long)icc.size());
	}
}

// a profile Little CMS cannot reduce to tone curves and colorants: converted to linear sRGB by FreeImage_ConvertToICCProfile
static FIBITMAP *
ConvertThroughProfile(FIBITMAP *dib, bool alpha) {
	FIBITMAP *encoded = alpha ? FreeImage_ConvertToRGBAF(dib) : FreeImage_ConvertToRGBF(dib);
	if (!encoded) {
		return NULL;
	}
	const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	FreeImage_CreateICCProfile(encoded, icc->data, (long)icc->size);
	DWORD size = 0;
	const void *linear = FreeImage_GetBuiltInICCProfile(FICMS_PROFILE_LINEAR_SRGB, &size);
	FIBITMAP *result = linear ? FreeImage_ConvertToICCProfile(encoded, linear, size, FICMS_INTENT_RELATIVE_COLORIMETRIC) : NULL;
	FreeImage_Unload(encoded);
	if (result) {
		// linear sRGB is what FreeImage takes a floating-point image without a profile for
		Describe(result, dib, 1, std::vector<BYTE>());
	}
	return result;
}

static unsigned
UnscaledMaximum(FIBITMAP *dib, unsigned maximum) {
	FITAG *tag = NULL;
	if (FreeImage_GetMetadata(FIMD_CUSTOM, dib, "UnscaledBits", &tag) && tag && (FreeImage_GetTagType(tag) == FIDT_BYTE) && (FreeImage_GetTagCount(tag) == 1)) {
		const unsigned bits = *(const BYTE *)FreeImage_GetTagValue(tag);
		if ((bits > 0) && ((1u << bits) - 1 < maximum)) {
			return (1u << bits) - 1;
		}
	}
	return maximum;
}

static FIBITMAP *
ConvertToLinear(FIBITMAP *dib, int flags, cmsContext context) {
	const FREE_IMAGE_TYPE type = FreeImage_GetImageType(dib);
	const bool to_bt709 = ((flags & FI_LINEAR_SRGB_PRIMARIES) == FI_LINEAR_SRGB_PRIMARIES);
	const bool alpha = (type == FIT_RGBA16) || (type == FIT_RGBAF) || ((type == FIT_BITMAP) && FreeImage_IsTransparent(dib));
	const bool grey = IsGreyPixels(dib);

	Plan plan;
	cmsHPROFILE profile = NULL;
	std::vector<BYTE> linear_icc;
	BYTE cicp[4];
	const bool described = GetCICPMetadata(dib, cicp) && (CurveOfCode(cicp[1]) != NULL);
	if (described) {
		PlanFromCode(plan, context, cicp[0], cicp[1], to_bt709);
	} else {
		const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
		if (icc && icc->data && (icc->size >= 132)) {
			profile = cmsOpenProfileFromMemTHR(context, icc->data, icc->size);
		}
		const cmsColorSpaceSignature space = profile ? cmsGetColorSpace(profile) : (cmsColorSpaceSignature)0;
		if (profile && (space != (grey ? cmsSigGrayData : cmsSigRgbData))) {
			// a profile for other pixels says nothing about these
			cmsCloseProfile(profile);
			profile = NULL;
		}
		const cmsVideoSignalType *signal = profile ? (const cmsVideoSignalType *)cmsReadTag(profile, cmsSigcicpTag) : NULL;
		if (signal && CurveOfCode(signal->TransferCharacteristics)) {
			PlanFromCode(plan, context, signal->ColourPrimaries, signal->TransferCharacteristics, to_bt709);
		} else if (profile && grey) {
			plan.trc[0] = plan.trc[1] = plan.trc[2] = (const cmsToneCurve *)cmsReadTag(profile, cmsSigGrayTRCTag);
			if (!plan.trc[0]) {
				plan.curve = FromSRGB;
			}
			plan.primaries = 1;
		} else if (profile) {
			if (!cmsIsMatrixShaper(profile)) {
				cmsCloseProfile(profile);
				return ConvertThroughProfile(dib, alpha);
			}
			plan.trc[0] = (const cmsToneCurve *)cmsReadTag(profile, cmsSigRedTRCTag);
			plan.trc[1] = (const cmsToneCurve *)cmsReadTag(profile, cmsSigGreenTRCTag);
			plan.trc[2] = (const cmsToneCurve *)cmsReadTag(profile, cmsSigBlueTRCTag);
			cmsHPROFILE linear = LinearCopy(context, profile);
			if (!plan.trc[0] || !plan.trc[1] || !plan.trc[2] || !linear) {
				if (linear) {
					cmsCloseProfile(linear);
				}
				cmsCloseProfile(profile);
				return ConvertThroughProfile(dib, alpha);
			}
			if (to_bt709) {
				plan.convert = MatrixToBT709(context, linear, plan.matrix);
				plan.primaries = 1;
			} else {
				// the result keeps the profile's colorants, with linear tone curves
				cmsUInt32Number size = 0;
				if (cmsSaveProfileToMem(linear, NULL, &size) && size) {
					linear_icc.resize(size);
					if (!cmsSaveProfileToMem(linear, &linear_icc[0], &size)) {
						linear_icc.clear();
					}
				}
			}
			cmsCloseProfile(linear);
		} else {
			// FreeImage's defaults: sRGB for 8- and 16-bit images, linear sRGB for floating point
			const bool floating = (type == FIT_FLOAT) || (type == FIT_RGBF) || (type == FIT_RGBAF);
			plan.curve = floating ? FromLinear : FromSRGB;
			plan.primaries = 1;
		}
	}

	// the source, in a layout the rows read
	FIBITMAP *src = dib;
	Layout layout;
	unsigned maximum = 0;
	switch (type) {
		case FIT_BITMAP:
			src = alpha ? FreeImage_ConvertTo32Bits(dib) : FreeImage_ConvertTo24Bits(dib);
			layout = alpha ? IN_RGBA8 : IN_RGB8;
			maximum = 255;
			break;
		case FIT_UINT16:
			layout = IN_GREY16;
			maximum = 65535;
			break;
		case FIT_RGB16:
			layout = IN_RGB16;
			maximum = 65535;
			break;
		case FIT_RGBA16:
			layout = IN_RGBA16;
			maximum = 65535;
			break;
		case FIT_FLOAT:
			layout = IN_GREYF;
			break;
		case FIT_RGBF:
			layout = IN_RGBF;
			break;
		default:
			layout = IN_RGBAF;
			break;
	}

	FIBITMAP *dst = NULL;
	if (src) {
		std::vector<float> lut[3];
		if (maximum) {
			// unscaled samples are read in their own precision
			const unsigned top = UnscaledMaximum(dib, maximum);
			for (unsigned c = 0; c < 3; c++) {
				if ((c > 0) && (plan.trc[c] == plan.trc[0])) {
					lut[c] = lut[0];
					continue;
				}
				lut[c].resize(maximum + 1);
				for (unsigned v = 0; v <= maximum; v++) {
					lut[c][v] = (float)plan.Apply(c, (double)MIN(v, top) / top);
				}
			}
		}
		dst = FreeImage_AllocateT(alpha ? FIT_RGBAF : FIT_RGBF, (int)FreeImage_GetWidth(dib), (int)FreeImage_GetHeight(dib));
		if (dst) {
			ConvertRows(src, dst, layout, plan, lut);
			Describe(dst, dib, plan.primaries, linear_icc);
		}
		if (src != dib) {
			FreeImage_Unload(src);
		}
	}
	if (profile) {
		cmsCloseProfile(profile);
	}
	return dst;
}

