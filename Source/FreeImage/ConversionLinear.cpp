static bool
IsGreyPixels(FIBITMAP *dib) {
	switch (FreeImage_GetImageType(dib)) {
		case FIT_UINT16:
		case FIT_FLOAT:
			return true;
		case FIT_BITMAP: {
			const FREE_IMAGE_COLOR_TYPE color = FreeImage_GetColorType(dib);
			return (color == FIC_MINISBLACK) || (color == FIC_MINISWHITE);
		}
		default:
			return false;
	}
}

static void
PlanFromCode(Plan &plan, cmsContext context, BYTE primaries, BYTE transfer, bool to_bt709) {
	plan.curve = CurveOfCode(transfer);
	plan.hlg = (transfer == 18);
	if (primaries == 9) {
		// BT.2100's luminance for the HLG display step
		plan.weights[0] = 0.2627; plan.weights[1] = 0.6780; plan.weights[2] = 0.0593;
	}
	plan.primaries = primaries;
	if (to_bt709 && (primaries != 1)) {
		const Chromaticities *c = ChromaticitiesOfCode(primaries);
		cmsHPROFILE from = c ? LinearProfileOfCode(context, *c) : NULL;
		if (from) {
			plan.convert = MatrixToBT709(context, from, plan.matrix);
			cmsCloseProfile(from);
		}
		if (plan.convert || (primaries == 2)) {
			plan.primaries = 1;
		}
	}
}

