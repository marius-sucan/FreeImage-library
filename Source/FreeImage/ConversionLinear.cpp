static double
Signed(double signal, double light) {
	return (signal < 0) ? -light : light;
}

static double
FromLinear(double signal) {
	return signal;
}

static double
FromSRGB(double signal) {
	const double v = fabs(signal);
	return Signed(signal, (v <= 0.04045) ? v / 12.92 : pow((v + 0.055) / 1.055, 2.4));
}

// BT.709, BT.601 and BT.2020: their camera curve, undone; xvYCC and BT.1361 extend it below 0
static double
FromBT709(double signal) {
	const double v = fabs(signal);
	return Signed(signal, (v < 0.081) ? v / 4.5 : pow((v + 0.099) / 1.099, 1 / 0.45));
}

static double
FromGamma22(double signal) {
	return Signed(signal, pow(fabs(signal), 2.2));
}

static double
FromGamma28(double signal) {
	return Signed(signal, pow(fabs(signal), 2.8));
}

static double
FromSMPTE240(double signal) {
	const double v = fabs(signal);
	return Signed(signal, (v < 0.0913) ? v / 4 : pow((v + 0.1115) / 1.1115, 1 / 0.45));
}

static double
FromLog100(double signal) {
	return (signal <= 0) ? 0 : pow(10.0, 2 * (signal - 1));
}

static double
FromLog316(double signal) {
	return (signal <= 0) ? 0 : pow(10.0, 2.5 * (signal - 1));
}

// SMPTE ST 2084: absolute luminance up to 10000 cd/m2
static double
FromPQ(double signal) {
	const double m1 = 2610.0 / 16384, m2 = 2523.0 / 4096 * 128;
	const double c1 = 3424.0 / 4096, c2 = 2413.0 / 4096 * 32, c3 = 2392.0 / 4096 * 32;
	const double p = pow(MAX(signal, 0.0), 1 / m2);
	return 10000 * pow(MAX(p - c1, 0.0) / (c2 - c3 * p), 1 / m1) / REFERENCE_WHITE;
}

// ARIB STD-B67: scene light up to 1, the display step comes after
static double
FromHLG(double signal) {
	const double a = 0.17883277, b = 1 - 4 * a, c = 0.5 - a * log(4 * a);
	if (signal <= 0) {
		return 0;
	}
	return (signal <= 0.5) ? signal * signal / 3 : (exp((signal - c) / a) + b) / 12;
}

// SMPTE ST 428-1, the cinema's XYZ, 48 cd/m2 as white
static double
FromSMPTE428(double signal) {
	return pow(MAX(signal, 0.0), 2.6) * 52.37 / 48;
}

static Curve
CurveOfCode(BYTE transfer) {
	switch (transfer) {
		case 1: case 6: case 11: case 12: case 14: case 15:
			return FromBT709;
		case 4:
			return FromGamma22;
		case 5:
			return FromGamma28;
		case 7:
			return FromSMPTE240;
		case 8:
			return FromLinear;
		case 9:
			return FromLog100;
		case 10:
			return FromLog316;
		case 13:
			return FromSRGB;
		case 16:
			return FromPQ;
		case 17:
			return FromSMPTE428;
		case 18:
			return FromHLG;
		default:	// 2 unspecified, 0 and 3 reserved
			return NULL;
	}
}

