static FIBITMAP *
AllocateOutput(BOOL header_only, const JXLOutput *out, uint32_t width, uint32_t height) {
	if((width == 0) || (height == 0) || (width > (uint32_t)INT_MAX) || (height > (uint32_t)INT_MAX)) {
		FreeImage_OutputMessageProc(s_format_id, "Unsupported image size: %u x %u", width, height);
		return NULL;
	}
	FIBITMAP *dib = NULL;
	if((out->type == FIT_BITMAP) && (out->bpp >= 24)) {
		dib = FreeImage_AllocateHeaderT(header_only, FIT_BITMAP, (int)width, (int)height, (int)out->bpp, FI_RGBA_RED_MASK, FI_RGBA_GREEN_MASK, FI_RGBA_BLUE_MASK);
	} else {
		dib = FreeImage_AllocateHeaderT(header_only, out->type, (int)width, (int)height, (int)out->bpp, 0, 0, 0);
	}
	if(!dib) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_DIB_MEMORY);
		return NULL;
	}
	if((out->type == FIT_BITMAP) && (out->bpp == 8)) {
		RGBQUAD *pal = FreeImage_GetPalette(dib);
		for(int i = 0; i < 256; i++) {
			pal[i].rgbRed = pal[i].rgbGreen = pal[i].rgbBlue = (BYTE)i;
			pal[i].rgbReserved = 0;
		}
	}
	return dib;
}

static unsigned
SampleBytes(JxlDataType type) {
	switch(type) {
		case JXL_TYPE_UINT8:
			return 1;
		case JXL_TYPE_UINT16:
		case JXL_TYPE_FLOAT16:
			return 2;
		default:
			return 4;
	}
}

// libjxl rows are top-down, a part of a row per call, from several threads
static void
SinkPixels(void *opaque, size_t x, size_t y, size_t num_pixels, const void *pixels) {
	JXLSink *sink = (JXLSink*)opaque;
	if((y >= sink->height) || (x >= sink->width) || (num_pixels > sink->width - x)) {
		return;
	}
	BYTE *dst = sink->bits + (size_t)sink->pitch * (sink->height - 1 - y) + x * sink->dst_pixel;
	if(sink->transform) {
		cmsDoTransform(sink->transform, pixels, dst, (cmsUInt32Number)num_pixels);
	} else if(sink->swap_rb) {
		const BYTE *src = (const BYTE*)pixels;
		const unsigned n = sink->channels;
		for(size_t i = 0; i < num_pixels; i++, src += n, dst += n) {
			dst[FI_RGBA_RED] = src[0];
			dst[FI_RGBA_GREEN] = src[1];
			dst[FI_RGBA_BLUE] = src[2];
			if(n == 4) {
				dst[FI_RGBA_ALPHA] = src[3];
			}
		}
	} else {
		memcpy(dst, pixels, num_pixels * sink->src_pixel);
	}
	sink->pixels.fetch_add(num_pixels, std::memory_order_relaxed);
}

static FIBITMAP *
LoadHeader(const JXLReader *reader, BOOL playback) {
	JXLOutput out;
	ChooseOutput(reader, playback, &out);
	FIBITMAP *dib = AllocateOutput(TRUE, &out, reader->info.xsize, reader->info.ysize);
	if(dib) {
		AttachColor(dib, reader, &out, PageRoute(reader, &out));
	}
	return dib;
}

// a decoder positioned before 'page'
static BOOL
PrepareDecoder(JXLReader *reader, int page) {
	if(reader->decoder && (page >= reader->next_page)) {
		if(page > reader->next_page) {
			JxlDecoderSkipFrames(reader->decoder, (size_t)(page - reader->next_page));
			reader->next_page = page;
		}
		return TRUE;
	}
	if(reader->decoder) {
		// going back: start again from the first byte
		JxlDecoderRewind(reader->decoder);
	} else {
		reader->decoder = JxlDecoderCreate(NULL);
		if(!reader->decoder) {
			FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
			return FALSE;
		}
		if(!reader->runner) {
			reader->runner = CreateRunner(reader->info.xsize, reader->info.ysize);
		}
		if((reader->runner && (JxlDecoderSetParallelRunner(reader->decoder, JxlResizableParallelRunner, reader->runner) != JXL_DEC_SUCCESS)) ||
			(JxlDecoderSubscribeEvents(reader->decoder, JXL_DEC_COLOR_ENCODING | JXL_DEC_FRAME | JXL_DEC_FRAME_PROGRESSION | JXL_DEC_FULL_IMAGE) != JXL_DEC_SUCCESS) ||
			(JxlDecoderSetUnpremultiplyAlpha(reader->decoder, JXL_TRUE) != JXL_DEC_SUCCESS)) {
			CloseDecoder(reader);
			return FALSE;
		}
	}
	reader->next_page = 0;
	// the input stays open: a cut file then asks for more, and what was decoded can be flushed
	if(JxlDecoderSetInput(reader->decoder, &reader->data[0], reader->data.size()) != JXL_DEC_SUCCESS) {
		CloseDecoder(reader);
		return FALSE;
	}
	if(page > 0) {
		JxlDecoderSkipFrames(reader->decoder, (size_t)page);
		reader->next_page = page;
	}
	return TRUE;
}

static FIBITMAP *
LoadPixels(JXLReader *reader, int page, BOOL playback) {
	JXLOutput out;
	ChooseOutput(reader, playback, &out);
	const JXLRoute route = PageRoute(reader, &out);

	JxlPixelFormat format = out.format;
	cmsHTRANSFORM transform = NULL;
	if(route == JXL_ROUTE_TO_ICC) {
		transform = GetTransform(reader, &out);
		if(!transform) {
			FreeImage_OutputMessageProc(s_format_id, "Cannot convert the image to its ICC profile");
			return NULL;
		}
		format.data_type = JXL_TYPE_FLOAT;
	}

	if(!PrepareDecoder(reader, page)) {
		return NULL;
	}
	JxlDecoder *dec = reader->decoder;

	// allocated when libjxl asks: past the frame header and its whole TOC, so a damaged size allocates nothing
	FIBITMAP *dib = NULL;
	JXLSink sink;
	sink.channels = format.num_channels;
	sink.src_pixel = format.num_channels * SampleBytes(format.data_type);
	sink.swap_rb = out.swap_rb;
	sink.transform = transform;
	sink.pixels.store(0);

	BOOL complete = FALSE;
	BOOL salvaged = FALSE;
	BOOL missing = FALSE;
	BOOL cut = FALSE;
	BOOL output_set = FALSE;
	BOOL progressed = FALSE;	// a whole lower-resolution pass is decoded
	BOOL flushed = FALSE;
	try {
		for(;;) {
			const JxlDecoderStatus status = JxlDecoderProcessInput(dec);
			if(status == JXL_DEC_COLOR_ENCODING) {
				if(route == JXL_ROUTE_TO_SRGB) {
					JxlColorEncoding srgb;
					JxlColorEncodingSetToSRGB(&srgb, (reader->info.num_color_channels == 1) ? JXL_TRUE : JXL_FALSE);
					JxlDecoderSetPreferredColorProfile(dec, &srgb);
				}
				continue;
			}
			if(status == JXL_DEC_FRAME) {
				continue;
			}
			if(status == JXL_DEC_FRAME_PROGRESSION) {
				progressed = TRUE;
				continue;
			}
			if(status == JXL_DEC_NEED_IMAGE_OUT_BUFFER) {
				dib = AllocateOutput(FALSE, &out, reader->info.xsize, reader->info.ysize);
				if(!dib) {
					CloseDecoder(reader);
					return NULL;
				}
				sink.bits = FreeImage_GetBits(dib);
				sink.pitch = FreeImage_GetPitch(dib);
				sink.width = FreeImage_GetWidth(dib);
				sink.height = FreeImage_GetHeight(dib);
				sink.dst_pixel = FreeImage_GetBPP(dib) / 8;
				if(JxlDecoderSetImageOutCallback(dec, &format, SinkPixels, &sink) != JXL_DEC_SUCCESS) {
					FreeImage_OutputMessageProc(s_format_id, "Cannot decode the image to %u channels of %u bytes", format.num_channels, SampleBytes(format.data_type));
					break;
				}
				output_set = TRUE;
				continue;
			}
			if(status == JXL_DEC_FULL_IMAGE) {
				complete = output_set;
				break;
			}
			if(status == JXL_DEC_NEED_MORE_INPUT) {
				cut = TRUE;
				if(output_set) {
					// past a whole pass, the rest is shown at its resolution; else only whole groups
					if(progressed && (JxlDecoderFlushImage(dec) == JXL_DEC_SUCCESS)) {
						flushed = TRUE;
					}
					salvaged = TRUE;
				}
				break;
			}
			if(status == JXL_DEC_SUCCESS) {
				missing = TRUE;
				break;
			}
			// damaged, or cut before the frame's pixels
			if(output_set) {
				salvaged = TRUE;
			}
			break;
		}

		if(complete) {
			reader->next_page = page + 1;
		} else {
			CloseDecoder(reader);
			if(!salvaged || (sink.pixels.load() == 0)) {
				if(missing) {
					FreeImage_OutputMessageProc(s_format_id, "Page %d does not exist", page);
				} else {
					FreeImage_OutputMessageProc(s_format_id, cut ? "Cannot decode the image: the file is cut short" : "Cannot decode the image: the data is invalid or not supported");
				}
				FreeImage_Unload(dib);
				return NULL;
			}
			if(flushed) {
				FreeImage_OutputMessageProc(s_format_id, "Warning: the file is cut short; what was not decoded in full is shown at a lower resolution");
			} else {
				DamagedImageWarning(s_format_id);
			}
		}

		AttachColor(dib, reader, &out, route);
		return dib;
	} catch(std::bad_alloc&) {
		FreeImage_Unload(dib);
		throw;
	}
}

// ----------------------------------------------------------
//   CMYK: CMY as colour samples, K as an extra channel, 1 meaning no ink
// ----------------------------------------------------------

typedef struct tagJXLCMYKSink {
	BYTE *bits;					// the CMYK bitmap, bottom-up
	unsigned pitch;
	unsigned width;
	unsigned height;
	BOOL deep;
	unsigned channels;			// 3, or 4 with alpha
	BYTE *alpha;				// top-down alpha plane, or NULL
	std::atomic<unsigned long long> pixels;
} JXLCMYKSink;

static void
SinkCMYK(void *opaque, size_t x, size_t y, size_t num_pixels, const void *pixels) {
	JXLCMYKSink *sink = (JXLCMYKSink*)opaque;
	if((y >= sink->height) || (x >= sink->width) || (num_pixels > sink->width - x)) {
		return;
	}
	const unsigned n = sink->channels;
	if(sink->deep) {
		const WORD *src = (const WORD*)pixels;
		WORD *dst = (WORD*)(sink->bits + (size_t)sink->pitch * (sink->height - 1 - y)) + x * 4;
		WORD *alpha = sink->alpha ? (WORD*)sink->alpha + y * (size_t)sink->width + x : NULL;
		for(size_t i = 0; i < num_pixels; i++, src += n, dst += 4) {
			dst[0] = (WORD)(65535 - src[0]);
			dst[1] = (WORD)(65535 - src[1]);
			dst[2] = (WORD)(65535 - src[2]);
			if(alpha) {
				alpha[i] = src[3];
			}
		}
	} else {
		const BYTE *src = (const BYTE*)pixels;
		BYTE *dst = sink->bits + (size_t)sink->pitch * (sink->height - 1 - y) + x * 4;
		BYTE *alpha = sink->alpha ? sink->alpha + y * (size_t)sink->width + x : NULL;
		for(size_t i = 0; i < num_pixels; i++, src += n, dst += 4) {
			dst[0] = (BYTE)(255 - src[0]);
			dst[1] = (BYTE)(255 - src[1]);
			dst[2] = (BYTE)(255 - src[2]);
			if(alpha) {
				alpha[i] = src[3];
			}
		}
	}
	sink->pixels.fetch_add(num_pixels, std::memory_order_relaxed);
}

static FIBITMAP *
AllocateCMYKResult(BOOL header_only, const JXLReader *reader, BOOL keep_cmyk) {
	JXLOutput out;
	memset(&out, 0, sizeof(out));
	const BOOL deep = (reader->info.bits_per_sample > 8) ? TRUE : FALSE;
	const BOOL alpha = (keep_cmyk || (reader->info.alpha_bits > 0)) ? TRUE : FALSE;
	if(deep) {
		out.type = alpha ? FIT_RGBA16 : FIT_RGB16;
		out.bpp = alpha ? 64 : 48;
	} else {
		out.type = FIT_BITMAP;
		out.bpp = alpha ? 32 : 24;
	}
	return AllocateOutput(header_only, &out, reader->info.xsize, reader->info.ysize);
}

static void
AttachCMYKProfile(FIBITMAP *cmyk, const JXLReader *reader) {
	if(!reader->orig_icc.empty() && (reader->orig_icc.size() <= (size_t)LONG_MAX)) {
		FIICCPROFILE *icc = FreeImage_CreateICCProfile(cmyk, (void*)&reader->orig_icc[0], (long)reader->orig_icc.size());
		if(icc) {
			icc->flags |= FIICC_COLOR_IS_CMYK;
		}
	}
}

static FIBITMAP *
LoadCMYK(JXLReader *reader, int page, BOOL header_only, BOOL keep_cmyk) {
	if(header_only) {
		FIBITMAP *dib = AllocateCMYKResult(TRUE, reader, keep_cmyk);
		if(dib && keep_cmyk) {
			AttachCMYKProfile(dib, reader);
		}
		return dib;
	}

	const BOOL deep = (reader->info.bits_per_sample > 8) ? TRUE : FALSE;
	const BOOL alpha = (!keep_cmyk && (reader->info.alpha_bits > 0)) ? TRUE : FALSE;
	std::vector<BYTE> black;
	std::vector<BYTE> alpha_plane;

	JXLCMYKSink sink;
	sink.deep = deep;
	sink.channels = (reader->info.alpha_bits > 0) ? 4 : 3;
	sink.alpha = NULL;
	sink.pixels.store(0);

	JxlPixelFormat format;
	format.num_channels = sink.channels;
	format.data_type = deep ? JXL_TYPE_UINT16 : JXL_TYPE_UINT8;
	format.endianness = JXL_NATIVE_ENDIAN;
	format.align = 0;

	// allocated when libjxl asks, as in LoadPixels
	FIBITMAP *cmyk = NULL;
	BOOL complete = FALSE;
	try {
		if(PrepareDecoder(reader, page)) {
			JxlDecoder *dec = reader->decoder;
			for(;;) {
				const JxlDecoderStatus status = JxlDecoderProcessInput(dec);
				if((status == JXL_DEC_COLOR_ENCODING) || (status == JXL_DEC_FRAME) || (status == JXL_DEC_FRAME_PROGRESSION)) {
					continue;
				}
				if(status == JXL_DEC_NEED_IMAGE_OUT_BUFFER) {
					cmyk = AllocateCMYKResult(FALSE, reader, TRUE);
					if(!cmyk) {
						CloseDecoder(reader);
						return NULL;
					}
					const size_t plane = (size_t)reader->info.xsize * reader->info.ysize * (deep ? 2 : 1);
					black.resize(plane);
					alpha_plane.resize(alpha ? plane : 0);
					sink.bits = FreeImage_GetBits(cmyk);
					sink.pitch = FreeImage_GetPitch(cmyk);
					sink.width = FreeImage_GetWidth(cmyk);
					sink.height = FreeImage_GetHeight(cmyk);
					sink.alpha = alpha ? &alpha_plane[0] : NULL;
					if((JxlDecoderSetImageOutCallback(dec, &format, SinkCMYK, &sink) != JXL_DEC_SUCCESS) ||
						(JxlDecoderSetExtraChannelBuffer(dec, &format, &black[0], black.size(), reader->black_index) != JXL_DEC_SUCCESS)) {
						break;
					}
					continue;
				}
				complete = ((status == JXL_DEC_FULL_IMAGE) && cmyk) ? TRUE : FALSE;
				break;
			}
		}
	} catch(std::bad_alloc&) {
		FreeImage_Unload(cmyk);
		throw;
	}
	if(!complete) {
		CloseDecoder(reader);
		FreeImage_OutputMessageProc(s_format_id, "Cannot decode the CMYK image: the file is cut short, damaged or not supported");
		FreeImage_Unload(cmyk);
		return NULL;
	}
	reader->next_page = page + 1;
	AttachCMYKProfile(cmyk, reader);

	// K joins C, M and Y as ink
	const unsigned width = FreeImage_GetWidth(cmyk);
	const unsigned height = FreeImage_GetHeight(cmyk);
	for(unsigned y = 0; y < height; y++) {
		BYTE *row = FreeImage_GetScanLine(cmyk, height - 1 - y);
		if(deep) {
			const WORD *k = (const WORD*)&black[0] + (size_t)y * width;
			WORD *dst = (WORD*)row;
			for(unsigned x = 0; x < width; x++) {
				dst[4 * x + 3] = (WORD)(65535 - k[x]);
			}
		} else {
			const BYTE *k = &black[(size_t)y * width];
			for(unsigned x = 0; x < width; x++) {
				row[4 * x + 3] = (BYTE)(255 - k[x]);
			}
		}
	}
	if(keep_cmyk) {
		return cmyk;
	}

	// to RGB through the profile, as FreeImage_ConvertCMYKToRGB() does
	FIBITMAP *rgb = FreeImage_ConvertCMYKToRGB(cmyk, NULL, 0, 0);
	FreeImage_Unload(cmyk);
	if(!rgb) {
		FreeImage_OutputMessageProc(s_format_id, "Cannot convert the CMYK image to RGB");
		return NULL;
	}
	// sRGB: untagged
	FreeImage_DestroyICCProfile(rgb);
	if(alpha) {
		FIBITMAP *rgba = deep ? FreeImage_ConvertToRGBA16(rgb) : FreeImage_ConvertTo32Bits(rgb);
		FreeImage_Unload(rgb);
		if(!rgba) {
			FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_DIB_MEMORY);
			return NULL;
		}
		for(unsigned y = 0; y < height; y++) {
			BYTE *row = FreeImage_GetScanLine(rgba, height - 1 - y);
			if(deep) {
				const WORD *a = (const WORD*)&alpha_plane[0] + (size_t)y * width;
				FIRGBA16 *dst = (FIRGBA16*)row;
				for(unsigned x = 0; x < width; x++) {
					dst[x].alpha = a[x];
				}
			} else {
				const BYTE *a = &alpha_plane[(size_t)y * width];
				for(unsigned x = 0; x < width; x++) {
					row[4 * x + FI_RGBA_ALPHA] = a[x];
				}
			}
		}
		rgb = rgba;
	}
	return rgb;
}

