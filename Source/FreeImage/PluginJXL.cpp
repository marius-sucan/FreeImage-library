#define FI_JXL_READ_STEP (1 << 20)

static BOOL
ReadWholeFile(FreeImageIO *io, fi_handle handle, std::vector<BYTE>& data) {
	const INT64 start = io->tell_proc(handle);
	INT64 end = -1;
	if((start >= 0) && (io->seek_proc(handle, 0, SEEK_END) == 0)) {
		end = io->tell_proc(handle);
		if(io->seek_proc(handle, start, SEEK_SET) != 0) {
			return FALSE;
		}
	}
	if((start >= 0) && (end >= start)) {
		if((UINT64)(end - start) > (UINT64)(std::numeric_limits<size_t>::max)()) {
			FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
			return FALSE;
		}
		data.resize((size_t)(end - start));
		const size_t got = FreeImage_ReadBytes(io, handle, data.empty() ? NULL : &data[0], data.size());
		data.resize(got);
		return TRUE;
	}
	// no length: read to the end
	size_t got = 0;
	for(;;) {
		data.resize(got + FI_JXL_READ_STEP);
		const size_t n = FreeImage_ReadBytes(io, handle, &data[got], FI_JXL_READ_STEP);
		got += n;
		if(n < FI_JXL_READ_STEP) {
			break;
		}
	}
	data.resize(got);
	return TRUE;
}

