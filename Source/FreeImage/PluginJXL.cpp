		case 8:
			enc->transfer_function = JXL_TRANSFER_FUNCTION_LINEAR;
			break;
		case 13:
			enc->transfer_function = JXL_TRANSFER_FUNCTION_SRGB;
			break;
		case 16:
			enc->transfer_function = JXL_TRANSFER_FUNCTION_PQ;
			enc->rendering_intent = JXL_RENDERING_INTENT_PERCEPTUAL;
			break;
