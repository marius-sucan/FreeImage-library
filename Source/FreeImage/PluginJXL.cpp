// how an animation's frames reach the file; libjxl blends lossy frames only in colours it can name
typedef enum {
	JXL_FRAMES_LAYERED = 0,		// each frame blends over the earlier ones in the decoder
	JXL_FRAMES_SRGB = 1,		// layered, every frame converted to sRGB (linear sRGB for float) first
	JXL_FRAMES_WHOLE = 2		// the writer composes; each frame is the whole canvas, keeping the ICC profile
} JXLFrames;

typedef struct tagJXLWriter {
	JxlEncoder *encoder;
	JxlEncoderFrameSettings *settings;
	void *runner;
	// the layout of every frame
	FREE_IMAGE_TYPE type;
	unsigned bpp;
	JxlPixelFormat format;
	BOOL swap_rb;
	BOOL alpha;
	uint32_t canvas_width;
	uint32_t canvas_height;
	BOOL animation;
	std::vector<BYTE> profile;		// the file's ICC profile, every frame's colours
	BOOL has_profile;
	JXLFrames frame_mode;
	std::vector<BYTE> canvas;		// JXL_FRAMES_WHOLE: what the frames drew so far, top-down in the frame layout
	// a multi-page save: libjxl marks the last frame when it is added, so each page waits for the next
	int frames;						// frames given to the encoder
	FIBITMAP *held;					// the newest page; alone it is a still image
	int held_flags;
	BOOL written;
	BOOL failed;
	// GIF-style disposal, on JPEG XL reference frames
	BOOL nontrivial;				// a frame left its pixels for the next one
	BOOL clear_previous;
	uint32_t prev_x;
	uint32_t prev_y;
	uint32_t prev_width;
	uint32_t prev_height;
	std::vector<BYTE> out;
} JXLWriter;

static void
DestroyWriter(JXLWriter *writer) {
	if(writer) {
		if(writer->encoder) {
			JxlEncoderDestroy(writer->encoder);
		}
		if(writer->runner) {
			JxlResizableParallelRunnerDestroy(writer->runner);
		}
		if(writer->held) {
			FreeImage_Unload(writer->held);
		}
		delete writer;
	}
}

static void
ReportEncoderError(JxlEncoder *encoder, const char *what) {
	const char *detail = "unknown error";
	switch(JxlEncoderGetError(encoder)) {
		case JXL_ENC_ERR_OOM:
			detail = FI_MSG_ERROR_MEMORY;
			break;
		case JXL_ENC_ERR_BAD_INPUT:
			detail = "invalid input";
			break;
		case JXL_ENC_ERR_NOT_SUPPORTED:
			detail = "not supported";
			break;
		case JXL_ENC_ERR_API_USAGE:
			detail = "invalid settings";
			break;
		case JXL_ENC_ERR_GENERIC:
			detail = "encoder error";
			break;
		default:
			break;
	}
	FreeImage_OutputMessageProc(s_format_id, "%s: %s", what, detail);
}

// write what the encoder has produced so far
static BOOL
FlushOutput(JXLWriter *writer, FreeImageIO *io, fi_handle handle) {
	if(writer->out.empty()) {
		writer->out.resize(1 << 20);
	}
	for(;;) {
		uint8_t *next = &writer->out[0];
		size_t avail = writer->out.size();
		const JxlEncoderStatus status = JxlEncoderProcessOutput(writer->encoder, &next, &avail);
		const size_t produced = writer->out.size() - avail;
		if(produced && (FreeImage_WriteBytes(io, handle, &writer->out[0], produced) != produced)) {
			FreeImage_OutputMessageProc(s_format_id, "Cannot write the file");
			return FALSE;
		}
		if(status == JXL_ENC_SUCCESS) {
			return TRUE;
		}
		if(status != JXL_ENC_NEED_MORE_OUTPUT) {
			ReportEncoderError(writer->encoder, "Cannot encode the image");
			return FALSE;
		}
	}
}

// the layout a bitmap is written in; an animation is always written with alpha
static BOOL
ChooseLayout(FIBITMAP *dib, BOOL animation, JXLWriter *writer) {
	const FREE_IMAGE_TYPE type = FreeImage_GetImageType(dib);
	const unsigned bpp = FreeImage_GetBPP(dib);

	memset(&writer->format, 0, sizeof(writer->format));
	writer->format.endianness = JXL_NATIVE_ENDIAN;
	writer->swap_rb = FALSE;

	switch(type) {
		case FIT_BITMAP:
			writer->format.data_type = JXL_TYPE_UINT8;
			if(animation || (bpp == 32) || FreeImage_IsTransparent(dib)) {
				writer->bpp = 32;
			} else if((bpp <= 8) && ((FreeImage_GetColorType(dib) == FIC_MINISBLACK) || (FreeImage_GetColorType(dib) == FIC_MINISWHITE))) {
				writer->bpp = 8;
			} else {
				writer->bpp = 24;
			}
			writer->format.num_channels = writer->bpp / 8;
#if FREEIMAGE_COLORORDER == FREEIMAGE_COLORORDER_BGR
			writer->swap_rb = (writer->bpp >= 24) ? TRUE : FALSE;
#endif
			break;
		case FIT_UINT16:
		case FIT_RGB16:
		case FIT_RGBA16:
			writer->format.data_type = JXL_TYPE_UINT16;
			if(animation || (type == FIT_RGBA16)) {
				writer->type = FIT_RGBA16;
			} else {
				writer->type = type;
			}
			break;
		case FIT_FLOAT:
		case FIT_RGBF:
		case FIT_RGBAF:
			writer->format.data_type = JXL_TYPE_FLOAT;
			if(animation || (type == FIT_RGBAF)) {
				writer->type = FIT_RGBAF;
			} else {
				writer->type = type;
			}
			break;
		default:
			return FALSE;
	}
	if(type == FIT_BITMAP) {
		writer->type = FIT_BITMAP;
	} else {
		switch(writer->type) {
			case FIT_UINT16:
			case FIT_FLOAT:
				writer->format.num_channels = 1;
				break;
			case FIT_RGB16:
			case FIT_RGBF:
				writer->format.num_channels = 3;
				break;
			default:
				writer->format.num_channels = 4;
				break;
		}
		writer->bpp = writer->format.num_channels * 8 * SampleBytes(writer->format.data_type);
	}
	writer->alpha = ((writer->format.num_channels == 2) || (writer->format.num_channels == 4)) ? TRUE : FALSE;
	return TRUE;
}

// the bitmap in the file's layout; *converted is NULL when it already is
static BOOL
ConvertToLayout(FIBITMAP *dib, const JXLWriter *writer, FIBITMAP **converted) {
	*converted = NULL;
	FIBITMAP *rgb = NULL;
	if(FreeImage_GetColorType(dib) == FIC_CMYK) {
		// JPEG XL CMYK is not written: the colours go through the profile
		rgb = FreeImage_ConvertCMYKToRGB(dib, NULL, 0, 0);
		if(!rgb) {
			return FALSE;
		}
		dib = rgb;
	}
	const FREE_IMAGE_TYPE type = FreeImage_GetImageType(dib);
	FIBITMAP *result = NULL;
	if(writer->type == FIT_BITMAP) {
		if((type == FIT_BITMAP) && (FreeImage_GetBPP(dib) == writer->bpp) && ((writer->bpp != 8) || (FreeImage_GetColorType(dib) == FIC_MINISBLACK))) {
			*converted = rgb;
			return TRUE;
		}
		switch(writer->bpp) {
			case 8:
				result = FreeImage_ConvertToGreyscale(dib);
				break;
			case 24:
				result = FreeImage_ConvertTo24Bits(dib);
				break;
			default:
				result = FreeImage_ConvertTo32Bits(dib);
				break;
		}
	} else {
		if(type == writer->type) {
			*converted = rgb;
			return TRUE;
		}
		switch(writer->type) {
			case FIT_RGBA16:
				result = FreeImage_ConvertToRGBA16(dib);
				break;
			case FIT_RGBAF:
				result = FreeImage_ConvertToRGBAF(dib);
				break;
			default:
				result = FreeImage_ConvertToType(dib, writer->type, TRUE);
				break;
		}
	}
	if(rgb) {
		FreeImage_Unload(rgb);
	}
	if(!result) {
		return FALSE;
	}
	*converted = result;
	return TRUE;
}

// top-down interleaved samples of the part of a bitmap that lies on the canvas
static void
FrameSamples(FIBITMAP *dib, const JXLWriter *writer, uint32_t width, uint32_t height, std::vector<BYTE>& samples, BOOL *clamped) {
	const unsigned bytes = writer->format.num_channels * SampleBytes(writer->format.data_type);
	const unsigned dib_height = FreeImage_GetHeight(dib);
	const size_t row = (size_t)width * bytes;
	samples.resize(row * height);
	for(uint32_t y = 0; y < height; y++) {
		const BYTE *src = FreeImage_GetScanLine(dib, dib_height - 1 - y);
		BYTE *dst = &samples[row * y];
		if(writer->swap_rb) {
			const unsigned n = writer->format.num_channels;
			for(uint32_t x = 0; x < width; x++, src += n, dst += n) {
				dst[0] = src[FI_RGBA_RED];
				dst[1] = src[FI_RGBA_GREEN];
				dst[2] = src[FI_RGBA_BLUE];
				if(n == 4) {
					dst[3] = src[FI_RGBA_ALPHA];
				}
			}
		} else {
			memcpy(dst, src, row);
			if(writer->format.data_type == JXL_TYPE_FLOAT) {
				// libjxl takes no NaN or infinity
				float *f = (float*)dst;
				for(size_t i = 0; i < (size_t)width * writer->format.num_channels; i++) {
					if(f[i] != f[i]) {
						f[i] = 0;
						*clamped = TRUE;
					} else if(f[i] > FLT_MAX) {
						f[i] = FLT_MAX;
						*clamped = TRUE;
					} else if(f[i] < -FLT_MAX) {
						f[i] = -FLT_MAX;
						*clamped = TRUE;
					}
				}
			}
		}
	}
}

// Exif and XMP of a bitmap as boxes; FALSE when the encoder refuses them
static BOOL
AddMetadataBoxes(JXLWriter *writer, FIBITMAP *dib) {
	std::vector<BYTE> exif;
	FITAG *tag = NULL;
	if(FreeImage_GetMetadata(FIMD_EXIF_RAW, dib, g_TagLib_ExifRawFieldName, &tag) && tag && FreeImage_GetTagValue(tag)) {
		static const BYTE signature[6] = { 0x45, 0x78, 0x69, 0x66, 0x00, 0x00 };	// "Exif\0\0"
		const BYTE *data = (const BYTE*)FreeImage_GetTagValue(tag);
		size_t length = FreeImage_GetTagLength(tag);
		if((length > sizeof(signature)) && (memcmp(data, signature, sizeof(signature)) == 0)) {
			data += sizeof(signature);
			length -= sizeof(signature);
		}
		// the box holds the offset of the TIFF header, here 0, then the TIFF data
		if((length >= 8) && ((memcmp(data, "II*\0", 4) == 0) || (memcmp(data, "MM\0*", 4) == 0))) {
			exif.assign(4, 0);
			exif.insert(exif.end(), data, data + length);
		}
	}
	tag = NULL;
	const BOOL have_xmp = (FreeImage_GetMetadata(FIMD_XMP, dib, g_TagLib_XMPFieldName, &tag) && tag && FreeImage_GetTagValue(tag) && FreeImage_GetTagLength(tag)) ? TRUE : FALSE;
	if(exif.empty() && !have_xmp) {
		return TRUE;
	}
	if(JxlEncoderUseBoxes(writer->encoder) != JXL_ENC_SUCCESS) {
		return FALSE;
	}
	if(!exif.empty() && (JxlEncoderAddBox(writer->encoder, "Exif", &exif[0], exif.size(), JXL_FALSE) != JXL_ENC_SUCCESS)) {
		return FALSE;
	}
	if(have_xmp && (JxlEncoderAddBox(writer->encoder, "xml ", (const uint8_t*)FreeImage_GetTagValue(tag), FreeImage_GetTagLength(tag), JXL_FALSE) != JXL_ENC_SUCCESS)) {
		return FALSE;
	}
	JxlEncoderCloseBoxes(writer->encoder);
	return TRUE;
}

// libjxl's choice for lossy samples: TRUE when it keeps the profile, FALSE when it names the colours instead
static BOOL
ProfileStaysICC(const std::vector<BYTE>& icc) {
	const JxlCmsInterface *cms = JxlGetDefaultCms();
	JxlColorEncoding enc;
	JXL_BOOL cmyk = JXL_FALSE;
	memset(&enc, 0, sizeof(enc));
	if(!cms || !cms->set_fields_from_icc(cms->set_fields_data, &icc[0], icc.size(), &enc, &cmyk) || cmyk) {
		return TRUE;
	}
	return ((enc.color_space == JXL_COLOR_SPACE_UNKNOWN) || (enc.transfer_function == JXL_TRANSFER_FUNCTION_UNKNOWN)) ? TRUE : FALSE;
}

// TRUE when every colour of an RGB profile lies within two 8-bit steps of the sRGB gamut
static BOOL
ProfileFitsSRGB(const std::vector<BYTE>& icc) {
	const int N = 17;
	cmsHPROFILE profile = cmsOpenProfileFromMem(&icc[0], (cmsUInt32Number)icc.size());
	cmsHPROFILE srgb = cmsCreate_sRGBProfile();
	cmsHTRANSFORM transform = NULL;
	if(profile && srgb) {
		transform = cmsCreateTransform(profile, TYPE_RGB_FLT, srgb, TYPE_RGB_FLT, INTENT_RELATIVE_COLORIMETRIC, cmsFLAGS_NOCACHE | cmsFLAGS_BLACKPOINTCOMPENSATION | cmsFLAGS_HIGHRESPRECALC);
	}
	if(profile) {
		cmsCloseProfile(profile);
	}
	if(srgb) {
		cmsCloseProfile(srgb);
	}
	if(!transform) {
		return FALSE;
	}
	std::vector<float> in(N * N * N * 3), out(in.size());
	for(int r = 0, i = 0; r < N; r++) {
		for(int g = 0; g < N; g++) {
			for(int b = 0; b < N; b++, i += 3) {
				in[i] = (float)r / (N - 1);
				in[i + 1] = (float)g / (N - 1);
				in[i + 2] = (float)b / (N - 1);
			}
		}
	}
	cmsDoTransform(transform, &in[0], &out[0], N * N * N);
	cmsDeleteTransform(transform);
	const float step = 2.0f / 255;
	for(size_t i = 0; i < out.size(); i++) {
		if(!((out[i] >= -step) && (out[i] <= 1 + step))) {
			return FALSE;
		}
	}
	return TRUE;
}

// the profile a load made of the CICP tag
static BOOL
IsCICPProfile(const FIICCPROFILE *icc, const BYTE cicp[4], BOOL grey) {
	unsigned size = 0;
	const void *profile = GetCICPProfile(cicp[0], cicp[1], grey, &size);
	return (profile && (size == (unsigned)icc->size) && (memcmp(profile, icc->data, size) == 0)) ? TRUE : FALSE;
}

// the colours: the bitmap's ICC profile, else its CICP tag, else sRGB (linear for float)
static BOOL
SetColors(JXLWriter *writer, FIBITMAP *dib, BOOL lossy_animation) {
	const BOOL grey = (writer->format.num_channels < 3) ? TRUE : FALSE;
	const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	BOOL to_srgb = FALSE;
	writer->has_profile = FALSE;
	writer->frame_mode = JXL_FRAMES_LAYERED;
	JxlColorEncoding enc;
	BYTE cicp[4];
	const BOOL coded = (GetCICPMetadata(dib, cicp) && CICPToEncoding(cicp, grey, &enc)) ? TRUE : FALSE;
	// a profile made of the tag goes as the tag's encoding: a lossless file would keep the ICC
	const BOOL made = (coded && icc && icc->data && IsCICPProfile(icc, cicp, grey)) ? TRUE : FALSE;
	if(icc && icc->data && (icc->size >= 132) && !(icc->flags & FIICC_COLOR_IS_CMYK) && !made) {
		std::vector<BYTE> bytes((const BYTE*)icc->data, (const BYTE*)icc->data + icc->size);
		if(ProfileColorSpace(bytes) == (DWORD)(grey ? FICMS_COLORSPACE_GRAY : FICMS_COLORSPACE_RGB)) {
			// a profile libjxl keeps: its lossy frames could not blend
			if(lossy_animation && ProfileStaysICC(bytes)) {
				to_srgb = ProfileFitsSRGB(bytes);
				writer->frame_mode = to_srgb ? JXL_FRAMES_SRGB : JXL_FRAMES_WHOLE;
			}
			if(!to_srgb) {
				if(JxlEncoderSetICCProfile(writer->encoder, &bytes[0], bytes.size()) == JXL_ENC_SUCCESS) {
					writer->profile.swap(bytes);
					writer->has_profile = TRUE;
					return TRUE;
				}
				writer->frame_mode = JXL_FRAMES_LAYERED;
				FreeImage_OutputMessageProc(s_format_id, "Warning: the ICC profile cannot be used; the colors are written as %s", (writer->format.data_type == JXL_TYPE_FLOAT) ? "linear sRGB" : "sRGB");
			}
		}
	}
	if(to_srgb || !coded) {
		if(writer->format.data_type == JXL_TYPE_FLOAT) {
			JxlColorEncodingSetToLinearSRGB(&enc, grey ? JXL_TRUE : JXL_FALSE);
		} else {
			JxlColorEncodingSetToSRGB(&enc, grey ? JXL_TRUE : JXL_FALSE);
		}
	} else if(made) {
		// later frames are converted to the encoding's colors
		unsigned size = 0;
		const BYTE *profile = (const BYTE*)GetCICPProfile(cicp[0], cicp[1], grey, &size);
		if(profile) {
			writer->profile.assign(profile, profile + size);
			writer->has_profile = TRUE;
		}
	}
	return (JxlEncoderSetColorEncoding(writer->encoder, &enc) == JXL_ENC_SUCCESS) ? TRUE : FALSE;
}

// the encoder for a still image or an animation, set up from its first frame
static BOOL
StartEncoder(JXLWriter *writer, FIBITMAP *dib, int flags, BOOL animation, uint32_t width, uint32_t height, LONG loop) {
	const int quality = flags & 0x7F;
	const BOOL lossless = (((flags & JXL_LOSSLESS) == JXL_LOSSLESS) || (quality >= 100)) ? TRUE : FALSE;
	int effort = (flags >> 16) & 0xF;
	if((effort < 1) || (effort > 10)) {
		effort = 7;
	}

	writer->encoder = JxlEncoderCreate(NULL);
	if(!writer->encoder) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
		return FALSE;
	}
	writer->runner = CreateRunner(width, height);
	if(writer->runner && (JxlEncoderSetParallelRunner(writer->encoder, JxlResizableParallelRunner, writer->runner) != JXL_ENC_SUCCESS)) {
		return FALSE;
	}

	JxlBasicInfo info;
	JxlEncoderInitBasicInfo(&info);
	info.xsize = width;
	info.ysize = height;
	switch(writer->format.data_type) {
		case JXL_TYPE_UINT8:
			info.bits_per_sample = 8;
			break;
		case JXL_TYPE_UINT16:
			info.bits_per_sample = 16;
			break;
		default:
			info.bits_per_sample = 32;
			info.exponent_bits_per_sample = 8;
			break;
	}
	info.num_color_channels = (writer->format.num_channels < 3) ? 1 : 3;
	if(writer->alpha) {
		info.alpha_bits = info.bits_per_sample;
		info.alpha_exponent_bits = info.exponent_bits_per_sample;
		info.num_extra_channels = 1;
	}
	info.uses_original_profile = lossless ? JXL_TRUE : JXL_FALSE;
	if(animation) {
		info.have_animation = JXL_TRUE;
		info.animation.tps_numerator = 1000;
		info.animation.tps_denominator = 1;
		info.animation.num_loops = (loop > 0) ? (uint32_t)loop : 0;
	}
	if(JxlEncoderSetBasicInfo(writer->encoder, &info) != JXL_ENC_SUCCESS) {
		ReportEncoderError(writer->encoder, "Cannot encode the image");
		return FALSE;
	}
	if(writer->alpha) {
		JxlExtraChannelInfo extra;
		JxlEncoderInitExtraChannelInfo(JXL_CHANNEL_ALPHA, &extra);
		extra.bits_per_sample = info.alpha_bits;
		extra.exponent_bits_per_sample = info.alpha_exponent_bits;
		if(JxlEncoderSetExtraChannelInfo(writer->encoder, 0, &extra) != JXL_ENC_SUCCESS) {
			ReportEncoderError(writer->encoder, "Cannot encode the alpha channel");
			return FALSE;
		}
	}
	if(!SetColors(writer, dib, (animation && !lossless) ? TRUE : FALSE)) {
		ReportEncoderError(writer->encoder, "Cannot encode the colors");
		return FALSE;
	}
	if(!AddMetadataBoxes(writer, dib)) {
		ReportEncoderError(writer->encoder, "Cannot write the metadata");
		return FALSE;
	}

	writer->settings = JxlEncoderFrameSettingsCreate(writer->encoder, NULL);
	if(!writer->settings) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
		return FALSE;
	}
	if((JxlEncoderFrameSettingsSetOption(writer->settings, JXL_ENC_FRAME_SETTING_EFFORT, effort) != JXL_ENC_SUCCESS) ||
		(lossless && (JxlEncoderSetFrameLossless(writer->settings, JXL_TRUE) != JXL_ENC_SUCCESS)) ||
		(!lossless && (JxlEncoderSetFrameDistance(writer->settings, (quality > 0) ? JxlEncoderDistanceFromQuality((float)quality) : 1.0f) != JXL_ENC_SUCCESS))) {
		ReportEncoderError(writer->encoder, "Cannot set the encoding options");
		return FALSE;
	}
	writer->canvas_width = width;
	writer->canvas_height = height;
	writer->animation = animation;
	return TRUE;
}

template <class T> static inline T
CanvasSample(float v, float one) {
	return (T)((v <= 0) ? 0 : (v >= one) ? one : v + 0.5f);
}

template <> inline float
CanvasSample<float>(float v, float) {
	return v;
}

// straight alpha, as GIF and APNG compose: the frame over the canvas, or in its place
template <class T> static void
DrawFrame(BYTE *canvas_bits, uint32_t canvas_width, const BYTE *frame_bits, uint32_t x0, uint32_t y0, uint32_t width, uint32_t height, BOOL over, float one) {
	for(uint32_t y = 0; y < height; y++) {
		T *dst = (T*)canvas_bits + ((size_t)(y0 + y) * canvas_width + x0) * 4;
		const T *src = (const T*)frame_bits + (size_t)y * width * 4;
		if(!over) {
			memcpy(dst, src, (size_t)width * 4 * sizeof(T));
			continue;
		}
		for(uint32_t x = 0; x < width; x++, src += 4, dst += 4) {
			const float sa = (float)src[3] / one;
			if(!(sa > 0)) {
				continue;
			}
			if(sa >= 1) {
				dst[0] = src[0];
				dst[1] = src[1];
				dst[2] = src[2];
				dst[3] = src[3];
				continue;
			}
			const float da = ((float)dst[3] <= 0) ? 0 : ((float)dst[3] >= one) ? 1 : (float)dst[3] / one;
			const float behind = da * (1 - sa);
			const float a = sa + behind;
			for(int c = 0; c < 3; c++) {
				dst[c] = CanvasSample<T>(((float)src[c] * sa + (float)dst[c] * behind) / a, one);
			}
			dst[3] = CanvasSample<T>(a * one, one);
		}
	}
}

// a frame drawn on the writer's canvas, written as the whole canvas: nothing is left for a decoder to blend
static void
AddWholeFrame(JXLWriter *writer, FIBITMAP *frame, uint32_t x0, uint32_t y0, uint32_t width, uint32_t height, BOOL empty, LONG disposal, LONG blend, LONG frametime) {
	const size_t pixel = (size_t)writer->format.num_channels * SampleBytes(writer->format.data_type);
	if(writer->canvas.empty()) {
		writer->canvas.assign((size_t)writer->canvas_width * writer->canvas_height * pixel, 0);
	}
	std::vector<BYTE> before;
	if(disposal == 3) {
		before = writer->canvas;
	}
	BOOL clamped = FALSE;
	if(!empty) {
		std::vector<BYTE> samples;
		FrameSamples(frame, writer, width, height, samples, &clamped);
		const BOOL over = (blend == 0) ? TRUE : FALSE;
		switch(writer->format.data_type) {
			case JXL_TYPE_UINT8:
				DrawFrame<BYTE>(&writer->canvas[0], writer->canvas_width, &samples[0], x0, y0, width, height, over, 255.0f);
				break;
			case JXL_TYPE_UINT16:
				DrawFrame<WORD>(&writer->canvas[0], writer->canvas_width, &samples[0], x0, y0, width, height, over, 65535.0f);
				break;
			default:
				DrawFrame<float>(&writer->canvas[0], writer->canvas_width, &samples[0], x0, y0, width, height, over, 1.0f);
				break;
		}
	}

	JxlFrameHeader header;
	JxlEncoderInitFrameHeader(&header);
	header.duration = (frametime > 0) ? (uint32_t)frametime : 1;
	if((JxlEncoderSetFrameHeader(writer->settings, &header) != JXL_ENC_SUCCESS) ||
		(JxlEncoderSetExtraChannelBlendInfo(writer->settings, 0, &header.layer_info.blend_info) != JXL_ENC_SUCCESS) ||
		(JxlEncoderAddImageFrame(writer->settings, &writer->format, &writer->canvas[0], writer->canvas.size()) != JXL_ENC_SUCCESS)) {
		ReportEncoderError(writer->encoder, "Cannot encode a frame");
		throw (int)0;
	}
	if(clamped) {
		FreeImage_OutputMessageProc(s_format_id, "Warning: NaN and infinite samples are written as 0 and the largest float");
	}

	// what the next frame is drawn on
	if(disposal == 3) {
		writer->canvas.swap(before);
	} else if((disposal == 2) && !empty) {
		const size_t row = (size_t)writer->canvas_width * pixel;
		for(uint32_t y = 0; y < height; y++) {
			memset(&writer->canvas[(size_t)(y0 + y) * row + (size_t)x0 * pixel], 0, (size_t)width * pixel);
		}
	}
}

// a frame placed on the canvas; for a still image the whole canvas
static BOOL
AddFrame(JXLWriter *writer, FIBITMAP *dib) {
	FIBITMAP *converted = NULL;
	if(!ConvertToLayout(dib, writer, &converted)) {
		FreeImage_OutputMessageProc(s_format_id, "Cannot convert a frame to the file's pixel format");
		return FALSE;
	}
	FIBITMAP *frame = converted ? converted : dib;

	// later frames are converted to the first frame's profile; to sRGB, every frame
	FIBITMAP *recolored = NULL;
	if(writer->animation && ((writer->frames > 0) || (writer->frame_mode == JXL_FRAMES_SRGB))) {
		if(!ConvertToFileProfile(frame, writer->has_profile ? &writer->profile[0] : NULL, writer->has_profile ? (DWORD)writer->profile.size() : 0, &recolored)) {
			FreeImage_OutputMessageProc(s_format_id, "Warning: a frame's colors could not be converted to the file's ICC profile");
		}
		if(recolored) {
			frame = recolored;
		}
	}

	BOOL ok = FALSE;
	try {
		uint32_t x0 = 0, y0 = 0;
		uint32_t width = FreeImage_GetWidth(frame);
		uint32_t height = FreeImage_GetHeight(frame);
		JxlFrameHeader header;
		JxlEncoderInitFrameHeader(&header);

		if(writer->animation) {
			LONG value = 0;
			// GIF numbering: 2 restores the background, 3 the previous canvas
			LONG disposal = 1;
			LONG blend = 0;
			LONG frametime = 100;
			if(GetAnimTag(dib, "FrameLeft", FIDT_SHORT, &value)) {
				x0 = (uint32_t)value;
			}
			if(GetAnimTag(dib, "FrameTop", FIDT_SHORT, &value)) {
				y0 = (uint32_t)value;
			}
			GetAnimTag(dib, "DisposalMethod", FIDT_BYTE, &disposal);
			GetAnimTag(dib, "BlendMethod", FIDT_BYTE, &blend);
			GetAnimTag(dib, "FrameTime", FIDT_LONG, &frametime);

			// a frame off the canvas keeps its time as one transparent pixel
			BOOL empty = FALSE;
			if((x0 >= writer->canvas_width) || (y0 >= writer->canvas_height)) {
				x0 = y0 = 0;
				width = height = 1;
				empty = TRUE;
			}
			if(width > writer->canvas_width - x0) {
				width = writer->canvas_width - x0;
			}
			if(height > writer->canvas_height - y0) {
				height = writer->canvas_height - y0;
			}

			if(writer->frame_mode == JXL_FRAMES_WHOLE) {
				AddWholeFrame(writer, frame, x0, y0, width, height, empty, disposal, blend, frametime);
			} else {
				const BOOL leave = ((disposal != 2) && (disposal != 3)) ? TRUE : FALSE;
				if(leave) {
					writer->nontrivial = TRUE;
				}
				const BOOL for_next = (writer->nontrivial && (disposal != 3)) ? TRUE : FALSE;

				// the previous frame's rectangle back to transparent, as libjxl's APNG reader does
				if(writer->clear_previous) {
					JxlFrameHeader clear;
					JxlEncoderInitFrameHeader(&clear);
					clear.duration = 0;
					clear.layer_info.have_crop = JXL_TRUE;
					clear.layer_info.crop_x0 = (int32_t)writer->prev_x;
					clear.layer_info.crop_y0 = (int32_t)writer->prev_y;
					clear.layer_info.xsize = writer->prev_width;
					clear.layer_info.ysize = writer->prev_height;
					clear.layer_info.blend_info.blendmode = JXL_BLEND_REPLACE;
					clear.layer_info.blend_info.source = 1;
					clear.layer_info.save_as_reference = 1;
					std::vector<BYTE> blank((size_t)writer->prev_width * writer->prev_height * writer->format.num_channels * SampleBytes(writer->format.data_type), 0);
					if((JxlEncoderSetFrameHeader(writer->settings, &clear) != JXL_ENC_SUCCESS) ||
						(JxlEncoderSetExtraChannelBlendInfo(writer->settings, 0, &clear.layer_info.blend_info) != JXL_ENC_SUCCESS) ||
						(JxlEncoderAddImageFrame(writer->settings, &writer->format, &blank[0], blank.size()) != JXL_ENC_SUCCESS)) {
						ReportEncoderError(writer->encoder, "Cannot encode a frame");
						throw (int)0;
					}
				}

				header.duration = (frametime > 0) ? (uint32_t)frametime : 1;
				header.layer_info.have_crop = ((x0 != 0) || (y0 != 0) || (width != writer->canvas_width) || (height != writer->canvas_height)) ? JXL_TRUE : JXL_FALSE;
				header.layer_info.crop_x0 = (int32_t)x0;
				header.layer_info.crop_y0 = (int32_t)y0;
				header.layer_info.xsize = width;
				header.layer_info.ysize = height;
				header.layer_info.blend_info.blendmode = ((blend == 0) || empty) ? JXL_BLEND_BLEND : JXL_BLEND_REPLACE;
				header.layer_info.blend_info.source = 1;
				header.layer_info.blend_info.alpha = 0;
				header.layer_info.blend_info.clamp = JXL_FALSE;
				header.layer_info.save_as_reference = for_next ? 1 : 0;

				writer->clear_previous = (writer->nontrivial && (disposal == 2) && !empty) ? TRUE : FALSE;
				writer->prev_x = x0;
				writer->prev_y = y0;
				writer->prev_width = width;
				writer->prev_height = height;

				if((JxlEncoderSetFrameHeader(writer->settings, &header) != JXL_ENC_SUCCESS) ||
					(JxlEncoderSetExtraChannelBlendInfo(writer->settings, 0, &header.layer_info.blend_info) != JXL_ENC_SUCCESS)) {
					ReportEncoderError(writer->encoder, "Cannot encode a frame");
					throw (int)0;
				}

				std::vector<BYTE> samples;
				BOOL clamped = FALSE;
				if(empty) {
					samples.assign(writer->format.num_channels * SampleBytes(writer->format.data_type), 0);
				} else {
					FrameSamples(frame, writer, width, height, samples, &clamped);
				}
				if(JxlEncoderAddImageFrame(writer->settings, &writer->format, &samples[0], samples.size()) != JXL_ENC_SUCCESS) {
					ReportEncoderError(writer->encoder, "Cannot encode a frame");
					throw (int)0;
				}
				if(clamped) {
					FreeImage_OutputMessageProc(s_format_id, "Warning: NaN and infinite samples are written as 0 and the largest float");
				}
			}
		} else {
			std::vector<BYTE> samples;
			BOOL clamped = FALSE;
			FrameSamples(frame, writer, width, height, samples, &clamped);
			if(JxlEncoderAddImageFrame(writer->settings, &writer->format, &samples[0], samples.size()) != JXL_ENC_SUCCESS) {
				ReportEncoderError(writer->encoder, "Cannot encode the image");
				throw (int)0;
			}
			if(clamped) {
				FreeImage_OutputMessageProc(s_format_id, "Warning: NaN and infinite samples are written as 0 and the largest float");
			}
		}
		writer->frames++;
		ok = TRUE;
	} catch(int) {
		ok = FALSE;
	} catch(std::bad_alloc&) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
		ok = FALSE;
	}

	if(recolored) {
		FreeImage_Unload(recolored);
	}
	if(converted) {
		FreeImage_Unload(converted);
	}
	return ok;
}

static BOOL
WriteStill(JXLWriter *writer, FreeImageIO *io, fi_handle handle, FIBITMAP *dib, int flags) {
	if(!ChooseLayout(dib, FALSE, writer)) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_UNSUPPORTED_FORMAT);
		return FALSE;
	}
	if(!StartEncoder(writer, dib, flags, FALSE, FreeImage_GetWidth(dib), FreeImage_GetHeight(dib), 0)) {
		return FALSE;
	}
	if(!AddFrame(writer, dib)) {
		return FALSE;
	}
	JxlEncoderCloseInput(writer->encoder);
	return FlushOutput(writer, io, handle);
}

// an animation from its first two pages: the canvas covers both and what they ask for
static BOOL
StartAnimation(JXLWriter *writer, FIBITMAP *first, FIBITMAP *second, int flags) {
	uint32_t width = 0, height = 0;
	LONG value = 0, loop = 0;
	FIBITMAP *pages[2] = { first, second };
	for(int i = 0; i < 2; i++) {
		LONG left = 0, top = 0;
		GetAnimTag(pages[i], "FrameLeft", FIDT_SHORT, &left);
		GetAnimTag(pages[i], "FrameTop", FIDT_SHORT, &top);
		const uint32_t right = (uint32_t)left + FreeImage_GetWidth(pages[i]);
		const uint32_t bottom = (uint32_t)top + FreeImage_GetHeight(pages[i]);
		if(right > width) {
			width = right;
		}
		if(bottom > height) {
			height = bottom;
		}
		if(GetAnimTag(pages[i], "LogicalWidth", FIDT_SHORT, &value) && ((uint32_t)value > width)) {
			width = (uint32_t)value;
		}
		if(GetAnimTag(pages[i], "LogicalHeight", FIDT_SHORT, &value) && ((uint32_t)value > height)) {
			height = (uint32_t)value;
		}
	}
	GetAnimTag(first, "Loop", FIDT_LONG, &loop);
	if(!ChooseLayout(first, TRUE, writer)) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_UNSUPPORTED_FORMAT);
		return FALSE;
	}
	return StartEncoder(writer, first, flags, TRUE, width, height, loop);
}

