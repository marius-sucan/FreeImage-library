static void
ChooseOutput(const JXLReader *reader, BOOL playback, JXLOutput *out) {
	const JxlBasicInfo& info = reader->info;
	const BOOL alpha = (info.alpha_bits > 0) ? TRUE : FALSE;
	const BOOL grey = (info.num_color_channels == 1) ? TRUE : FALSE;
	const BOOL real = ((info.exponent_bits_per_sample > 0) || (info.bits_per_sample > 16)) ? TRUE : FALSE;
	const BOOL deep = (info.bits_per_sample > 8) ? TRUE : FALSE;

	memset(out, 0, sizeof(*out));
	out->format.endianness = JXL_NATIVE_ENDIAN;
	out->format.align = 0;

	if(playback || (!real && !deep)) {
		out->type = FIT_BITMAP;
		out->format.data_type = JXL_TYPE_UINT8;
		if(grey && !alpha && !playback) {
			out->bpp = 8;
			out->format.num_channels = 1;
		} else {
			out->bpp = (alpha || playback) ? 32 : 24;
			out->format.num_channels = (alpha || playback) ? 4 : 3;
#if FREEIMAGE_COLORORDER == FREEIMAGE_COLORORDER_BGR
			out->swap_rb = TRUE;
#endif
		}
	} else if(real) {
		out->format.data_type = JXL_TYPE_FLOAT;
		if(grey && !alpha) {
			out->type = FIT_FLOAT;
			out->bpp = 32;
			out->format.num_channels = 1;
		} else {
			out->type = alpha ? FIT_RGBAF : FIT_RGBF;
			out->bpp = alpha ? 128 : 96;
			out->format.num_channels = alpha ? 4 : 3;
		}
	} else {
		out->format.data_type = JXL_TYPE_UINT16;
		if(grey && !alpha) {
			out->type = FIT_UINT16;
			out->bpp = 16;
			out->format.num_channels = 1;
		} else {
			out->type = alpha ? FIT_RGBA16 : FIT_RGB16;
			out->bpp = alpha ? 64 : 48;
			out->format.num_channels = alpha ? 4 : 3;
		}
	}
	out->grey_to_rgb = (grey && (out->format.num_channels >= 3)) ? TRUE : FALSE;
}

// the Little CMS layout of a bitmap row
static cmsUInt32Number
SinkFormat(const JXLOutput *out) {
	const BOOL alpha = (out->format.num_channels == 2) || (out->format.num_channels == 4);
	switch(out->format.data_type) {
		case JXL_TYPE_UINT8:
			if(out->format.num_channels == 1) {
				return TYPE_GRAY_8;
			}
			if(out->swap_rb) {
				return alpha ? TYPE_BGRA_8 : TYPE_BGR_8;
			}
			return alpha ? TYPE_RGBA_8 : TYPE_RGB_8;
		case JXL_TYPE_UINT16:
			if(out->format.num_channels == 1) {
				return TYPE_GRAY_16;
			}
			return alpha ? TYPE_RGBA_16 : TYPE_RGB_16;
		default:
			if(out->format.num_channels == 1) {
				return TYPE_GRAY_FLT;
			}
			return alpha ? TYPE_RGBA_FLT : TYPE_RGB_FLT;
	}
}

// libjxl's linear output to the original profile; NULL when Little CMS cannot do it
static cmsHTRANSFORM
GetTransform(JXLReader *reader, const JXLOutput *out) {
	const cmsUInt32Number out_format = SinkFormat(out);
	for(size_t i = 0; i < reader->transforms.size(); i++) {
		if(reader->transforms[i].out_format == out_format) {
			return reader->transforms[i].transform;
		}
	}
	if(reader->data_icc.empty() || reader->orig_icc.empty()) {
		return NULL;
	}
	const BOOL alpha = (out->format.num_channels == 2) || (out->format.num_channels == 4);
	const cmsUInt32Number in_format = (out->format.num_channels == 1) ? TYPE_GRAY_FLT : (alpha ? TYPE_RGBA_FLT : TYPE_RGB_FLT);

	cmsHTRANSFORM transform = NULL;
	cmsHPROFILE src = cmsOpenProfileFromMem(&reader->data_icc[0], (cmsUInt32Number)reader->data_icc.size());
	cmsHPROFILE dst = cmsOpenProfileFromMem(&reader->orig_icc[0], (cmsUInt32Number)reader->orig_icc.size());
	if(src && dst) {
		// what libjxl's own CMS uses: thread-safe, black point compensated
		const cmsUInt32Number intent = cmsGetHeaderRenderingIntent(dst);
		transform = cmsCreateTransform(src, in_format, dst, out_format, intent,
			cmsFLAGS_NOCACHE | cmsFLAGS_BLACKPOINTCOMPENSATION | cmsFLAGS_HIGHRESPRECALC | cmsFLAGS_COPY_ALPHA);
	}
	if(src) {
		cmsCloseProfile(src);
	}
	if(dst) {
		cmsCloseProfile(dst);
	}
	if(transform) {
		JXLTransform entry;
		entry.out_format = out_format;
		entry.transform = transform;
		try {
			reader->transforms.push_back(entry);
		} catch(std::bad_alloc&) {
			cmsDeleteTransform(transform);
			throw;
		}
	}
	return transform;
}

// decided once per file, so a header-only load describes what a full load returns
static void
ChooseRoute(JXLReader *reader) {
	reader->route = JXL_ROUTE_AS_DECODED;
	if(reader->info.uses_original_profile) {
		return;
	}
	if(reader->orig_encoded && reader->data_encoded && SameEncoding(&reader->orig_enc, &reader->data_enc)) {
		return;
	}
	// libjxl renders XYB to linear sRGB when it cannot render the original colours
	JXLOutput out;
	ChooseOutput(reader, FALSE, &out);
	const DWORD space = ProfileColorSpace(reader->orig_icc);
	const BOOL grey = (reader->info.num_color_channels == 1) ? TRUE : FALSE;
	if(!out.grey_to_rgb && (space == (DWORD)(grey ? FICMS_COLORSPACE_GRAY : FICMS_COLORSPACE_RGB)) && GetTransform(reader, &out)) {
		reader->route = JXL_ROUTE_TO_ICC;
		return;
	}
	reader->route = JXL_ROUTE_TO_SRGB;
}

// the file's route, unless the page's layout cannot take the original profile (grey playback)
static JXLRoute
PageRoute(const JXLReader *reader, const JXLOutput *out) {
	if((reader->route == JXL_ROUTE_TO_ICC) && out->grey_to_rgb) {
		return JXL_ROUTE_TO_SRGB;
	}
	return reader->route;
}

static void
AttachColor(FIBITMAP *dib, const JXLReader *reader, const JXLOutput *out, JXLRoute route) {
	unsigned primaries = 2, transfer = 2;

	if(route == JXL_ROUTE_TO_SRGB) {
		SetCICPMetadata(dib, 1, 13, 0, TRUE);
		return;
	}
	if(route == JXL_ROUTE_TO_ICC) {
		FreeImage_CreateICCProfile(dib, (void*)&reader->orig_icc[0], (long)reader->orig_icc.size());
		if(reader->orig_encoded && EncodingToCICP(&reader->orig_enc, &primaries, &transfer)) {
			SetCICPMetadata(dib, primaries, transfer, 0, TRUE);
		}
		return;
	}
	if(reader->data_encoded) {
		if(EncodingToCICP(&reader->data_enc, &primaries, &transfer)) {
			SetCICPMetadata(dib, primaries, transfer, 0, TRUE);
		}
		// sRGB is what an untagged bitmap means
		if(IsSRGB(&reader->data_enc)) {
			return;
		}
	}
	// a grey profile does not describe RGB samples
	if(!out->grey_to_rgb && !reader->data_icc.empty() && (reader->data_icc.size() <= (size_t)LONG_MAX)) {
		FreeImage_CreateICCProfile(dib, (void*)&reader->data_icc[0], (long)reader->data_icc.size());
	}
}

// ----------------------------------------------------------
//   Metadata
// ----------------------------------------------------------

static void
AttachMetadata(FIBITMAP *dib, const JXLReader *reader) {
	// Exif: a 4-byte big-endian offset to the TIFF header, then the Exif data
	if(reader->exif.size() > 4) {
		const BYTE *p = &reader->exif[0];
		const uint32_t offset = ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) | ((uint32_t)p[2] << 8) | (uint32_t)p[3];
		const size_t size = reader->exif.size() - 4;
		if((offset < size) && (size - offset <= (size_t)UINT_MAX)) {
			const unsigned length = (unsigned)(size - offset);
			psd_read_exif_profile_raw(dib, p + 4 + offset, length);
			psd_read_exif_profile(dib, p + 4 + offset, length);
		}
	}
	// XMP
	if(!reader->xmp.empty() && (reader->xmp.size() <= (size_t)UINT_MAX)) {
		FITAG *tag = FreeImage_CreateTag();
		if(tag) {
			FreeImage_SetTagKey(tag, g_TagLib_XMPFieldName);
			FreeImage_SetTagLength(tag, (DWORD)reader->xmp.size());
			FreeImage_SetTagCount(tag, (DWORD)reader->xmp.size());
			FreeImage_SetTagType(tag, FIDT_ASCII);
			FreeImage_SetTagValue(tag, &reader->xmp[0]);
			FreeImage_SetMetadata(FIMD_XMP, dib, FreeImage_GetTagKey(tag), tag);
			FreeImage_DeleteTag(tag);
		}
	}
}

static LONG
TicksToMs(const JxlBasicInfo& info, uint32_t ticks) {
	if((info.animation.tps_numerator == 0) || (info.animation.tps_denominator == 0)) {
		return 0;
	}
	const double ms = (double)ticks * 1000.0 * (double)info.animation.tps_denominator / (double)info.animation.tps_numerator;
	return (ms >= (double)LONG_MAX) ? LONG_MAX : (LONG)(ms + 0.5);
}

// a JXL page is the whole composited canvas, as AVIF frames are
static void
AttachAnimation(FIBITMAP *dib, const JXLReader *reader, int page) {
	if(!reader->info.have_animation || (reader->durations.size() < 2)) {
		return;
	}
	const LONG frametime = TicksToMs(reader->info, reader->durations[page]);
	const WORD left = 0;
	const WORD top = 0;
	const BYTE disposal = 1;
	const BYTE blend = 1;
	SetAnimTag(dib, "FrameTime", ANIMTAG_FRAMETIME, FIDT_LONG, 1, 4, &frametime);
	SetAnimTag(dib, "FrameLeft", ANIMTAG_FRAMELEFT, FIDT_SHORT, 1, 2, &left);
	SetAnimTag(dib, "FrameTop", ANIMTAG_FRAMETOP, FIDT_SHORT, 1, 2, &top);
	SetAnimTag(dib, "DisposalMethod", ANIMTAG_DISPOSALMETHOD, FIDT_BYTE, 1, 1, &disposal);
	SetAnimTag(dib, "BlendMethod", ANIMTAG_BLENDMETHOD, FIDT_BYTE, 1, 1, &blend);

	// on every frame, so deleting page 0 keeps them; SHORTs saturate
	const WORD logicalwidth = (WORD)((reader->info.xsize > 0xFFFF) ? 0xFFFF : reader->info.xsize);
	const WORD logicalheight = (WORD)((reader->info.ysize > 0xFFFF) ? 0xFFFF : reader->info.ysize);
	// num_loops 0 is infinite, as Loop 0 is
	const LONG loop = (reader->info.animation.num_loops > (uint32_t)LONG_MAX) ? LONG_MAX : (LONG)reader->info.animation.num_loops;
	SetAnimTag(dib, "LogicalWidth", ANIMTAG_LOGICALWIDTH, FIDT_SHORT, 1, 2, &logicalwidth);
	SetAnimTag(dib, "LogicalHeight", ANIMTAG_LOGICALHEIGHT, FIDT_SHORT, 1, 2, &logicalheight);
	SetAnimTag(dib, "Loop", ANIMTAG_LOOP, FIDT_LONG, 1, 4, &loop);
}

