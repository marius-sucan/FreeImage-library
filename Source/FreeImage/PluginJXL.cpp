// Exif and XMP larger than this are skipped (a compressed box can expand without bound)
#define FI_JXL_MAX_BOX ((size_t)64 << 20)

static void
ReadColorEncoding(JXLReader *reader, JxlDecoder *dec) {
	size_t size = 0;
	reader->orig_encoded = (JxlDecoderGetColorAsEncodedProfile(dec, JXL_COLOR_PROFILE_TARGET_ORIGINAL, &reader->orig_enc) == JXL_DEC_SUCCESS) ? TRUE : FALSE;
	if((JxlDecoderGetICCProfileSize(dec, JXL_COLOR_PROFILE_TARGET_ORIGINAL, &size) == JXL_DEC_SUCCESS) && (size > 0)) {
		reader->orig_icc.resize(size);
		if(JxlDecoderGetColorAsICCProfile(dec, JXL_COLOR_PROFILE_TARGET_ORIGINAL, &reader->orig_icc[0], size) != JXL_DEC_SUCCESS) {
			reader->orig_icc.clear();
		}
	}
	reader->data_encoded = (JxlDecoderGetColorAsEncodedProfile(dec, JXL_COLOR_PROFILE_TARGET_DATA, &reader->data_enc) == JXL_DEC_SUCCESS) ? TRUE : FALSE;
	size = 0;
	if((JxlDecoderGetICCProfileSize(dec, JXL_COLOR_PROFILE_TARGET_DATA, &size) == JXL_DEC_SUCCESS) && (size > 0)) {
		reader->data_icc.resize(size);
		if(JxlDecoderGetColorAsICCProfile(dec, JXL_COLOR_PROFILE_TARGET_DATA, &reader->data_icc[0], size) != JXL_DEC_SUCCESS) {
			reader->data_icc.clear();
		}
	}
}

static BOOL
ParseHeaders(JXLReader *reader) {
	JxlDecoder *dec = JxlDecoderCreate(NULL);
	if(!dec) {
		FreeImage_OutputMessageProc(s_format_id, FI_MSG_ERROR_MEMORY);
		return FALSE;
	}

	std::vector<BYTE> *box = NULL;	// the box being captured
	size_t box_used = 0;
	BOOL done = FALSE;

	if((JxlDecoderSubscribeEvents(dec, JXL_DEC_BASIC_INFO | JXL_DEC_COLOR_ENCODING | JXL_DEC_FRAME | JXL_DEC_BOX | JXL_DEC_BOX_COMPLETE) != JXL_DEC_SUCCESS) ||
		(JxlDecoderSetDecompressBoxes(dec, JXL_TRUE) != JXL_DEC_SUCCESS) ||
		(JxlDecoderSetInput(dec, &reader->data[0], reader->data.size()) != JXL_DEC_SUCCESS)) {
		JxlDecoderDestroy(dec);
		return FALSE;
	}
	JxlDecoderCloseInput(dec);

	while(!done) {
		const JxlDecoderStatus status = JxlDecoderProcessInput(dec);
		switch(status) {
			case JXL_DEC_BASIC_INFO:
				if(JxlDecoderGetBasicInfo(dec, &reader->info) == JXL_DEC_SUCCESS) {
					reader->have_info = TRUE;
					for(uint32_t i = 0; i < reader->info.num_extra_channels; i++) {
						JxlExtraChannelInfo extra;
						if((JxlDecoderGetExtraChannelInfo(dec, i, &extra) == JXL_DEC_SUCCESS) && (extra.type == JXL_CHANNEL_BLACK) && !reader->cmyk) {
							reader->cmyk = TRUE;
							reader->black_index = i;
						}
					}
				}
				break;

			case JXL_DEC_COLOR_ENCODING:
				ReadColorEncoding(reader, dec);
				break;

			case JXL_DEC_FRAME:
			{
				JxlFrameHeader header;
				if(JxlDecoderGetFrameHeader(dec, &header) == JXL_DEC_SUCCESS) {
					reader->durations.push_back(header.duration);
				}
				break;
			}

			case JXL_DEC_BOX:
			{
				if(box) {
					const size_t unused = JxlDecoderReleaseBoxBuffer(dec);
					box->resize(box->size() - unused);
				}
				// a box nobody claimed is skipped by the decoder
				box = NULL;
				JxlBoxType type;
				if(JxlDecoderGetBoxType(dec, type, JXL_TRUE) != JXL_DEC_SUCCESS) {
					break;
				}
				if((memcmp(type, "Exif", 4) == 0) && reader->exif.empty()) {
					box = &reader->exif;
				} else if((memcmp(type, "xml ", 4) == 0) && reader->xmp.empty()) {
					box = &reader->xmp;
				} else {
					break;
				}
				uint64_t size = 0;
				JxlBoxType raw;
				size_t capacity = 65536;
				if((JxlDecoderGetBoxType(dec, raw, JXL_FALSE) == JXL_DEC_SUCCESS) && (memcmp(raw, "brob", 4) != 0) &&
					(JxlDecoderGetBoxSizeContents(dec, &size) == JXL_DEC_SUCCESS) && (size > 0)) {
					capacity = (size < (uint64_t)FI_JXL_MAX_BOX) ? (size_t)size : FI_JXL_MAX_BOX;
				}
				box->resize(capacity);
				box_used = 0;
				if(JxlDecoderSetBoxBuffer(dec, &(*box)[0], box->size()) != JXL_DEC_SUCCESS) {
					box->clear();
					box = NULL;
				}
				break;
			}

			case JXL_DEC_BOX_NEED_MORE_OUTPUT:
			{
				if(!box) {
					done = TRUE;
					break;
				}
				const size_t unused = JxlDecoderReleaseBoxBuffer(dec);
				box_used = box->size() - unused;
				if(box->size() >= FI_JXL_MAX_BOX) {
					FreeImage_OutputMessageProc(s_format_id, "Warning: a metadata box larger than %u MB is skipped", (unsigned)(FI_JXL_MAX_BOX >> 20));
					box->clear();
					box = NULL;
					break;
				}
				const size_t grown = (box->size() > FI_JXL_MAX_BOX / 2) ? FI_JXL_MAX_BOX : box->size() * 2;
				box->resize(grown);
				if(JxlDecoderSetBoxBuffer(dec, &(*box)[box_used], box->size() - box_used) != JXL_DEC_SUCCESS) {
					box->clear();
					box = NULL;
				}
				break;
			}

			case JXL_DEC_BOX_COMPLETE:
				if(box) {
					const size_t unused = JxlDecoderReleaseBoxBuffer(dec);
					box->resize(box->size() - unused);
					box = NULL;
				}
				break;

			case JXL_DEC_SUCCESS:
				if(box) {
					const size_t unused = JxlDecoderReleaseBoxBuffer(dec);
					box->resize(box->size() - unused);
					box = NULL;
				}
				done = TRUE;
				break;

			default:
				// cut short or damaged: keep what was read
				if(box) {
					box->clear();
					box = NULL;
				}
				reader->cut = TRUE;
				done = TRUE;
				break;
		}
	}

	JxlDecoderDestroy(dec);
	return reader->have_info;
}

