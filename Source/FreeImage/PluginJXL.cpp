// ICC header data colour space
static DWORD
ProfileColorSpace(const std::vector<BYTE>& icc) {
	if(icc.size() < 132) {
		return 0;
	}
	return ((DWORD)icc[16] << 24) | ((DWORD)icc[17] << 16) | ((DWORD)icc[18] << 8) | (DWORD)icc[19];
}

