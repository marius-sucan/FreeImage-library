static BOOL
IsSRGB(const JxlColorEncoding *enc) {
	if(enc->white_point != JXL_WHITE_POINT_D65 || enc->transfer_function != JXL_TRANSFER_FUNCTION_SRGB) {
		return FALSE;
	}
	if(enc->color_space == JXL_COLOR_SPACE_GRAY) {
		return TRUE;
	}
	return ((enc->color_space == JXL_COLOR_SPACE_RGB) && (enc->primaries == JXL_PRIMARIES_SRGB)) ? TRUE : FALSE;
}

static BOOL
SameEncoding(const JxlColorEncoding *a, const JxlColorEncoding *b) {
	if((a->color_space != b->color_space) || (a->white_point != b->white_point) || (a->transfer_function != b->transfer_function)) {
		return FALSE;
	}
	if((a->transfer_function == JXL_TRANSFER_FUNCTION_GAMMA) && (a->gamma != b->gamma)) {
		return FALSE;
	}
	if((a->white_point == JXL_WHITE_POINT_CUSTOM) && memcmp(a->white_point_xy, b->white_point_xy, sizeof(a->white_point_xy))) {
		return FALSE;
	}
	if(a->color_space == JXL_COLOR_SPACE_GRAY) {
		return TRUE;
	}
	if(a->primaries != b->primaries) {
		return FALSE;
	}
	if((a->primaries == JXL_PRIMARIES_CUSTOM) &&
		(memcmp(a->primaries_red_xy, b->primaries_red_xy, sizeof(a->primaries_red_xy)) ||
		 memcmp(a->primaries_green_xy, b->primaries_green_xy, sizeof(a->primaries_green_xy)) ||
		 memcmp(a->primaries_blue_xy, b->primaries_blue_xy, sizeof(a->primaries_blue_xy)))) {
		return FALSE;
	}
	return TRUE;
}

// ITU-T H.273 code points of an encoding; FALSE when neither primaries nor transfer has one
static BOOL
EncodingToCICP(const JxlColorEncoding *enc, unsigned *primaries, unsigned *transfer) {
	*primaries = 2;
	*transfer = 2;
	if(enc->color_space == JXL_COLOR_SPACE_GRAY) {
		if(enc->white_point == JXL_WHITE_POINT_D65) {
			*primaries = 1;
		}
	} else if(enc->color_space == JXL_COLOR_SPACE_RGB) {
		if(enc->white_point == JXL_WHITE_POINT_D65) {
			switch(enc->primaries) {
				case JXL_PRIMARIES_SRGB:
					*primaries = 1;
					break;
				case JXL_PRIMARIES_2100:
					*primaries = 9;
					break;
				case JXL_PRIMARIES_P3:
					*primaries = 12;
					break;
				default:
					break;
			}
		} else if((enc->white_point == JXL_WHITE_POINT_DCI) && (enc->primaries == JXL_PRIMARIES_P3)) {
			*primaries = 11;
		}
	} else {
		return FALSE;
	}
	switch(enc->transfer_function) {
		case JXL_TRANSFER_FUNCTION_709:
			*transfer = 1;
			break;
		case JXL_TRANSFER_FUNCTION_LINEAR:
			*transfer = 8;
			break;
		case JXL_TRANSFER_FUNCTION_SRGB:
			*transfer = 13;
			break;
		case JXL_TRANSFER_FUNCTION_PQ:
			*transfer = 16;
			break;
		case JXL_TRANSFER_FUNCTION_DCI:
			*transfer = 17;
			break;
		case JXL_TRANSFER_FUNCTION_HLG:
			*transfer = 18;
			break;
		case JXL_TRANSFER_FUNCTION_GAMMA:
			// JxlColorEncoding stores the encoding exponent, 1 / 2.2 for BT.470 System M
			if(fabs(enc->gamma - 1.0 / 2.2) < 1e-4) {
				*transfer = 4;
			} else if(fabs(enc->gamma - 1.0 / 2.8) < 1e-4) {
				*transfer = 5;
			}
			break;
		default:
			break;
	}
	return ((*primaries != 2) || (*transfer != 2)) ? TRUE : FALSE;
}

