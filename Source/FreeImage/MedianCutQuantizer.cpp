// whether the CPU runs AVX2 and the OS saves the YMM registers
static bool
DetectAVX2() {
	unsigned c1, b7, xcr0;
#if defined(_MSC_VER) && !defined(__clang__)
	int info[4];
	__cpuid(info, 0);
	if (info[0] < 7) {
		return false;
	}
	__cpuid(info, 1);
	c1 = (unsigned)info[2];
	__cpuidex(info, 7, 0);
	b7 = (unsigned)info[1];
	// OSXSAVE and AVX before XGETBV
	if ((c1 & (3u << 27)) != (3u << 27)) {
		return false;
	}
	xcr0 = (unsigned)_xgetbv(0);
#else
	unsigned a, b, c, d;
	if (__get_cpuid_max(0, NULL) < 7) {
		return false;
	}
	__cpuid(1, a, b, c, d);
	c1 = c;
	__cpuid_count(7, 0, a, b, c, d);
	b7 = b;
	if ((c1 & (3u << 27)) != (3u << 27)) {
		return false;
	}
	__asm__ __volatile__("xgetbv" : "=a"(xcr0), "=d"(d) : "c"(0));
#endif
	return ((xcr0 & 6) == 6) && ((b7 & (1u << 5)) != 0);
}

static bool
HasAVX2() {
	static const bool avx2 = DetectAVX2();
	return avx2;
}
