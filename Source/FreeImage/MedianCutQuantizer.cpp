// 3-D prefix sums of the 5-bit histogram: counts, and counts times each channel's level
struct MCMoments {
	INT64 *table[4];

	MCMoments() {
		table[0] = (INT64 *)malloc(4 * CELLS * sizeof(INT64));
		for (int k = 1; k < 4; k++) {
			table[k] = table[0] ? table[0] + k * CELLS : NULL;
		}
	}
	~MCMoments() {
		free(table[0]);
	}

	// k = 0 counts, k = 1, 2, 3 the R, G, B level sums
	INT64 Sum(int k, const int *lo, const int *hi) const {
		const INT64 *t = table[k];
		const int r0 = lo[0] * SIDE * SIDE, r1 = (hi[0] + 1) * SIDE * SIDE;
		const int g0 = lo[1] * SIDE, g1 = (hi[1] + 1) * SIDE;
		const int b0 = lo[2], b1 = hi[2] + 1;
		return t[r1 + g1 + b1] - t[r0 + g1 + b1] - t[r1 + g0 + b1] - t[r1 + g1 + b0]
			+ t[r0 + g0 + b1] + t[r0 + g1 + b0] + t[r1 + g0 + b0] - t[r0 + g0 + b0];
	}
};

struct MCBox {
	int lo[3], hi[3];	// inclusive 5-bit levels, R, G, B
	INT64 pop;
};

// the 5-bit cell of a pixel, R major
static inline unsigned
CellOf(const BYTE *p) {
	return ((p[FI_RGBA_RED] >> 3) << 10) | ((p[FI_RGBA_GREEN] >> 3) << 5) | (p[FI_RGBA_BLUE] >> 3);
}

