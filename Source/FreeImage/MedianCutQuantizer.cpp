MedianCutQuantizer::MedianCutQuantizer(int PaletteSize) : m_size(PaletteSize) {
}

FIBITMAP*
MedianCutQuantizer::Quantize(FIBITMAP *dib, int ReserveSize, RGBQUAD *ReservePalette) {
	const unsigned width = FreeImage_GetWidth(dib);
	const unsigned height = FreeImage_GetHeight(dib);
	if (!width || !height) {
		return NULL;
	}
	if (!ReservePalette) {
		ReserveSize = 0;
	}
	ReserveSize = MAX(0, MIN(ReserveSize, m_size));
	const int count = m_size - ReserveSize;

	RGBQUAD palette[256];
	int filled = 0;
	if (count > 0) {
		UINT64 *hist = (UINT64 *)malloc(HIST_SIZE * sizeof(UINT64));
		MCMoments moments;
		if (!hist || !moments.table[0] || !CountColors(dib, hist)) {
			free(hist);
			return NULL;
		}
		BuildMoments(hist, moments);
		free(hist);
		filled = MedianCut(moments, count, palette);
	}
	// the reserved colors follow the computed ones
	for (int i = 0; i < ReserveSize; i++) {
		palette[filled + i] = ReservePalette[i];
		palette[filled + i].rgbReserved = 0;
	}
	filled += ReserveSize;

	DWORD lut[LUT_SIZE];
	BuildLookup(palette, filled, lut);

	FIBITMAP *dst = FreeImage_Allocate(width, height, 8);
	if (!dst) {
		return NULL;
	}
	RGBQUAD *dst_pal = FreeImage_GetPalette(dst);
	for (int i = 0; i < filled; i++) {
		dst_pal[i] = palette[i];
	}
	if (!Diffuse(dib, dst, lut)) {
		FreeImage_Unload(dst);
		return NULL;
	}
	return dst;
}
