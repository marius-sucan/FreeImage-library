static Model
ModelOf(cmsHPROFILE profile) {
	switch (cmsGetDeviceClass(profile)) {
		case cmsSigInputClass:
		case cmsSigDisplayClass:
		case cmsSigOutputClass:
		case cmsSigColorSpaceClass:
			break;
		default:
			return MODEL_NONE;
	}
	switch (cmsGetColorSpace(profile)) {
		case cmsSigGrayData:	return MODEL_GRAY;
		case cmsSigRgbData:		return MODEL_RGB;
		case cmsSigCmykData:	return MODEL_CMYK;
		default:				return MODEL_NONE;
	}
}

// Little CMS errors go to FreeImage_OutputMessageProc unless muted
class Context {
public:
	cmsContext id;
	bool mute;

	Context() : id(NULL), mute(false) {
		id = cmsCreateContext(NULL, this);
		if (id) {
			cmsSetLogErrorHandlerTHR(id, Log);
		}
	}
	~Context() {
		if (id) {
			cmsDeleteContext(id);
		}
	}
	cmsHPROFILE Open(const void *data, DWORD size) {
		if (!id || !data || (size < 128)) {
			return NULL;
		}
		return cmsOpenProfileFromMemTHR(id, data, size);
	}

private:
	static void Log(cmsContext id, cmsUInt32Number, const char *text) {
		const Context *self = (const Context *)cmsGetContextUserData(id);
		if (self && !self->mute && text) {
			FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: Little CMS: %s", text);
		}
	}
	Context(const Context &);
	Context &operator=(const Context &);
};

struct Profile {
	cmsHPROFILE handle;		// NULL for device CMYK
	Model model;
	const void *bytes;		// the profile, to recognise two equal ones
	DWORD size;
	bool tag;				// the result carries this profile

	Profile() : handle(NULL), model(MODEL_NONE), bytes(NULL), size(0), tag(false) {
	}
	~Profile() {
		if (handle) {
			cmsCloseProfile(handle);
		}
	}
	bool Same(const Profile &other) const {
		return bytes && other.bytes && (size == other.size) && ((bytes == other.bytes) || (memcmp(bytes, other.bytes, size) == 0));
	}

private:
	Profile(const Profile &);
	Profile &operator=(const Profile &);
};

// the image's profile, even when the caller passes the image's own profile
static void
AttachProfile(FIBITMAP *dib, const void *data, DWORD size) {
	FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	const BYTE *current = (const BYTE*)icc->data;
	const BYTE *bytes = (const BYTE*)data;
	if (current && (bytes >= current) && (bytes < current + icc->size)) {
		if ((bytes == current) && (size == icc->size)) {
			return;
		}
		void *copy = malloc(size);
		if (copy) {
			memcpy(copy, data, size);
			FreeImage_CreateICCProfile(dib, copy, (long)size);
			free(copy);
		} else {
			FreeImage_DestroyICCProfile(dib);
		}
		return;
	}
	FreeImage_CreateICCProfile(dib, (void*)data, (long)size);
}

