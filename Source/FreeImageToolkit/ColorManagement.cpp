class ColorConverter {
public:
	explicit ColorConverter(int flags) : m_flags(flags), m_dib(NULL), m_width(0), m_height(0),
		m_transform(NULL), m_device_in(false), m_device_out(false), m_step(0), m_grey(false),
		m_in_format(0), m_out_format(0), m_ignore_embedded(false), m_embedded(false), m_cache(NULL) {
		memset(&m_px, 0, sizeof(m_px));
	}
	~ColorConverter() {
		if (m_transform && !m_cached_transform) {
			cmsDeleteTransform(m_transform);
		}
	}

	bool SetSource(FIBITMAP *dib);
	bool SetDestination(const void *data, DWORD size, Model required, Model if_null);
	bool SetProof(const void *data, DWORD size);
	FIBITMAP *Convert();
	BOOL Apply();

	Model SourceModel() const {
		return m_px.model;
	}
	// the image is taken as its type's default, whatever profile it embeds; call before SetSource
	void IgnoreEmbedded() {
		m_ignore_embedded = true;
	}
	bool EmbeddedSource() const {
		return m_embedded;
	}
	// the transform comes from the cache, which outlives the converter
	void UseCache(TransformCache *cache) {
		m_cache = cache;
	}
	// FreeImage's default space: grey for grey images, else RGB
	Model DefaultModel() const {
		return (m_px.model == MODEL_GRAY) ? MODEL_GRAY : MODEL_RGB;
	}

private:
	Context m_context;
	int m_flags;
	FIBITMAP *m_dib;
	Pixels m_px;
	int m_width;
	int m_height;
	Profile m_source;
	Profile m_destination;
	Profile m_proof;
	Profile m_device;		// sRGB or grey sRGB, the other side of device CMYK
	cmsHTRANSFORM m_transform;
	bool m_device_in;		// device CMYK source
	bool m_device_out;		// device CMYK destination
	unsigned m_step;		// samples per pixel read by the device CMYK separation
	bool m_grey;			// the separation reads grey
	cmsUInt32Number m_in_format;
	cmsUInt32Number m_out_format;
	bool m_ignore_embedded;
	bool m_embedded;		// the source is the embedded profile
	TransformCache *m_cache;
	std::shared_ptr<void> m_cached_transform;

	bool OpenBuiltIn(Profile &profile, Model model, unsigned depth);
	bool OpenGiven(Profile &profile, const void *data, DWORD size, const char *what);
	bool IsIdentity() const;
	bool CreateTransform(bool same_buffer);
	void Tag(FIBITMAP *dib) const;
	bool Run(FIBITMAP *target, Layout out, bool in_place);
	bool RunTable(FIBITMAP *target, Layout out, bool in_place);
	bool RunRows(FIBITMAP *target, Layout out, bool in_place);
	void Row(const BYTE *src, BYTE *dst, BYTE *buffer_a, BYTE *buffer_b) const;
	void Separate(const BYTE *src, BYTE *dst, unsigned width, unsigned depth) const;

	ColorConverter(const ColorConverter &);
	ColorConverter &operator=(const ColorConverter &);
};

bool ColorConverter::
OpenBuiltIn(Profile &profile, Model model, unsigned depth) {
	DWORD size = 0;
	const void *data = FreeImage_GetBuiltInICCProfile(DefaultProfile(model, depth), &size);
	profile.handle = data ? m_context.Open(data, size) : NULL;
	if (!profile.handle) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the built-in profiles are not available");
		return false;
	}
	profile.model = model;
	profile.bytes = data;
	profile.size = size;
	profile.tag = false;
	return true;
}

bool ColorConverter::
OpenGiven(Profile &profile, const void *data, DWORD size, const char *what) {
	if ((size < 128) || (size > 0x7FFFFFFF)) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the %s profile has an invalid size", what);
		return false;
	}
	profile.handle = m_context.Open(data, size);
	if (!profile.handle) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the %s profile is invalid", what);
		return false;
	}
	profile.model = ModelOf(profile.handle);
	if (profile.model == MODEL_NONE) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the %s profile is not a grey, RGB or CMYK device profile", what);
		return false;
	}
	profile.bytes = data;
	profile.size = size;
	profile.tag = true;
	return true;
}

bool ColorConverter::
SetSource(FIBITMAP *dib) {
	if (!m_context.id || !FreeImage_HasPixels(dib)) {
		return false;
	}
	const char *error = AnalysePixels(dib, m_px);
	if (error) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: %s", error);
		return false;
	}
	m_dib = dib;
	m_width = (int)FreeImage_GetWidth(dib);
	m_height = (int)FreeImage_GetHeight(dib);

	const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	if (!m_ignore_embedded && icc->data && icc->size) {
		m_context.mute = true;
		cmsHPROFILE handle = m_context.Open(icc->data, icc->size);
		m_context.mute = false;
		if (!handle) {
			FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the embedded profile is invalid and is ignored");
		} else {
			const Model model = ModelOf(handle);
			const bool indexed = (m_px.layout == LAYOUT_INDEXED) || (m_px.layout == LAYOUT_GRAY8);
			// a grey palette may come with an RGB profile
			if ((model == m_px.model) || (indexed && (m_px.model == MODEL_GRAY) && (model == MODEL_RGB))) {
				m_px.model = model;
				m_source.handle = handle;
				m_source.model = model;
				m_source.bytes = icc->data;
				m_source.size = icc->size;
				m_embedded = true;
			} else {
				cmsCloseProfile(handle);
				FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the embedded profile does not match the pixels and is ignored");
			}
		}
	}
	if (!m_source.handle) {
		if (m_px.model == MODEL_CMYK) {
			m_source.model = MODEL_CMYK;
		} else if (!OpenBuiltIn(m_source, m_px.model, m_px.depth)) {
			return false;
		}
	}
	return true;
}

bool ColorConverter::
SetDestination(const void *data, DWORD size, Model required, Model if_null) {
	if (data) {
		if (!OpenGiven(m_destination, data, size, "destination")) {
			return false;
		}
		if ((required != MODEL_NONE) && (m_destination.model != required)) {
			FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the destination profile is not a%s profile", (required == MODEL_CMYK) ? " CMYK" : (required == MODEL_RGB) ? "n RGB" : " grey");
			return false;
		}
		return true;
	}
	if (if_null == MODEL_CMYK) {
		m_destination.model = MODEL_CMYK;
		return true;
	}
	return OpenBuiltIn(m_destination, if_null, m_px.depth);
}

bool ColorConverter::
SetProof(const void *data, DWORD size) {
	if (!data) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: soft proofing needs the profile of the proofing device");
		return false;
	}
	if (!OpenGiven(m_proof, data, size, "proofing")) {
		return false;
	}
	m_proof.tag = false;
	return true;
}

bool ColorConverter::
IsIdentity() const {
	if (m_proof.handle || (m_source.model != m_destination.model)) {
		return false;
	}
	if (!m_source.handle && !m_destination.handle) {
		return true;
	}
	return m_source.Same(m_destination);
}

// the Little CMS stage, none when both sides are the same profile and the samples can be copied
bool ColorConverter::
CreateTransform(bool same_buffer) {
	const Profile &in = m_device_in ? m_device : m_source;
	const Profile &out = m_device_out ? m_device : m_destination;
	if (!m_proof.handle && in.Same(out) && (m_device_out || (m_in_format == m_out_format))) {
		return true;
	}

	cmsUInt32Number flags = 0;
	if (m_flags & FICMS_BLACKPOINT_COMPENSATION) {
		flags |= cmsFLAGS_BLACKPOINTCOMPENSATION;
	}
	if (!same_buffer && T_EXTRA(m_in_format) && T_EXTRA(m_out_format)) {
		flags |= cmsFLAGS_COPY_ALPHA;
	}
	// Little CMS's precalculated 16-bit tables are coarser than its 8-bit path: 16 bits are computed exactly
	if ((T_BYTES(m_in_format) == 2) || (T_BYTES(m_out_format) == 2)) {
		flags |= cmsFLAGS_NOOPTIMIZE;
	}
	const cmsUInt32Number intent = (cmsUInt32Number)(m_flags & 0xFF);

	if (m_proof.handle) {
		flags |= cmsFLAGS_SOFTPROOFING;
		if (m_flags & FICMS_GAMUT_CHECK) {
			flags |= cmsFLAGS_GAMUTCHECK;
		}
		const cmsUInt32Number proof_intent = (m_flags & FICMS_SIMULATE_PAPER) ? INTENT_ABSOLUTE_COLORIMETRIC : INTENT_RELATIVE_COLORIMETRIC;
		m_transform = cmsCreateProofingTransformTHR(m_context.id, in.handle, m_in_format, out.handle, m_out_format, m_proof.handle, intent, proof_intent, flags);
		// without a gamut table Little CMS 2.19 still takes its gamut-check path and crashes
		if (m_transform && (flags & cmsFLAGS_GAMUTCHECK) && !cmsGetTransformGamutCheckPipeline(m_transform)) {
			cmsDeleteTransform(m_transform);
			m_transform = NULL;
			FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the proofing profile cannot be used for a gamut check");
			return false;
		}
	} else if (m_cache) {
		m_cached_transform = m_cache->Get(in, out, m_in_format, m_out_format, intent, flags);
		m_transform = m_cached_transform.get();
	} else {
		m_transform = cmsCreateTransformTHR(m_context.id, in.handle, m_in_format, out.handle, m_out_format, intent, flags);
	}
	if (!m_transform) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: the profiles cannot be linked");
		return false;
	}
	return true;
}

// the destination profile, or none for FreeImage's default space
void ColorConverter::
Tag(FIBITMAP *dib) const {
	// before the source profile, which may be the image's own, is replaced
	const bool converted = !IsIdentity();
	if (m_destination.tag) {
		AttachProfile(dib, m_destination.bytes, m_destination.size);
	} else {
		FreeImage_DestroyICCProfile(dib);
	}
	FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	if (m_destination.model == MODEL_CMYK) {
		icc->flags |= FIICC_COLOR_IS_CMYK;
	} else {
		icc->flags &= ~FIICC_COLOR_IS_CMYK;
	}
	// the CICP tag describes the samples before the conversion
	if (converted) {
		FreeImage_SetMetadata(FIMD_CUSTOM, dib, "CICP", NULL);
	}
}

bool ColorConverter::
Run(FIBITMAP *target, Layout out, bool in_place) {
	m_device_in = (m_source.model == MODEL_CMYK) && !m_source.handle;
	m_device_out = (m_destination.model == MODEL_CMYK) && !m_destination.handle;
	m_grey = m_device_out && (m_source.model == MODEL_GRAY);
	if (m_device_in || m_device_out) {
		if (!OpenBuiltIn(m_device, m_grey ? MODEL_GRAY : MODEL_RGB, (m_px.depth == 8) ? 8 : 16)) {
			return false;
		}
	}
	if ((m_px.layout == LAYOUT_INDEXED) || (m_px.layout == LAYOUT_GRAY8)) {
		return RunTable(target, out, in_place);
	}
	return RunRows(target, out, in_place);
}

// device CMYK from the stage's output, or from the source when there is no stage
void ColorConverter::
Separate(const BYTE *src, BYTE *dst, unsigned width, unsigned depth) const {
	if (depth == 8) {
		RGBToDeviceCMYK<BYTE>(src, m_step, m_grey, FI_RGBA_RED, FI_RGBA_GREEN, FI_RGBA_BLUE, dst, width);
	} else {
		RGBToDeviceCMYK<WORD>((const WORD*)src, m_step, m_grey, 0, 1, 2, (WORD*)dst, width);
	}
}

// palettes and 8-bit grey: the 256 possible values go through a table
bool ColorConverter::
RunTable(FIBITMAP *target, Layout out, bool in_place) {
	const bool alpha = m_px.alpha && (out == LAYOUT_RGBA8);
	const bool grey_in = (m_px.model == MODEL_GRAY);

	if (grey_in) {
		m_in_format = alpha ? TYPE_GRAYA_8 : TYPE_GRAY_8;
	} else {
		m_in_format = alpha ? ICC_TYPE_RGBA_8 : ICC_TYPE_RGB_8;
	}
	if (m_device_out) {
		m_out_format = m_grey ? TYPE_GRAY_8 : ICC_TYPE_RGB_8;
	} else if (out == LAYOUT_INDEXED) {
		m_out_format = (m_destination.model == MODEL_GRAY) ? TYPE_GRAY_8 : ICC_TYPE_RGB_8;
	} else {
		m_out_format = LayoutFormat(out, false);
	}
	if (!CreateTransform(false)) {
		return false;
	}

	// the entries in the stage's input format
	BYTE entries[256 * 4];
	{
		const RGBQUAD *palette = FreeImage_GetPalette(m_dib);
		const BYTE *table = FreeImage_GetTransparencyTable(m_dib);
		const unsigned count = (alpha && table) ? FreeImage_GetTransparencyCount(m_dib) : 0;
		const unsigned bytes = PixelBytes(m_in_format);
		for (unsigned i = 0; i < 256; i++) {
			RGBQUAD color = { 0, 0, 0, 0 };
			if (i < m_px.colors) {
				color = palette[i];
			}
			const BYTE a = (i < count) ? table[i] : 0xFF;
			BYTE *entry = entries + i * bytes;
			if (grey_in) {
				entry[0] = color.rgbRed;
				if (alpha) entry[1] = a;
			} else {
				entry[FI_RGBA_RED] = color.rgbRed;
				entry[FI_RGBA_GREEN] = color.rgbGreen;
				entry[FI_RGBA_BLUE] = color.rgbBlue;
				if (alpha) entry[FI_RGBA_ALPHA] = a;
			}
		}
	}

	// the converted entries in the output format
	const unsigned lut_bytes = m_device_out ? 4 : PixelBytes(m_out_format);
	BYTE lut[256 * 4];
	BYTE middle[256 * 4];
	const BYTE *p = entries;
	if (m_transform) {
		BYTE *t = m_device_out ? middle : lut;
		cmsDoTransform(m_transform, p, t, 256);
		p = t;
	}
	if (m_device_out) {
		m_step = m_transform ? PixelBytes(m_out_format) : PixelBytes(m_in_format);
		Separate(p, lut, 256, 8);
		p = lut;
	}
	if (p != lut) {
		memcpy(lut, p, 256 * lut_bytes);
	}

	if (out == LAYOUT_INDEXED) {
		// the palette changes, the indices stay
		RGBQUAD *palette = FreeImage_GetPalette(target);
		const bool grey_out = (m_destination.model == MODEL_GRAY);
		for (unsigned i = 0; i < m_px.colors; i++) {
			const BYTE *entry = lut + i * lut_bytes;
			if (grey_out) {
				palette[i].rgbRed = palette[i].rgbGreen = palette[i].rgbBlue = entry[0];
			} else {
				palette[i].rgbRed = entry[FI_RGBA_RED];
				palette[i].rgbGreen = entry[FI_RGBA_GREEN];
				palette[i].rgbBlue = entry[FI_RGBA_BLUE];
			}
		}
		return true;
	}

	const bool threaded = (m_height > 1) && ((UINT64)m_width * (UINT64)m_height >= ICC_PARALLEL_PIXELS);
	const unsigned width = (unsigned)m_width;

	if (in_place) {
		// an 8-bit grey ramp keeps its palette: the values change
		BYTE index[256];
		for (unsigned i = 0; i < 256; i++) {
			index[i] = m_px.reversed ? (BYTE)(255 - lut[i]) : lut[i];
		}
		#pragma omp parallel for schedule(static) default(shared) if(threaded)
		for (int y = 0; y < m_height; y++) {
			BYTE *bits = FreeImage_GetScanLine(target, y);
			for (unsigned x = 0; x < width; x++) {
				bits[x] = index[bits[x]];
			}
		}
		return true;
	}

	const unsigned bpp = FreeImage_GetBPP(m_dib);
	#pragma omp parallel for schedule(static) default(shared) if(threaded)
	for (int y = 0; y < m_height; y++) {
		const BYTE *src = FreeImage_GetScanLine(m_dib, y);
		BYTE *dst = FreeImage_GetScanLine(target, y);
		for (unsigned x = 0; x < width; x++) {
			unsigned i;
			if (bpp == 8) {
				i = src[x];
			} else if (bpp == 4) {
				i = (x & 1) ? (src[x >> 1] & 0x0F) : (src[x >> 1] >> 4);
			} else {
				i = (src[x >> 3] >> (7 - (x & 7))) & 1;
			}
			const BYTE *entry = lut + i * lut_bytes;
			for (unsigned k = 0; k < lut_bytes; k++) {
				dst[k] = entry[k];
			}
			dst += lut_bytes;
		}
	}
	return true;
}

// one row: expansion or device CMYK, the Little CMS stage, the device CMYK separation
void ColorConverter::
Row(const BYTE *src, BYTE *dst, BYTE *buffer_a, BYTE *buffer_b) const {
	const unsigned width = (unsigned)m_width;
	const bool copy_out = !m_transform && !m_device_out;
	const BYTE *p = src;

	if ((m_px.layout == LAYOUT_555) || (m_px.layout == LAYOUT_565)) {
		BYTE *t = copy_out ? dst : buffer_a;
		if (m_px.layout == LAYOUT_565) {
			FreeImage_ConvertLine16To24_565(t, (BYTE*)p, (int)width);
		} else {
			FreeImage_ConvertLine16To24_555(t, (BYTE*)p, (int)width);
		}
		p = t;
	} else if (m_device_in) {
		BYTE *t = copy_out ? dst : buffer_a;
		if (m_px.depth == 8) {
			DeviceCMYKToRGB8(p, t, width);
		} else {
			DeviceCMYKToRGB16((const WORD*)p, (WORD*)t, width);
		}
		p = t;
	}
	if (m_transform) {
		BYTE *t = m_device_out ? buffer_b : dst;
		cmsDoTransform(m_transform, p, t, width);
		p = t;
	}
	if (m_device_out) {
		Separate(p, dst, width, (m_px.depth == 8) ? 8 : 16);
		p = dst;
	}
	if (p != dst) {
		memcpy(dst, p, (size_t)width * PixelBytes(m_out_format));
	}
}

// every other layout: row by row
bool ColorConverter::
RunRows(FIBITMAP *target, Layout out, bool in_place) {
	const bool d8 = (m_px.depth == 8);
	// CMYK to RGBA in place: through a row buffer, alpha set opaque
	const bool opaque = in_place && (out != m_px.layout);

	if (m_device_in) {
		m_in_format = d8 ? ICC_TYPE_RGB_8 : TYPE_RGB_16;
	} else if ((m_px.layout == LAYOUT_555) || (m_px.layout == LAYOUT_565)) {
		m_in_format = ICC_TYPE_RGB_8;
	} else {
		m_in_format = LayoutFormat(m_px.layout, m_px.reversed);
	}
	if (m_device_out) {
		if (m_grey) {
			m_out_format = d8 ? TYPE_GRAY_8 : TYPE_GRAY_16;
		} else {
			m_out_format = d8 ? ICC_TYPE_RGB_8 : TYPE_RGB_16;
		}
	} else if (opaque) {
		m_out_format = d8 ? ICC_TYPE_RGB_8 : TYPE_RGB_16;
	} else {
		m_out_format = LayoutFormat(out, (out == m_px.layout) && m_px.reversed);
	}
	const bool same_buffer = in_place && !opaque && !m_device_in;
	if (!CreateTransform(same_buffer)) {
		return false;
	}
	if (m_device_out) {
		m_step = m_transform ? T_CHANNELS(m_out_format) + T_EXTRA(m_out_format) : T_CHANNELS(m_in_format) + T_EXTRA(m_in_format);
	}
	if (in_place && !m_transform && !m_device_in) {
		// nothing changes
		return true;
	}

	const size_t width = (size_t)m_width;
	const bool expand = m_device_in || (m_px.layout == LAYOUT_555) || (m_px.layout == LAYOUT_565);
	const size_t size_a = expand ? width * PixelBytes(m_in_format) : 0;
	const size_t size_b = (m_device_out && m_transform) ? width * PixelBytes(m_out_format) : 0;
	const size_t size_c = opaque ? width * PixelBytes(m_out_format) : 0;

	const bool threaded = (m_height > 1) && ((UINT64)m_width * (UINT64)m_height >= ICC_PARALLEL_PIXELS);
	bool failed = false;

	#pragma omp parallel default(shared) if(threaded)
	{
		RowBuffers buffers;
		if (!buffers.Allocate(size_a, size_b, size_c)) {
			#pragma omp critical
			failed = true;
		}
		// nothing is written unless every thread has its buffers
		#pragma omp barrier
		if (!failed) {
			#pragma omp for schedule(static)
			for (int y = 0; y < m_height; y++) {
				BYTE *dst = FreeImage_GetScanLine(target, y);
				if (opaque) {
					Row(dst, buffers.c, buffers.a, buffers.b);
					if (d8) {
						PackOpaque8(buffers.c, dst, (unsigned)width);
					} else {
						PackOpaque16((const WORD*)buffers.c, (WORD*)dst, (unsigned)width);
					}
				} else {
					Row(in_place ? dst : FreeImage_GetScanLine(m_dib, y), dst, buffers.a, buffers.b);
				}
			}
		}
	}
	if (failed) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: %s", FI_MSG_ERROR_MEMORY);
		return false;
	}
	return true;
}

FIBITMAP *ColorConverter::
Convert() {
	const Layout out = OutputLayout(m_px, m_destination.model);
	if (out == LAYOUT_NONE) {
		return NULL;
	}
	if (out == m_px.layout) {
		// the same pixel format: a copy converted in place
		FIBITMAP *dst = FreeImage_Clone(m_dib);
		if (!dst) {
			return NULL;
		}
		if (!IsIdentity() && !Run(dst, out, true)) {
			FreeImage_Unload(dst);
			return NULL;
		}
		Tag(dst);
		return dst;
	}
	FIBITMAP *dst = AllocateLayout(out, m_width, m_height);
	if (!dst) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: %s", FI_MSG_ERROR_DIB_MEMORY);
		return NULL;
	}
	FreeImage_CloneMetadata(dst, m_dib);
	if (!Run(dst, out, false)) {
		FreeImage_Unload(dst);
		return NULL;
	}
	Tag(dst);
	return dst;
}

BOOL ColorConverter::
Apply() {
	if (IsIdentity()) {
		Tag(m_dib);
		return TRUE;
	}
	const Layout out = InPlaceLayout(m_px, m_destination.model);
	if (out == LAYOUT_NONE) {
		FreeImage_OutputMessageProc(FIF_UNKNOWN, "ICC: this conversion changes the pixel format, use FreeImage_ConvertToICCProfile");
		return FALSE;
	}
	if (!Run(m_dib, out, true)) {
		return FALSE;
	}
	Tag(m_dib);
	return TRUE;
}

