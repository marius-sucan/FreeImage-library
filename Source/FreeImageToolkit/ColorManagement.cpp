// FreeImage's sRGB or grey through the profile comes back within two 8-bit steps (colord's sRGB.icc: one)
static bool
Equivalent(const Context &context, cmsHPROFILE builtin, cmsHPROFILE profile, bool grey) {
	const cmsUInt32Number format = grey ? TYPE_GRAY_16 : TYPE_RGB_16;
	cmsHTRANSFORM transform = cmsCreateTransformTHR(context.id, builtin, format, profile, format, INTENT_RELATIVE_COLORIMETRIC, cmsFLAGS_NOOPTIMIZE);
	if (!transform) {
		return false;
	}
	const unsigned N = 17;
	const unsigned count = grey ? 1024 : N * N * N;
	std::vector<WORD> in(grey ? count : count * 3), out(in.size());
	for (unsigned i = 0; i < count; i++) {
		if (grey) {
			in[i] = (WORD)(i * 65535 / (count - 1));
		} else {
			in[3 * i] = (WORD)((i / (N * N)) * 65535 / (N - 1));
			in[3 * i + 1] = (WORD)(((i / N) % N) * 65535 / (N - 1));
			in[3 * i + 2] = (WORD)((i % N) * 65535 / (N - 1));
		}
	}
	cmsDoTransform(transform, &in[0], &out[0], count);
	cmsDeleteTransform(transform);
	for (size_t i = 0; i < in.size(); i++) {
		if (abs((int)in[i] - (int)out[i]) > 2 * 257) {
			return false;
		}
	}
	return true;
}

// the largest profile checked for being sRGB or grey in all but name
#define ICC_TWIN_MAX_SIZE (1024 * 1024)
// the most profiles whose answer is kept
#define ICC_TWIN_ENTRIES 16

// embedded profiles that FreeImage's sRGB or grey stand for; each is checked once
class TwinCache {
public:
	bool IsTwin(const void *bytes, DWORD size) {
		if (!bytes || (size < 128) || (size > ICC_TWIN_MAX_SIZE)) {
			return false;
		}
		{
			std::lock_guard<std::mutex> guard(m_lock);
			for (size_t i = 0; i < m_entries.size(); i++) {
				if ((m_entries[i].bytes.size() == size) && !memcmp(&m_entries[i].bytes[0], bytes, size)) {
					return m_entries[i].twin;
				}
			}
		}
		Entry entry;
		entry.twin = Check(bytes, size);
		entry.bytes.assign((const BYTE*)bytes, (const BYTE*)bytes + size);
		std::lock_guard<std::mutex> guard(m_lock);
		if (m_entries.size() >= ICC_TWIN_ENTRIES) {
			m_entries.erase(m_entries.begin());
		}
		m_entries.push_back(entry);
		return entry.twin;
	}

private:
	struct Entry {
		std::vector<BYTE> bytes;
		bool twin;
	};

	std::mutex m_lock;
	std::vector<Entry> m_entries;

	static bool Check(const void *bytes, DWORD size) {
		Context context;
		context.mute = true;
		cmsHPROFILE profile = context.Open(bytes, size);
		const Model model = profile ? ModelOf(profile) : MODEL_NONE;
		bool twin = false;
		if ((model == MODEL_RGB) || (model == MODEL_GRAY)) {
			DWORD builtin_size = 0;
			const void *builtin_data = FreeImage_GetBuiltInICCProfile((model == MODEL_GRAY) ? FICMS_PROFILE_GRAY : FICMS_PROFILE_SRGB, &builtin_size);
			cmsHPROFILE builtin = context.Open(builtin_data, builtin_size);
			twin = builtin && Equivalent(context, builtin, profile, (model == MODEL_GRAY));
			if (builtin) {
				cmsCloseProfile(builtin);
			}
		}
		if (profile) {
			cmsCloseProfile(profile);
		}
		return twin;
	}
};

static TwinCache &
GetTwinCache() {
	// never destroyed: a load may still run while the process ends
	static TwinCache *cache = new TwinCache;
	return *cache;
}

// a grey profile whose tone curve is the luminance the display shows for (v, v, v)
static bool
DisplayGrey(const Context &context, cmsHPROFILE display, std::vector<BYTE> &grey) {
	const unsigned N = 4096;
	cmsHPROFILE xyz = cmsCreateXYZProfileTHR(context.id);
	cmsHTRANSFORM transform = xyz ? cmsCreateTransformTHR(context.id, display, TYPE_RGB_16, xyz, TYPE_XYZ_DBL, INTENT_RELATIVE_COLORIMETRIC, cmsFLAGS_NOOPTIMIZE) : NULL;
	if (xyz) {
		cmsCloseProfile(xyz);
	}
	if (!transform) {
		return false;
	}
	std::vector<WORD> rgb(N * 3);
	std::vector<cmsCIEXYZ> out(N);
	for (unsigned i = 0; i < N; i++) {
		rgb[3 * i] = rgb[3 * i + 1] = rgb[3 * i + 2] = (WORD)((i * 65535 + (N - 1) / 2) / (N - 1));
	}
	cmsDoTransform(transform, &rgb[0], &out[0], N);
	cmsDeleteTransform(transform);
	const double white = out[N - 1].Y;
	if (!(white > 0)) {
		return false;
	}
	// a tone curve has to rise
	std::vector<WORD> curve(N);
	double previous = 0;
	for (unsigned i = 0; i < N; i++) {
		double y = out[i].Y / white;
		y = (y < previous) ? previous : (y > 1) ? 1 : y;
		previous = y;
		curve[i] = (WORD)(y * 65535 + 0.5);
	}
	cmsToneCurve *tone = cmsBuildTabulatedToneCurve16(context.id, N, &curve[0]);
	cmsHPROFILE profile = tone ? cmsCreateGrayProfileTHR(context.id, cmsD50_xyY(), tone) : NULL;
	if (tone) {
		cmsFreeToneCurve(tone);
	}
	bool done = profile && SetDescription(profile, "Display grey (FreeImage)");
	if (done) {
		DWORD size = 0;
		BYTE *data = SaveBuiltInProfile(profile, &size);
		done = (data != NULL);
		if (data) {
			grey.assign(data, data + size);
			free(data);
		}
	}
	if (profile) {
		cmsCloseProfile(profile);
	}
	return done;
}

// what loads convert to for this display profile; sRGB for none, a profile Little CMS cannot convert to, or an sRGB twin
static std::shared_ptr<DisplayState>
BuildDisplayState(const std::vector<BYTE> &bytes, int flags, bool *usable) {
	std::shared_ptr<DisplayState> state = std::make_shared<DisplayState>();
	state->flags = flags;
	bool linked = false;
	if (bytes.size() >= 128) {
		Context context;
		context.mute = true;
		DWORD srgb_size = 0;
		const void *srgb_data = FreeImage_GetBuiltInICCProfile(FICMS_PROFILE_SRGB, &srgb_size);
		cmsHPROFILE srgb = context.Open(srgb_data, srgb_size);
		cmsHPROFILE profile = context.Open(&bytes[0], (DWORD)bytes.size());
		if (srgb && profile && (ModelOf(profile) == MODEL_RGB)) {
			const cmsUInt32Number bpc = (flags & FICMS_BLACKPOINT_COMPENSATION) ? cmsFLAGS_BLACKPOINTCOMPENSATION : 0;
			cmsHTRANSFORM transform = cmsCreateTransformTHR(context.id, srgb, TYPE_RGB_8, profile, TYPE_RGB_8, (cmsUInt32Number)(flags & 0xFF), bpc);
			if (transform) {
				cmsDeleteTransform(transform);
				linked = true;
				if (!Equivalent(context, srgb, profile, false)) {
					state->rgb = bytes;
					state->srgb = false;
					if (!DisplayGrey(context, profile, state->grey)) {
						BuiltInBytes(FICMS_PROFILE_GRAY, state->grey);
					}
				}
			}
		}
		if (profile) {
			cmsCloseProfile(profile);
		}
		if (srgb) {
			cmsCloseProfile(srgb);
		}
	}
	if (state->srgb) {
		BuiltInBytes(FICMS_PROFILE_SRGB, state->rgb);
		BuiltInBytes(FICMS_PROFILE_GRAY, state->grey);
	}
	if (usable) {
		*usable = linked;
	}
	return state;
}

// the state the loads share, built again when the system reports another profile
class DisplayCache {
public:
	DisplayCache() : m_flags(FICMS_INTENT_RELATIVE_COLORIMETRIC | FICMS_BLACKPOINT_COMPENSATION), m_pinned(false) {
	}

	// the system is asked at most once a second; FreeImage_OutputMessageProc never runs under the lock
	std::shared_ptr<const DisplayState> Current() {
		std::lock_guard<std::mutex> guard(m_lock);
		const std::chrono::steady_clock::time_point now = std::chrono::steady_clock::now();
		if (m_state && (m_pinned || (now - m_checked < std::chrono::seconds(1)))) {
			return m_state;
		}
		DisplayQuery query;
		QuerySystem(query);
		m_checked = now;
		if (!m_state || (query.key != m_key)) {
			ReadSystem(query);
			m_state = BuildDisplayState(query.bytes, m_flags, NULL);
			m_key.swap(query.key);
		}
		return m_state;
	}

	// NULL goes back to the system's profile
	bool Pin(const void *profile, DWORD size, int flags) {
		std::shared_ptr<const DisplayState> state;
		if (profile) {
			if ((size < 128) || (size > ICC_DISPLAY_MAX_SIZE)) {
				return false;
			}
			std::vector<BYTE> bytes;
			Append(bytes, profile, size);
			bool usable = false;
			state = BuildDisplayState(bytes, flags, &usable);
			if (!usable) {
				return false;
			}
		}
		std::lock_guard<std::mutex> guard(m_lock);
		m_state = state;
		m_key.clear();
		m_flags = flags;
		m_pinned = (profile != NULL);
		return true;
	}

private:
	std::mutex m_lock;
	std::shared_ptr<const DisplayState> m_state;
	std::vector<BYTE> m_key;
	std::chrono::steady_clock::time_point m_checked;
	int m_flags;
	bool m_pinned;
};

static DisplayCache &
GetDisplayCache() {
	// never destroyed: a load may still run while the process ends
	static DisplayCache *cache = new DisplayCache;
	return *cache;
}

