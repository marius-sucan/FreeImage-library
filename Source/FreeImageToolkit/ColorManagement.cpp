// HDR or Auto Color Management: Windows itself converts what applications draw from sRGB
static bool
AdvancedColorActive(const DisplayAPI &api, const WCHAR *device) {
	if (!api.buffer_sizes || !api.query_config || !api.device_info) {
		return false;
	}
	std::vector<DisplayConfigPath> paths;
	std::vector<DisplayConfigMode> modes;
	LONG result = ERROR_INSUFFICIENT_BUFFER;
	// the configuration may change between the two calls
	for (int attempt = 0; (attempt < 4) && (result == ERROR_INSUFFICIENT_BUFFER); attempt++) {
		UINT32 path_count = 0, mode_count = 0;
		if (api.buffer_sizes(ICC_QDC_ONLY_ACTIVE_PATHS, &path_count, &mode_count) != ERROR_SUCCESS) {
			return false;
		}
		paths.resize(path_count + 1);
		modes.resize(mode_count + 1);
		result = api.query_config(ICC_QDC_ONLY_ACTIVE_PATHS, &path_count, &paths[0], &mode_count, &modes[0], NULL);
		paths.resize(path_count);
	}
	if (result != ERROR_SUCCESS) {
		return false;
	}
	for (size_t i = 0; i < paths.size(); i++) {
		DisplayConfigSourceName name;
		memset(&name, 0, sizeof(name));
		name.header.type = ICC_DISPLAYCONFIG_SOURCE_NAME;
		name.header.size = sizeof(name);
		name.header.adapter = paths[i].source_adapter;
		name.header.id = paths[i].source_id;
		if ((api.device_info(&name.header) != ERROR_SUCCESS) || wcsncmp(name.gdi_name, device, CCHDEVICENAME)) {
			continue;
		}
		DisplayConfigColor color;
		memset(&color, 0, sizeof(color));
		color.header.type = ICC_DISPLAYCONFIG_ADVANCED_COLOR_2;
		color.header.size = sizeof(color);
		color.header.adapter = paths[i].target_adapter;
		color.header.id = paths[i].target_id;
		if (api.device_info(&color.header) == ERROR_SUCCESS) {
			// wide color gamut or HDR
			return (color.mode != 0);
		}
		// before Windows 11 24H2: advancedColorEnabled
		color.header.type = ICC_DISPLAYCONFIG_ADVANCED_COLOR;
		color.header.size = sizeof(color) - sizeof(color.mode);
		return (api.device_info(&color.header) == ERROR_SUCCESS) && (color.bits & 0x2);
	}
	return false;
}

// the primary monitor's profile: its file and when that changed
static void
QuerySystem(DisplayQuery &query) {
	const DisplayAPI &api = GetDisplayAPI();
	if (!api.monitor_from_point || !api.get_monitor_info || !api.create_ic || !api.get_icm_profile || !api.delete_dc) {
		return;
	}
	const POINT origin = { 0, 0 };
	HMONITOR monitor = api.monitor_from_point(origin, MONITOR_DEFAULTTOPRIMARY);
	MONITORINFOEXW info;
	memset(&info, 0, sizeof(info));
	info.cbSize = sizeof(info);
	if (!monitor || !api.get_monitor_info(monitor, (MONITORINFO*)&info)) {
		return;
	}
	if (AdvancedColorActive(api, info.szDevice)) {
		static const char ADVANCED[] = "advanced color";
		Append(query.key, ADVANCED, sizeof(ADVANCED));
		return;
	}
	HDC ic = api.create_ic(info.szDevice, NULL, NULL, NULL);
	if (!ic) {
		return;
	}
	std::vector<WCHAR> path(MAX_PATH + 1, 0);
	DWORD length = (DWORD)path.size();
	BOOL found = api.get_icm_profile(ic, &length, &path[0]);
	if (!found && (GetLastError() == ERROR_INSUFFICIENT_BUFFER) && (length > path.size()) && (length < 32768)) {
		path.assign(length + 1, 0);
		length = (DWORD)path.size();
		found = api.get_icm_profile(ic, &length, &path[0]);
	}
	api.delete_dc(ic);
	path.back() = 0;
	WIN32_FILE_ATTRIBUTE_DATA data;
	if (!found || !GetFileAttributesExW(&path[0], GetFileExInfoStandard, &data)) {
		return;
	}
	query.path = &path[0];
	Append(query.key, query.path.c_str(), query.path.size() * sizeof(WCHAR));
	Append(query.key, &data.nFileSizeHigh, sizeof(data.nFileSizeHigh));
	Append(query.key, &data.nFileSizeLow, sizeof(data.nFileSizeLow));
	Append(query.key, &data.ftLastWriteTime, sizeof(data.ftLastWriteTime));
}

static void
ReadSystem(DisplayQuery &query) {
	if (query.path.empty()) {
		return;
	}
	FILE *file = _wfopen(query.path.c_str(), L"rb");
	if (!file) {
		return;
	}
	if (fseek(file, 0, SEEK_END) == 0) {
		const long size = ftell(file);
		if ((size >= 128) && (size <= ICC_DISPLAY_MAX_SIZE) && (fseek(file, 0, SEEK_SET) == 0)) {
			query.bytes.resize((size_t)size);
			if (fread(&query.bytes[0], 1, (size_t)size, file) != (size_t)size) {
				query.bytes.clear();
			}
		}
	}
	fclose(file);
}

