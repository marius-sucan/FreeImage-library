static bool
IsGreyPalette(const RGBQUAD *palette, unsigned count) {
	for (unsigned i = 0; i < count; i++) {
		if ((palette[i].rgbRed != palette[i].rgbGreen) || (palette[i].rgbRed != palette[i].rgbBlue)) {
			return false;
		}
	}
	return true;
}

// NULL, or why the image cannot be color managed
static const char *
AnalysePixels(FIBITMAP *dib, Pixels &px) {
	memset(&px, 0, sizeof(px));

	const bool cmyk = (FreeImage_GetICCProfile(dib)->flags & FIICC_COLOR_IS_CMYK) != 0;
	const unsigned bpp = FreeImage_GetBPP(dib);

	switch (FreeImage_GetImageType(dib)) {
		case FIT_BITMAP:
			px.depth = 8;
			switch (bpp) {
				case 1:
				case 4:
				case 8:
				{
					const RGBQUAD *palette = FreeImage_GetPalette(dib);
					px.colors = FreeImage_GetColorsUsed(dib);
					if (!palette || !px.colors) {
						return "the image has no palette";
					}
					px.layout = LAYOUT_INDEXED;
					px.model = IsGreyPalette(palette, px.colors) ? MODEL_GRAY : MODEL_RGB;
					px.alpha = FreeImage_IsTransparent(dib) && (FreeImage_GetTransparencyCount(dib) > 0);
					if ((bpp == 8) && (px.colors == 256) && !px.alpha) {
						const FREE_IMAGE_COLOR_TYPE color_type = FreeImage_GetColorType(dib);
						if ((color_type == FIC_MINISBLACK) || (color_type == FIC_MINISWHITE)) {
							px.layout = LAYOUT_GRAY8;
							px.reversed = (color_type == FIC_MINISWHITE);
						}
					}
					return NULL;
				}
				case 16:
					px.layout = IS_FORMAT_RGB565(dib) ? LAYOUT_565 : LAYOUT_555;
					px.model = MODEL_RGB;
					return NULL;
				case 24:
					px.layout = LAYOUT_RGB8;
					px.model = MODEL_RGB;
					return NULL;
				case 32:
					px.layout = cmyk ? LAYOUT_CMYK8 : LAYOUT_RGBA8;
					px.model = cmyk ? MODEL_CMYK : MODEL_RGB;
					px.alpha = !cmyk;
					return NULL;
			}
			break;
		case FIT_UINT16:
			px.layout = LAYOUT_GRAY16;
			px.model = MODEL_GRAY;
			px.depth = 16;
			px.reversed = (FreeImage_GetColorType(dib) == FIC_MINISWHITE);
			return NULL;
		case FIT_RGB16:
			px.layout = LAYOUT_RGB16;
			px.model = MODEL_RGB;
			px.depth = 16;
			return NULL;
		case FIT_RGBA16:
			px.layout = cmyk ? LAYOUT_CMYK16 : LAYOUT_RGBA16;
			px.model = cmyk ? MODEL_CMYK : MODEL_RGB;
			px.depth = 16;
			px.alpha = !cmyk;
			return NULL;
		case FIT_FLOAT:
			px.layout = LAYOUT_GRAYF;
			px.model = MODEL_GRAY;
			px.depth = 32;
			return NULL;
		case FIT_RGBF:
			px.layout = LAYOUT_RGBF;
			px.model = MODEL_RGB;
			px.depth = 32;
			return NULL;
		case FIT_RGBAF:
			if (cmyk) {
				return "floating-point CMYK images are not supported";
			}
			px.layout = LAYOUT_RGBAF;
			px.model = MODEL_RGB;
			px.depth = 32;
			px.alpha = true;
			return NULL;
		default:
			break;
	}
	return "unsupported image type";
}

