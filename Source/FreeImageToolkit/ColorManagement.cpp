int
DisplayICCLoadFlags(FREE_IMAGE_FORMAT fif, int flags) {
	if ((flags & FIF_LOAD_DISPLAY_ICC) != FIF_LOAD_DISPLAY_ICC) {
		return flags;
	}
	flags &= ~FIF_LOAD_DISPLAY_ICC;
	if ((flags & FIF_LOAD_NOPIXELS) == FIF_LOAD_NOPIXELS) {
		return flags;
	}
	// CMYK stays CMYK, converted with its profile; Lab is converted by the loader
	switch (fif) {
		case FIF_JPEG:
			return flags | JPEG_CMYK;
		case FIF_TIFF:
			return flags | TIFF_CMYK;
		case FIF_PSD:
			return (flags | PSD_CMYK) & ~PSD_LAB;
		default:
			return flags;
	}
}

FIBITMAP *
ConvertToDisplayICC(FREE_IMAGE_FORMAT fif, int flags, FIBITMAP *dib) {
	if (!dib || ((flags & (FIF_LOAD_DISPLAY_ICC | FIF_LOAD_NOPIXELS)) != FIF_LOAD_DISPLAY_ICC) || !FreeImage_HasPixels(dib)) {
		return dib;
	}
	// raw sensor data holds no colors yet
	if ((fif == FIF_RAW) && ((flags & RAW_UNPROCESSED) == RAW_UNPROCESSED)) {
		return dib;
	}
	try {
		const std::shared_ptr<const DisplayState> display = GetDisplayCache().Current();
		FIBITMAP *replacement = NULL;
		if (!ToDisplay(*display, dib, &replacement)) {
			FreeImage_Unload(dib);
			return NULL;
		}
		if (replacement) {
			// conversions leave the thumbnail behind
			FreeImage_SetThumbnail(replacement, FreeImage_GetThumbnail(dib));
			FreeImage_Unload(dib);
			dib = replacement;
		}
		FIBITMAP *thumbnail = FreeImage_GetThumbnail(dib);
		if (thumbnail) {
			FIBITMAP *converted = NULL;
			if (!ToDisplay(*display, thumbnail, &converted)) {
				FreeImage_SetThumbnail(dib, NULL);
			} else if (converted) {
				FreeImage_SetThumbnail(dib, converted);
				FreeImage_Unload(converted);
			}
		}
		return dib;
	} catch (std::bad_alloc &) {
		FreeImage_OutputMessageProc(fif, FI_MSG_ERROR_MEMORY);
		FreeImage_Unload(dib);
		return NULL;
	}
}
