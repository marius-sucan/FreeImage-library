// dib in the display's colors, in place or as a replacement; false when a needed replacement could not be made
static bool
ToDisplay(const DisplayState &display, FIBITMAP *dib, FIBITMAP **replacement) {
	*replacement = NULL;
	switch (FreeImage_GetImageType(dib)) {
		case FIT_BITMAP:
		case FIT_UINT16:
		case FIT_RGB16:
		case FIT_RGBA16:
			break;
		default:
			// float images hold scene light for the tone mappers; the other types hold no colors
			return true;
	}
	Pixels px;
	if (AnalysePixels(dib, px)) {
		return true;
	}
	const bool grey = (px.model == MODEL_GRAY);
	const std::vector<BYTE> &target = grey ? display.grey : display.rgb;
	// CMYK becomes RGB; 555/565 cannot hold the display's colors
	const bool convert = (px.layout == LAYOUT_CMYK8) || (px.layout == LAYOUT_CMYK16) || (px.layout == LAYOUT_555) || (px.layout == LAYOUT_565);
	if (target.empty()) {
		return !convert;
	}
	// a profile sRGB or grey in all but name converts as FreeImage's: on an sRGB display, not at all
	const FIICCPROFILE *icc = FreeImage_GetICCProfile(dib);
	const bool twin = icc->data && (px.model != MODEL_CMYK) && GetTwinCache().IsTwin(icc->data, (DWORD)icc->size);

	// an embedded profile that cannot be linked is left out the second time
	for (int attempt = 0; attempt < 2; attempt++) {
		ColorConverter converter(display.flags);
		converter.UseCache(&display.transforms);
		if (attempt || twin) {
			converter.IgnoreEmbedded();
		}
		if (converter.SetSource(dib) && converter.SetDestination(&target[0], (DWORD)target.size(), grey ? MODEL_GRAY : MODEL_RGB, MODEL_NONE)) {
			if (convert) {
				*replacement = converter.Convert();
				if (*replacement) {
					return true;
				}
			} else if (converter.Apply()) {
				return true;
			}
		}
		if (!converter.EmbeddedSource()) {
			break;
		}
	}
	// a failed in-place conversion leaves the image as it was loaded
	return !convert;
}

