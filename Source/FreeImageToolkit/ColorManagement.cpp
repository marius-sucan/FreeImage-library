// the pixel format of a new image in the destination model: same precision, alpha kept when it can be
static Layout
OutputLayout(const Pixels &px, Model model) {
	switch (model) {
		case MODEL_RGB:
			if (px.depth == 8) return px.alpha ? LAYOUT_RGBA8 : LAYOUT_RGB8;
			if (px.depth == 16) return px.alpha ? LAYOUT_RGBA16 : LAYOUT_RGB16;
			return px.alpha ? LAYOUT_RGBAF : LAYOUT_RGBF;
		case MODEL_GRAY:
			// a transparent palette keeps its transparency table
			if (px.depth == 8) return ((px.layout == LAYOUT_INDEXED) && px.alpha) ? LAYOUT_INDEXED : LAYOUT_GRAY8;
			if (px.depth == 16) return LAYOUT_GRAY16;
			return LAYOUT_GRAYF;
		case MODEL_CMYK:
			return (px.depth == 8) ? LAYOUT_CMYK8 : LAYOUT_CMYK16;
		default:
			return LAYOUT_NONE;
	}
}

// the pixel format an in-place conversion leaves, or LAYOUT_NONE
static Layout
InPlaceLayout(const Pixels &px, Model model) {
	switch (px.layout) {
		case LAYOUT_INDEXED:
			return (model == MODEL_CMYK) ? LAYOUT_NONE : LAYOUT_INDEXED;
		case LAYOUT_GRAY8:
			if (model == MODEL_GRAY) return LAYOUT_GRAY8;
			return (model == MODEL_RGB) ? LAYOUT_INDEXED : LAYOUT_NONE;
		case LAYOUT_RGB8:
		case LAYOUT_RGBA8:
		case LAYOUT_RGB16:
		case LAYOUT_RGBA16:
		case LAYOUT_RGBF:
		case LAYOUT_RGBAF:
			return (model == MODEL_RGB) ? px.layout : LAYOUT_NONE;
		case LAYOUT_GRAY16:
		case LAYOUT_GRAYF:
			return (model == MODEL_GRAY) ? px.layout : LAYOUT_NONE;
		case LAYOUT_CMYK8:
			if (model == MODEL_CMYK) return LAYOUT_CMYK8;
			return (model == MODEL_RGB) ? LAYOUT_RGBA8 : LAYOUT_NONE;
		case LAYOUT_CMYK16:
			if (model == MODEL_CMYK) return LAYOUT_CMYK16;
			return (model == MODEL_RGB) ? LAYOUT_RGBA16 : LAYOUT_NONE;
		default:
			return LAYOUT_NONE;
	}
}

