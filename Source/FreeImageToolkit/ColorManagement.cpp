static bool
SetDescription(cmsHPROFILE profile, const char *text) {
	cmsMLU *mlu = cmsMLUalloc(cmsGetProfileContextID(profile), 1);
	const bool done = mlu && cmsMLUsetASCII(mlu, "en", "US", text) && cmsWriteTag(profile, cmsSigProfileDescriptionTag, mlu);
	if (mlu) {
		cmsMLUfree(mlu);
	}
	return done;
}

static cmsHPROFILE
CreateBuiltInProfile(cmsContext context, int which) {
	static const cmsCIExyY D65 = { 0.3127, 0.3290, 1.0 };
	static const cmsCIExyY D50 = { 0.3457, 0.3585, 1.0 };
	static const cmsCIExyYTRIPLE SRGB = { { 0.6400, 0.3300, 1.0 }, { 0.3000, 0.6000, 1.0 }, { 0.1500, 0.0600, 1.0 } };
	static const cmsCIExyYTRIPLE ADOBE = { { 0.6400, 0.3300, 1.0 }, { 0.2100, 0.7100, 1.0 }, { 0.1500, 0.0600, 1.0 } };
	static const cmsCIExyYTRIPLE P3 = { { 0.6800, 0.3200, 1.0 }, { 0.2650, 0.6900, 1.0 }, { 0.1500, 0.0600, 1.0 } };
	static const cmsCIExyYTRIPLE ROMM = { { 0.7347, 0.2653, 1.0 }, { 0.1596, 0.8404, 1.0 }, { 0.0366, 0.0001, 1.0 } };
	static const cmsFloat64Number SRGB_CURVE[5] = { 2.4, 1.0 / 1.055, 0.055 / 1.055, 1.0 / 12.92, 0.04045 };

	const cmsCIExyY *white = &D65;
	const cmsCIExyYTRIPLE *primaries = &SRGB;
	cmsToneCurve *curve = NULL;
	const char *name = NULL;

	switch (which) {
		case FICMS_PROFILE_SRGB:
			curve = cmsBuildParametricToneCurve(context, 4, SRGB_CURVE);
			name = "sRGB (FreeImage)";
			break;
		case FICMS_PROFILE_LINEAR_SRGB:
			curve = cmsBuildGamma(context, 1.0);
			name = "Linear sRGB (FreeImage)";
			break;
		case FICMS_PROFILE_GRAY:
			curve = cmsBuildParametricToneCurve(context, 4, SRGB_CURVE);
			name = "Gray, sRGB tone curve (FreeImage)";
			break;
		case FICMS_PROFILE_LINEAR_GRAY:
			curve = cmsBuildGamma(context, 1.0);
			name = "Linear gray (FreeImage)";
			break;
		case FICMS_PROFILE_ADOBE_RGB:
			curve = cmsBuildGamma(context, 563.0 / 256.0);
			primaries = &ADOBE;
			name = "Adobe RGB (1998) compatible (FreeImage)";
			break;
		case FICMS_PROFILE_DISPLAY_P3:
			curve = cmsBuildParametricToneCurve(context, 4, SRGB_CURVE);
			primaries = &P3;
			name = "Display P3 (FreeImage)";
			break;
		case FICMS_PROFILE_PROPHOTO_RGB:
			curve = cmsBuildGamma(context, 1.8);
			white = &D50;
			primaries = &ROMM;
			name = "ProPhoto RGB (FreeImage)";
			break;
		default:
			return NULL;
	}
	if (!curve) {
		return NULL;
	}

	cmsHPROFILE profile = NULL;
	if ((which == FICMS_PROFILE_GRAY) || (which == FICMS_PROFILE_LINEAR_GRAY)) {
		profile = cmsCreateGrayProfileTHR(context, cmsD50_xyY(), curve);
	} else {
		cmsToneCurve *curves[3] = { curve, curve, curve };
		profile = cmsCreateRGBProfileTHR(context, white, primaries, curves);
	}
	cmsFreeToneCurve(curve);

	if (profile && !SetDescription(profile, name)) {
		cmsCloseProfile(profile);
		profile = NULL;
	}
	return profile;
}

static BYTE *
SaveBuiltInProfile(cmsHPROFILE profile, DWORD *size) {
	cmsUInt32Number length = 0;
	if (!cmsSaveProfileToMem(profile, NULL, &length) || (length < 128)) {
		return NULL;
	}
	BYTE *data = (BYTE*)malloc(length);
	if (data && cmsSaveProfileToMem(profile, data, &length)) {
		// a fixed creation date and no primary platform: the same bytes on every run and system
		static const BYTE DATE[12] = { 0x07, 0xEA, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };
		memcpy(data + 24, DATE, sizeof(DATE));
		memset(data + 40, 0, 4);
		*size = length;
		return data;
	}
	free(data);
	return NULL;
}

// created once, kept until the process ends
struct BuiltInProfiles {
	BYTE *data[ICC_BUILTIN_COUNT];
	DWORD size[ICC_BUILTIN_COUNT];

	BuiltInProfiles() {
		cmsContext context = cmsCreateContext(NULL, NULL);
		for (int i = 0; i < ICC_BUILTIN_COUNT; i++) {
			data[i] = NULL;
			size[i] = 0;
			cmsHPROFILE profile = context ? CreateBuiltInProfile(context, i) : NULL;
			if (profile) {
				data[i] = SaveBuiltInProfile(profile, &size[i]);
				cmsCloseProfile(profile);
			}
		}
		if (context) {
			cmsDeleteContext(context);
		}
	}
};

