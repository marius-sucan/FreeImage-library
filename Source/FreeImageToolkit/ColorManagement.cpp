// as ConvertCMYKtoRGBA(): R = (1 - C)(1 - K), 8-bit output in FreeImage's color order
static void
DeviceCMYKToRGB8(const BYTE *src, BYTE *dst, unsigned width) {
	for (unsigned x = 0; x < width; x++) {
		const unsigned K = 255 - src[3];
		dst[FI_RGBA_RED]	= (BYTE)(((255 - src[0]) * K) / 255);
		dst[FI_RGBA_GREEN]	= (BYTE)(((255 - src[1]) * K) / 255);
		dst[FI_RGBA_BLUE]	= (BYTE)(((255 - src[2]) * K) / 255);
		src += 4;
		dst += 3;
	}
}

static void
DeviceCMYKToRGB16(const WORD *src, WORD *dst, unsigned width) {
	for (unsigned x = 0; x < width; x++) {
		const unsigned K = 65535 - src[3];
		dst[0] = (WORD)(((65535 - src[0]) * K) / 65535);
		dst[1] = (WORD)(((65535 - src[1]) * K) / 65535);
		dst[2] = (WORD)(((65535 - src[2]) * K) / 65535);
		src += 4;
		dst += 3;
	}
}

// full black generation; the exact inverse of DeviceCMYKToRGB*
template <class T> static void
RGBToDeviceCMYK(const T *src, unsigned step, bool grey, unsigned r, unsigned g, unsigned b, T *dst, unsigned width) {
	const unsigned MAX_VAL = (sizeof(T) == 1) ? 255 : 65535;
	for (unsigned x = 0; x < width; x++) {
		if (grey) {
			dst[0] = dst[1] = dst[2] = 0;
			dst[3] = (T)(MAX_VAL - src[0]);
		} else {
			const unsigned R = src[r], G = src[g], B = src[b];
			const unsigned M = MAX(R, MAX(G, B));
			if (M == 0) {
				dst[0] = dst[1] = dst[2] = 0;
				dst[3] = (T)MAX_VAL;
			} else {
				dst[0] = (T)(MAX_VAL - (MAX_VAL * R + M - 1) / M);
				dst[1] = (T)(MAX_VAL - (MAX_VAL * G + M - 1) / M);
				dst[2] = (T)(MAX_VAL - (MAX_VAL * B + M - 1) / M);
				dst[3] = (T)(MAX_VAL - M);
			}
		}
		src += step;
		dst += 4;
	}
}

static void
PackOpaque8(const BYTE *rgb, BYTE *rgba, unsigned width) {
	for (unsigned x = 0; x < width; x++) {
		rgba[0] = rgb[0];
		rgba[1] = rgb[1];
		rgba[2] = rgb[2];
		rgba[3] = 0xFF;
		rgb += 3;
		rgba += 4;
	}
}

